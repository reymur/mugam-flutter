import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

import 'support/source_text.dart';

// Проход по исходникам — третье средство из разбора «комментарий защищает
// строку, а не класс» (AUDIT_TODO.md). Оно ловит ровно то, чего не ловят
// ни тип, ни обычный тест: ДОПИСЫВАНИЕ нового кода мимо правила. Тот, кто
// заводит третий путь удаления участника, в `chat_departure.dart` не
// смотрит и комментария там не увидит — увидит красный тест.
//
// Здесь же место будущему проходу по цепочкам `.where(` (запрет «форма
// запроса обязана доказывать правило чтения», тот же разбор).

const _service = 'lib/firebase/firestore_service.dart';
const _eventForm = 'lib/features/agreements/screens/agreements_screen.dart';

void main() {
  late List<String> lines;
  late String source;

  setUpAll(() {
    source = readCode(_service);
    lines = source.split('\n');
  });

  group('удаление участника идёт только через chatAfterDeparture', () {
    test('никто не вычёркивает uid из members через arrayRemove', () {
      // Сокращение `members` — это и есть уход из чата, а уход обязан
      // снимать вместе с членством и отметку присутствия. `arrayRemove`
      // по этому полю снимает членство В ОБХОД правила и молча оставляет
      // человека в `activeUsers` — ровно та дыра, что была в
      // removeGroupMember до 04.08.
      final offenders = <String>[];
      // КАНАРЕЙКА ПО КАЖДОЙ ПОЛОВИНЕ УСЛОВИЯ, а не по строке целиком
      // (I31). Проверка утверждает ОТСУТСТВИЕ, и ослепнуть она может
      // ПОЛОВИНОЙ: достаточно, чтобы перестало находиться одно из двух
      // слов — переименовали поле, сменили кавычки, разбор съел строку —
      // и `&&` даст пусто при живом втором слове. Один общий счёт
      // «нашлось хоть что-то» этого не поймал бы: он остался бы
      // ненулевым за счёт уцелевшей половины. Поэтому считаются обе.
      var withMembers = 0;
      var withArrayRemove = 0;
      for (var i = 0; i < lines.length; i++) {
        final l = lines[i];
        if (l.contains("'members'")) withMembers += 1;
        if (l.contains('arrayRemove')) withArrayRemove += 1;
        if (l.contains("'members'") && l.contains('arrayRemove')) {
          offenders.add('$_service:${i + 1}: ${l.trim()}');
        }
      }
      expect(
        withMembers,
        greaterThan(0),
        reason: 'в $_service не нашлось ни одной строки с `\'members\'` — '
            'поле переименовано либо разбор его больше не видит. Пустой '
            'список нарушителей ниже тогда ничего не доказывает.',
      );
      expect(
        withArrayRemove,
        greaterThan(0),
        reason: 'в $_service не нашлось ни одного `arrayRemove` — служба '
            'переписана целиком либо разбор ослеп. Проверка ниже в этом '
            'случае зелена без единого прочитанного совпадения.',
      );
      expect(
        offenders,
        isEmpty,
        reason: 'Участник вычёркивается из members мимо chatAfterDeparture '
            '(lib/core/chat/chat_departure.dart). Считать оставшиеся списки '
            'этим правилом и записывать их целиком, вместе с activeUsers:\n'
            '${offenders.join('\n')}',
      );
    });

    test('members и activeUsers пишутся правилом ВМЕСТЕ, а не порознь', () {
      // Пара, а не два отдельных числа: путь ухода, который позовёт
      // правило и запишет из него только members, забыв activeUsers,
      // воспроизведёт исходный дефект при живом правиле.
      final calls = 'chatAfterDeparture('.allMatches(source).length;
      final membersWrites = "'members': after.members".allMatches(source).length;
      final activeWrites =
          "'activeUsers': after.activeUsers".allMatches(source).length;

      // I9 В ЧИСТОМ ВИДЕ — и лечится он здесь НЕ соседкой. Оба сравнения
      // ниже сверяют РАВЕНСТВО счётчиков, а `0 == 0` истинно: сломайся
      // разбор (опечатка в искомой строке, переименование поля, снятые
      // кавычки), все три счёта стали бы нулями, и сторож сказал бы «пути
      // ухода сходятся», не посмотрев ни на один.
      //
      // Разница с остальными вердиктами точная: те требуют, чтобы разбор
      // ЧТО-ТО НАШЁЛ, а эти два довольны тем, что не нашли ничего. Поэтому
      // строка «нашлось хоть что-то» их не спасает — нужен нижний порог у
      // КАЖДОГО счёта по отдельности, до сравнения.
      for (final e in {
        'chatAfterDeparture(': calls,
        "'members': after.members": membersWrites,
        "'activeUsers': after.activeUsers": activeWrites,
      }.entries) {
        expect(
          e.value,
          greaterThan(0),
          reason: 'В ${_service} не найдено ни одного «${e.key}». Либо путь '
              'ухода переписан целиком, либо разбор перестал его видеть — '
              'по зелёному прогону второе неотличимо от первого (I13).',
        );
      }

      expect(
        membersWrites,
        activeWrites,
        reason: 'Путь ухода пишет members и activeUsers порознь: '
            'members $membersWrites раз, activeUsers $activeWrites раз. '
            'Отметка присутствия обязана уходить вместе с членством.',
      );
      expect(
        calls,
        membersWrites,
        reason: 'Вызовов chatAfterDeparture $calls, а записей его результата '
            '$membersWrites. Либо правило зовут и не используют, либо путь '
            'ухода дописан мимо него.',
      );
    });
  });

  group('снятие участника мероприятия идёт одной записью', () {
    late String form;

    setUpAll(() => form = readCode(_eventForm));

    test('состав не сокращают мимо _applyParticipantSelection', () {
      // Тот же класс, что и уход из чата: два пути к одной операции —
      // диалог выбора и крестик на фишке. `_explicitlyRemoved` без
      // серверного правила за спиной, поэтому путь, сокративший состав
      // сам, не даёт некрасивого отказа — он молча даёт НЕВЕРНЫЙ исход:
      // перенос из конфликта возвращает человека обратно (N35).
      const forbidden = [
        '_selectedParticipantUids.remove(',
        '_selectedParticipantUids.removeWhere(',
        '_selectedParticipantUids.clear(',
      ];
      final offenders = <String>[];
      final formLines = form.split('\n');
      for (var i = 0; i < formLines.length; i++) {
        for (final f in forbidden) {
          if (formLines[i].contains(f)) {
            offenders.add('$_eventForm:${i + 1}: ${formLines[i].trim()}');
          }
        }
      }
      expect(
        offenders,
        isEmpty,
        reason: 'Состав участников сокращают мимо _applyParticipantSelection '
            '— путь уберёт человека, но не запомнит, что его убрали руками, '
            'и перенос из конфликтующего мероприятия вернёт его обратно '
            '(N35):\n${offenders.join('\n')}',
      );
    });

    test('answersForRewrite зовётся ровно в одном месте (шаг 4)', () {
      // Карта ответов приватна в `models.dart`, и это защита СМЫСЛА, а не
      // формы: читать ответ человека надо через `answerFor`, который знает
      // про запасной путь у документов без карты, про ключи вне состава и
      // про то, что отсутствие ключа — «не спрашивали», а не «ждём».
      //
      // `answersForRewrite` — узкий вход для того, кто карту ПЕРЕЗАПИСЫВАЕТ:
      // правка состава обязана перенести уже данные ответы. Появись у него
      // второй вызов — и приватность поля перестанет что-либо значить:
      // читать сырьё станет так же легко, как через геттер.
      //
      // Считаются ВЫЗОВЫ со скобкой, а не упоминания имени: комментарий и
      // док-строка о нём есть и должны быть (I12).
      final all = <String>[];
      for (final path in const [
        'lib/features/agreements/screens/agreements_screen.dart',
        'lib/firebase/firestore_service.dart',
        'lib/features/day/screens/day_screen.dart',
      ]) {
        final lines = readCode(path).split('\n');
        for (var i = 0; i < lines.length; i++) {
          final l = lines[i];
          if (l.trimLeft().startsWith('//')) continue;
          if (l.contains('answersForRewrite(')) all.add('$path:${i + 1}');
        }
      }
      expect(
        all.length,
        1,
        reason: 'Сырая карта ответов берётся не в одном месте — значит её '
            'начали читать мимо правила `answerFor`. Места: ${all.join(", ")}',
      );
    });

    test('_explicitlyRemoved пополняется ровно в одном месте', () {
      // Признак «убрал руками» ставит та же запись, что меняет состав.
      // Разойдись они — появится путь, который состав сократил, а признак
      // не поставил, и это ровно исходный N35.
      final marks = '_explicitlyRemoved.add('.allMatches(form).length;
      expect(
        marks,
        1,
        reason: '_explicitlyRemoved пополняется $marks раз(а). Ожидается '
            'ровно одно место — _applyParticipantSelection. Новый путь '
            'снятия участника обязан идти через него, а не повторять '
            'учёт у себя.',
      );
    });
  });

  group('у операций, чей автор выводится, дорога должна быть одна', () {
    test('у правки предложения дорог больше НЕТ — ждём НОЛЬ', () {
      // Сервер называет автором правки предложения ИНИЦИАТОРА, и
      // подкреплено это не правилом, а тем, что кнопку «Tarix dəyiş»
      // видит только он: `firestore.rules` разрешает писать event*
      // любому участнику чата. Пока дорога одна, вывод верен; появится
      // вторая — уведомление поедет не тому и не про того, и молча.
      //
      // Поиск по вызовам, сделанный однажды, — это память, а не защита.
      // Защита — вот она: второй вызов не пройдёт мимо, и тот, кто его
      // добавит, прочтёт этот текст.
      // ОБНОВЛЕНО 14.08: ДОРОГ БОЛЬШЕ НЕ ОДНА, А НОЛЬ.
      //
      // Правка отправленного предложения снята вместе со старым листом:
      // по новой схеме её нет как хода — инициатору менять `dates`
      // запрещено правилом, иначе отметки под старые дни молча означали бы
      // согласие на новые. Передумал — отправляет новое предложение.
      //
      // Сторож не снят, а ПЕРЕВЁРНУТ, и это важнее его прежней редакции:
      // раньше он держал единственность дороги, теперь — её отсутствие.
      // Вернётся вызов — вернётся и вывод автора на сервере, ничем, кроме
      // единственности, не подкреплённый.
      final screen =
          readCode('lib/features/chat/screens/chat_screen.dart');
      final calls = 'saveChatEventDate('.allMatches(screen).length;
      expect(
        calls,
        0,
        reason: 'Вызовов saveChatEventDate: $calls, ожидалось ноль. Правка '
            'отправленного предложения снята 14.08 вместе со старым листом. '
            'Вернуть её нельзя молча: сервер выводил её автора из того, '
            'самой единственности, не подкреплено. Появилась вторая — '
            'либо закрыть автора правилом (приём namesOnlySelf в '
            'firestore.rules), либо писать автора в документ явно.',
      );
    });
  });

  // ПУНКТ 6 (`docs/plan.md`): ПРЕДЛОЖЕНИЕ РАБОТЫ СОЗДАЁТСЯ ОДНИМ КОДОМ.
  //
  // Входов четыре — чат, карточка человека, день в календаре (два экрана),
  // главный, — и все зовут `proposeJobOffer`. Проверяется не стиль, а
  // класс: «предложение создано мимо общего кода». Он выражается
  // сколькими угодно написаниями, поэтому счёта четыре, а не один, и
  // каждый закрывает свою форму обхода.
  //
  // ЧЕГО ЭТОТ СТОРОЖ НЕ ЛОВИТ — здесь, а не отдельным разделом (правило
  // проекта: сторож без границ читается шире, чем есть):
  //   1. имя поля, собранное из кусков или взятое переменной
  //      (`'jobOffer' + 'By'`, `final k = 'jobOfferBy'`);
  //   2. запись из `functions/` — сервер сюда не смотрит вовсе;
  //   3. отдельную коллекцию под предложения, если её однажды заведут:
  //      тогда ключа `jobOfferBy` может не быть ни у кого, и все четыре
  //      счёта останутся зелёными, проверяя пустоту;
  //   4. вход, который зовёт общую точку, но подсовывает свои подписи или
  //      свой лист поверх неё.
  group('предложение работы создаётся одним кодом (пункт 6)', () {
    const entry = 'lib/features/job_offer/job_offer_entry.dart';
    const service = 'lib/firebase/firestore_service.dart';
    // Хранилище предложений — ПИСАТЕЛЬ, как и сервис: `createOffer` в нём
    // объявляется, а не зовётся со стороны. Считать объявление обходом
    // общей точки значило бы сторожить существование метода, а не дорогу
    // к нему — ровно та же поправка, что сделана сторожу «б» для файла
    // самого листа.
    const repository = 'lib/core/job_offer/job_offer_repository.dart';

    // Все файлы `lib/`, кроме сервиса и самой точки вызова: это и есть
    // «остальной проект», которому создавать предложение запрещено.
    List<String> otherLibFiles() => Directory('lib')
        .listSync(recursive: true)
        .whereType<File>()
        .map((f) => f.path)
        .where((p) => p.endsWith('.dart'))
        .where((p) => p != entry && p != service && p != repository)
        .toList();

    test('а: предложение создают только из точки вызова', () {
      final offenders = <String>[];
      for (final path in otherLibFiles()) {
        // Обе записи разом: прежняя (`setJobOffer`, сегодня без
        // вызывающих) и нынешняя (`createOffer` в подколлекцию). Прежняя
        // оставлена в счёте намеренно — пока она жива в сервисе, вернуть
        // её вызов из любого экрана ничто не мешает.
        final n = 'setJobOffer('.allMatches(readCode(path)).length +
            'createOffer('.allMatches(readCode(path)).length;
        if (n > 0) offenders.add('$path ($n)');
      }
      expect(
        offenders,
        isEmpty,
        reason: 'Предложение создаётся мимо общей точки: '
            '${offenders.join(', ')}. Вход обязан звать proposeJobOffer и '
            'передавать только то, что знает, — человека и/или день.',
      );
    });

    // Разбор с ГРАНИЦЕЙ СЛЕВА, а не подстрокой. Первая редакция считала
    // голое `JobOfferDateSheet(` и нашла в экране чата ТРИ штуки вместо
    // одной: подстрока сидит внутри имени `_openJobOfferDateSheet(`.
    // Сторож был бы красным на здоровом коде — то есть «нашёл» ровно то,
    // что сам же и породил.
    final sheetCall = RegExp(r'(?<![A-Za-z_])JobOfferDateSheet\(');
    final daysSheetCall = RegExp(r'(?<![A-Za-z_])JobOfferDaysSheet\(');

    // ОБНОВЛЁН 14.08 ПОД СНЯТИЕ СТАРОГО ЛИСТА.
    //
    // Прежде здесь ожидалась ровно одна законная вторая дорога — экран
    // чата, строивший `JobOfferDateSheet` для ПРАВКИ. Правка снята вместе
    // с листом, значит законных мест не осталось ни одного: старого листа
    // нет в проекте вовсе.
    //
    // А новый лист строится ровно в одном месте — в точке вызова, и это
    // проверяется отдельно (соседка «г» ниже). Здесь остаётся сторож на
    // ВОЗВРАТ СНЯТОГО: `JobOfferDateSheet(` не должен появиться нигде.
    test('б: снятый лист предложения не строится нигде', () {
      final places = <String>[];
      for (final path in otherLibFiles()) {
        final n = sheetCall.allMatches(readCode(path)).length;
        if (n > 0) places.add('$path ($n)');
      }
      expect(
        places,
        isEmpty,
        reason: 'Снятый лист предложения снова строится. Создание идёт '
            'через proposeJobOffer новым листом; правки предложения как '
            'её единственность опирается вывод автора на сервере.',
      );
    });

    // САМЫЙ ВАЖНЫЙ ИЗ ЧЕТЫРЁХ, и вот почему: счёт вызовов `setJobOffer(`
    // не увидит того, кто напишет обновление документа руками. Одно
    // намерение, две формы записи — N84 дословно.
    test('в: ключ jobOfferBy пишут только в сервисе', () {
      final offenders = <String>[];
      for (final path in otherLibFiles()) {
        // Считается ФОРМА ЗАПИСИ — ключ с двоеточием, как в литерале
        // карты, — а не всякое упоминание. Первая редакция считала голое
        // `'jobOfferBy'` и нашла три места, все три ЧТЕНИЯ
        // (`meta?['jobOfferBy']`): читать поле раунда законно всем, кто
        // его показывает, запрещено его ПИСАТЬ мимо сервиса. Сторож,
        // который этого не различает, запрещает читать — и его снимут
        // первым же человеком, которому он помешает.
        //
        // readCode сводит кавычки к одинарным — двойные тем же ключом
        // сюда попадают сами.
        final n = "'jobOfferBy':".allMatches(readCode(path)).length;
        if (n > 0) offenders.add('$path ($n)');
      }
      expect(
        offenders,
        isEmpty,
        reason: 'Ключ раунда пишется в обход setJobOffer: '
            '${offenders.join(', ')}. Счёт вызовов такую запись не видит — '
            'это другая ФОРМА того же намерения (N84).',
      );
    });

    // I13: без соседки «нашлось хоть что-то» три счёта выше зелены и на
    // переименованном методе, и на удалённой фиче — проверяя пустоту.
    test('г: то, что сторожится, вообще существует', () {
      final entryCode = readCode(entry);
      final serviceCode = readCode(service);
      // ОБНОВЛЕНО 14.08 ВМЕСТЕ С ПЕРЕВОДОМ ПЯТИ ВХОДОВ НА НОВЫЙ ЛИСТ.
      //
      // Прежде здесь стояло `setJobOffer(` и `JobOfferDateSheet(` — по
      // одному в точке вызова. Обоих там больше нет: создание уехало в
      // подколлекцию (`JobOfferRepository.createOffer`), лист сменился на
      // `JobOfferDaysSheet`. Соседка ПОЙМАЛА ЭТОТ ПЕРЕХОД в первый же
      // прогон и была права: сторожа «а» и «б» после перевода сторожили
      // пустоту.
      //
      // `setJobOffer` при этом остался в сервисе БЕЗ ЕДИНОГО ВЫЗЫВАЮЩЕГО
      // (`grep -rn "setJobOffer(" lib` — только объявление, 14.08). Он не
      // снят намеренно: снимать его надо вместе с четырнадцатью полями
      // раунда на документе чата, которые держат существующие предложения,
      // и это отдельная работа.
      expect('createOffer('.allMatches(entryCode).length, 1,
          reason: 'В точке вызова нет создания предложения — сторож «а» '
              'проверяет пустоту.');
      expect(daysSheetCall.allMatches(entryCode).length, 1,
          reason: 'Точка вызова больше не строит лист — сторож «б» '
              'проверяет пустоту.');
      expect("'jobOfferBy':".allMatches(serviceCode).length, greaterThan(0),
