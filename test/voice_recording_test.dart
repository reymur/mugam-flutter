import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:mugam_flutter/core/audio/voice_recording_session.dart';

// РАБОТА 2 — ОБЩАЯ ЗАПИСЬ ГОЛОСА, вынесенная 13.08 из состояния экрана чата.
//
// До выноса запись не была покрыта НИЧЕМ: `grep -rln "record\|voice\|audio\|
// waveform" test/` на 13.08 не давал ни одного файла. Это не упрёк прежнему
// коду — покрыть его было нечем: разбор громкости жил приватным методом
// внутри `_ChatScreenState`, а поднять экран чата в тесте значит поднять
// Firebase. Вынос сделал разбор доступным, и первое, чем он оплачивается, —
// вот эти проверки.
//
// ЧЕГО ЭТОТ НАБОР НЕ ЛОВИТ, сказано сразу (границы пишутся вместе со
// сторожем):
//   * настоящую запись — разрешение, отложенный старт, остановку,
//     отбрасывание случайного тычка. Всё это упирается в native-запись и
//     проверяется только на телефоне;
//   * порядок «разрешение → показ → отложенный старт». Он держится на
//     `onArmed`, и сломать его можно, не тронув ни одной строки здесь;
//   * то, что три места зовут сеанс одинаково. Сегодня зовущий один.

void main() {
  group('downsampleWaveform — разбор громкости', () {
    test('пустой вход даёт ровно targetCount нулей, а не пустой список', () {
      // Волна уходит в документ сообщения и показывается по сохранённому
      // числу столбиков. Пустой список на этом месте — не «тихая запись», а
      // отсутствие волны, и показ поехал бы.
      final bars = downsampleWaveform(const [], 40);
      expect(bars.length, 40);
      expect(bars.every((b) => b == 0), isTrue);
    });

    test('края шкалы: -50 dB это 0, -5 dB это 100', () {
      expect(downsampleWaveform(List.filled(40, -50.0), 40).first, 0);
      expect(downsampleWaveform(List.filled(40, -5.0), 40).first, 100);
    });

    test('за краями шкалы значения прижимаются, а не уходят за 0..100', () {
      // Микрофон отдаёт и -160 (тишина), и значения выше -5 у самого уха.
      final quiet = downsampleWaveform(List.filled(40, -160.0), 40);
      final loud = downsampleWaveform(List.filled(40, 0.0), 40);
      expect(quiet.every((b) => b == 0), isTrue);
      expect(loud.every((b) => b == 100), isTrue);
    });

    test('в столбике берётся ПИК, а не среднее', () {
      // Ради этого разбор и написан так: громкий всплеск обязан остаться
      // виден, а не сгладиться соседями. Среднее по этому входу дало бы
      // заметно меньше половины.
      final bars = downsampleWaveform(
        [-50.0, -50.0, -50.0, -5.0],
        1,
      );
      expect(bars.single, 100);
    });

    test('число столбиков не зависит от длины записи', () {
      expect(downsampleWaveform(List.filled(3, -20.0), 40).length, 40);
      expect(downsampleWaveform(List.filled(4000, -20.0), 40).length, 40);
    });

    test('сеанс объявляет то же число столбиков, что писалось до выноса', () {
      // 40 стояло в экране чата и уехало сюда константой. Разойдись оно —
      // старые сообщения показывались бы одной длины, новые другой.
      expect(VoiceRecordingSession.waveformBars, 40);
    });
  });

  // Ради этого работа и делалась: «написано в одном месте, нужно в трёх».
  // Сторож утверждает НАЛИЧИЕ ровно одного объявления, поэтому сам себе
  // канарейка (I31): ослепни разбор — он найдёт ноль, ноль не равен единице,
  // тест покраснеет. Молча позеленеть он не умеет.
  //
  // ЧЕГО ОН НЕ ЛОВИТ И ГДЕ ВРЁТ — вскрыто проверкой возвратом 13.08:
  //   * он сравнивает ТЕКСТ, а не код. Комментарий в любом файле `lib`,
  //     где написано `AudioRecorder(`, покраснеет наравне с настоящей
  //     второй копией — это I12 ровно в той форме, в какой он уже ловил
  //     сторожа цветов: запрет и объяснение запрета состоят из одних слов.
  //     Поэтому объяснять эту работу надо ЗДЕСЬ, а не в `lib`;
  //   * он смотрит на заведение записи, а не на её употребление. Второе
  //     место, зовущее сеанс своими словами вместо общего пути, он
  //     пропустит целиком.
  test('запись голоса объявлена ровно в одном месте', () {
    final files = Directory('lib')
        .listSync(recursive: true)
        .whereType<File>()
        .where((f) => f.path.endsWith('.dart'))
        .toList();
    // Первое число вслух (I13): сколько файлов вообще просмотрено. Ноль
    // здесь означал бы, что обход не нашёл исходников, а не что копий нет.
    expect(
      files.length,
      greaterThan(100),
      reason: 'обход не видит исходников — считать нечего',
    );

    final owners = files
        .where((f) => f.readAsStringSync().contains('AudioRecorder('))
        .map((f) => f.path)
        .toList();

    expect(
      owners,
      ['lib/core/audio/voice_recording_session.dart'],
      reason:
          'Запись голоса заводится только в общем сеансе. Вторая '
          '`AudioRecorder(` — это четвёртая копия, ради ухода от которой '
          'работа 2 и делалась.',
    );
  });

  // ТРЕБОВАНИЕ ВЛАДЕЛЬЦА 13.08, поставленное механизмом, а не памятью:
  // сеанс записи не знает ни про чат, ни про предложение, ни про базу —
  // принимает нажатие и отдаёт файл наружу. Без сторожа следующий припишет
  // туда отправку в чат «для удобства», и общий вход внутри окажется тремя
  // склеенными делами (I58).
  //
  // СУЖЕН ДО КОДА, И ЭТО НЕ ПРИДИРКА (I12). В шапке самого сеанса словами
  // объяснено, чего там быть не должно, — то есть слова «чат», «предложение»
  // и «Firestore» в файле ЕСТЬ и обязаны быть. Сторож, читающий файл
  // целиком, первым делом отказал бы объяснению самого себя. Ровно этим
  // спотыкался сторож цветов, и лечится это тем же: комментарии снимаются
  // до разбора.
  test('сеанс записи не знает ни про чат, ни про предложение, ни про базу', () {
    const path = 'lib/core/audio/voice_recording_session.dart';
    final source = File(path).readAsStringSync();
    // Снимаем комментарии: от `//` до конца строки. Строк с `//` внутри
    // литералов в этом файле нет (пути собираются через `/`), поэтому
    // разбор такой простоты здесь честен.
    final code = source
        .split('\n')
        .map((l) {
          final i = l.indexOf('//');
          return i == -1 ? l : l.substring(0, i);
        })
        .join('\n');

    // КАНАРЕЙКА (I31). Сторож утверждает ОТСУТСТВИЕ, а такое утверждение
    // ломается молча: сломайся снятие комментариев так, что от файла не
    // осталось ничего, — запрещённых слов не найдётся, и сторож позеленеет
    // именно тогда, когда ослеп. Канарейка ищет ТЕМ ЖЕ способом заведомо
    // существующее и падает на нуле.
    expect(
      code.contains('AudioRecorder('),
      isTrue,
      reason: 'разбор не видит кода — снятие комментариев съело файл',
    );

    const forbidden = <String>[
      'chatId',
      'offerId',
      'Firestore',
      'firestore',
      'sendAudioMessage',
      'messageSendController',
      'enqueue',
      'senderId',
    ];
    final found = forbidden.where(code.contains).toList();
    expect(
      found,
      isEmpty,
      reason:
          'Сеанс записи получил знание о том, КУДА уходит запись. Это и есть '
          'четвёртая копия с другой стороны: снаружи один общий вход, внутри '
          'три склеенных дела. Назначение живёт у зовущего.',
    );
  });
}
