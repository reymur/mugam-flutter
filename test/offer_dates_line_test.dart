import 'package:flutter_test/flutter_test.dart';
import 'package:mugam_flutter/core/job_offer/offer_draft.dart';

// СПИСОК ДАТ ЧЕЛОВЕЧЕСКИМИ СЛОВАМИ — `offerDatesLine`, одна форма на проект.
//
// Заведена 25.08 вместо двух: `offerSummaryLine` печатала дни без месяца,
// `offerAnchorText` — с месяцем, названным один раз по первой дате.
//
// ЧТО ЭТОТ НАБОР СТОРОЖИТ, кроме самих строк: он единственный, кто проверяет
// набор ЧЕРЕЗ ГРАНИЦУ МЕСЯЦА. Замер прода 25.08 (`runQuery` по `offers`, 19
// предложений): таких наборов **ноль из 19**. То есть на живых данных ошибка
// не проявится ни разу, и заметить её будет некому — кроме этого теста.

void main() {
  // Настоящий набор из прода: 18 дат, 14–31 августа 2026 (замер 25.08,
  // самый длинный из 19).
  List<String> august14to31() => [
    for (var d = 14; d <= 31; d++) '2026-08-${d.toString().padLeft(2, '0')}',
  ];

  group('отрезки', () {
    test('сплошной отрезок сжимается в один диапазон', () {
      expect(offerDatesLine(august14to31()), '14–31 avqust');
    });

    test('два отрезка — оба названы', () {
      expect(
        offerDatesLine([
          '2026-08-24',
          '2026-08-25',
          '2026-08-26',
          '2026-08-27',
          '2026-08-31',
        ]),
        '24–27, 31 avqust',
      );
    });

    test('одиночные дни остаются перечислением', () {
      expect(
        offerDatesLine(['2026-08-19', '2026-08-22', '2026-08-30']),
        '19, 22, 30 avqust',
      );
    });

    test('пара соседних дней — диапазон, а не перечисление', () {
      expect(offerDatesLine(['2026-08-25', '2026-08-26']), '25–26 avqust');
    });

    test('один день', () {
      expect(offerDatesLine(['2026-08-30']), '30 avqust');
    });

    // КАНАРЕЙКА НА СЖАТИЕ, И ОНА ОТДЕЛЬНАЯ ОТ ПРОВЕРОК ВЫШЕ.
    //
    // Те сверяют строку целиком и падают от любой правки — включая
    // безобидную смену тире. Эта держит **свойство, ради которого сжатие и
    // сделано**: строка ленты вмещает 43 знака (замер 25.08 по снимку с
    // трубки — 295 pt под текст, 6,84 pt на знак), а перечислением тот же
    // набор занимает 77.
    //
    // Верни кто-нибудь перечисление — проверки выше покраснеют вместе с
    // этой, но только эта скажет, ЧЕМ это плохо.
    test('самый длинный набор прода влезает в строку ленты', () {
      final line = offerDatesLine(august14to31());
      expect(
        line.length,
        lessThanOrEqualTo(20),
        reason: 'сжатие отрезков потеряно: 18 дат перечислением — 77 знаков '
            'при пределе строки 43, и хвост уедет на вторую строку либо '
            'пропадёт',
      );
      // Канарейка к канарейке: длина ноль тоже «меньше двадцати», и пустой
      // ответ прошёл бы молча.
      expect(line, isNotEmpty);
    });
  });

  group('месяц называется при смене', () {
    // ЕДИНСТВЕННАЯ ПРОВЕРКА ЭТОГО СЛУЧАЯ ВО ВСЁМ ПРОЕКТЕ: в проде таких
    // наборов ноль из 19 (замер 25.08). Прежняя редакция брала месяц по
    // первой дате и назвала бы сентябрьский день августовским.
    test('набор через границу месяца называет ОБА месяца', () {
      expect(
        offerDatesLine(['2026-08-30', '2026-09-02']),
        '30 avqust, 2 sentyabr',
      );
    });

    test('сплошная полоса через границу режется по месяцам', () {
      expect(
        offerDatesLine([
          '2026-08-30',
          '2026-08-31',
          '2026-09-01',
          '2026-09-02',
        ]),
        '30–31 avqust, 1–2 sentyabr',
      );
    });

    test('три месяца — три части', () {
      expect(
        offerDatesLine(['2026-08-31', '2026-09-15', '2026-10-01']),
        '31 avqust, 15 sentyabr, 1 oktyabr',
      );
    });
  });

  group('края', () {
    test('пустой набор — пустая строка, а не «0 gün»', () {
      expect(offerDatesLine([]), '');
    });

    test('порядок нажатий не влияет — дни идут по возрастанию', () {
      expect(
        offerDatesLine(['2026-08-31', '2026-08-14', '2026-08-15']),
        '14–15, 31 avqust',
      );
    });

    // Неразбираемое выбрасывается, а не печатается как есть: «2026-08-0X» в
    // строке для человека — мусор, а не дата. Прежде две формы решали это
    // по-разному, и расхождение снято в пользу выбрасывания.
    test('неразбираемая дата выбрасывается, остальные остаются', () {
      expect(
        offerDatesLine(['позавчера', '2026-08-25', '']),
        '25 avqust',
      );
      expect(offerDatesLine(['позавчера']), '');
    });
  });

  group('двое читателей общей формы', () {
    // Обе строки собирают ОДИН список — и потому не могут разойтись. Пока
    // форм было две, разойтись им мешало только то, что их никто не правил.
    test('строка под сеткой берёт общую форму', () {
      expect(
        offerSummaryLine(['2026-08-09', '2026-08-10', '2026-08-11']),
        '3 gün · 9–11 avqust',
      );
    });

    test('текст якоря берёт ту же', () {
      expect(
        offerAnchorText(
          dates: ['2026-08-19', '2026-08-20'],
          eventType: 'Toy',
        ),
        '2 gün: 19–20 avqust · Toy',
      );
    });

    test('обе показывают одни и те же дни', () {
      final dates = ['2026-08-24', '2026-08-25', '2026-08-31'];
      final line = offerDatesLine(dates);
      expect(offerSummaryLine(dates), contains(line));
      expect(offerAnchorText(dates: dates, eventType: 'Toy'), contains(line));
    });
  });
}
