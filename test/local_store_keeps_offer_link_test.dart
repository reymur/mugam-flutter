import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:mugam_flutter/core/store/local_message_store.dart';
import 'package:mugam_flutter/firebase/models.dart';
import 'package:shared_preferences/shared_preferences.dart';

// ССЫЛКА НА ПРЕДЛОЖЕНИЕ РАБОТЫ ДОЛЖНА ПЕРЕЖИТЬ ПАМЯТЬ ТЕЛЕФОНА.
//
// Лента берёт сообщения НЕ из Firestore напрямую, а из этого хранилища:
// пришло с сервера -> легло на диск -> прочитано обратно -> нарисовано.
// Карточку предложения лента отличает от обычного сообщения по полю
// `offerId`, и если оно теряется по дороге на диск, экран об этом не
// узнает никогда — он получит сообщение без ссылки и нарисует текст.
//
// ЧИТАЕТ ВТОРОЙ ЭКЗЕМПЛЯР ХРАНИЛИЩА, А НЕ ТОТ ЖЕ САМЫЙ, и это не
// придирка: тот же экземпляр может отдать сообщение из памяти, ни разу не
// заглянув на диск, — и круг, ради которого тест написан, не состоится.
// Второй экземпляр над теми же настройками читает именно записанное.
//
// Проверяется НАСТОЯЩИЙ путь, а не ближайшая к нему точка входа: методы
// перекладывания приватные, и звать их напрямую всё равно нечем, но
// главное — прод ходит именно так, через публичный вход.

Message _anchor() => Message(
  id: 'm-anchor',
  chatId: 'chat-1',
  senderId: 'boss',
  text: '2 gün: 19, 20 avqust · Toy',
  type: 'text',
  seq: 1,
  timestamp: Timestamp.fromDate(DateTime.utc(2026, 8, 19, 8, 29)),
  offerId: 'offer-42',
  // СОСЕДНЕЕ ПОЛЕ ДЛЯ КАНАРЕЙКИ — того же вида, что проверяемое: строка,
  // которой может не быть, и записывается она БЕЗУСЛОВНО.
  //
  // Первой канарейкой я взял имя отправителя цитаты — и она покраснела
  // вместе с проверяемым полем. Причина была не в коде, а в данных: блок
  // цитаты перекладывается только у сообщения, где задан id цитируемого,
  // а я его не задал. Канарейка проверяла поле, которое при таком
  // сообщении и не должно сохраняться, — то есть не годилась вовсе.
  //
  // ОТСЮДА ТРЕБОВАНИЕ К КАНАРЕЙКЕ, А НЕ ТОЛЬКО К ЭТОМУ ТЕСТУ: она обязана
  // быть безусловной. Поле, которое сохраняется лишь при заполненном
  // спутнике, красным не отличает поломку от неподходящих данных.
  mediaFileName: 'запись.m4a',
);

Future<LocalMessageStore> _freshStore() async {
  final prefs = await SharedPreferences.getInstance();
  final store = LocalMessageStore(prefs);
  await store.init();
  return store;
}

Future<Message> _roundTrip() async {
  SharedPreferences.setMockInitialValues({});

  final writer = await _freshStore();
  await writer.upsertManyFromFirestore(chatId: 'chat-1', reals: [_anchor()]);

  // ЗАПИСЬ ИСТОРИИ ОТЛОЖЕНА НА 400 мс, и публичного способа её дождаться
  // нет — `flushPending` сбрасывает только очередь отправки, не историю.
  // Ждём заведомо дольше задержки. Без этого ожидания читатель находит
  // пусто, и оба теста падают в одной точке — не потому, что поле
  // теряется, а потому, что записать ещё не успели.
  await Future<void>.delayed(const Duration(milliseconds: 700));

  // Новый экземпляр над теми же настройками — читает с «диска».
  final reader = await _freshStore();
  final messages = await reader.watchChat('chat-1').first;

  expect(
    messages.length,
    1,
    reason: 'сообщение вообще не доехало — круг проверять не на чем',
  );
  return messages.single;
}

void main() {
  group('память телефона не теряет полей сообщения', () {
    // КАНАРЕЙКА, И ОНА ОБЯЗАНА ОСТАВАТЬСЯ ЗЕЛЁНОЙ.
    //
    // Без неё красный на ссылке не отличить от «хранилище не работает
    // вовсе» или «сообщение не сохранилось»: оба дают ту же пустоту.
    // Поле выбрано нарочно того же вида, что и проверяемое, — строка,
    // которой может не быть, — чтобы разница между ними была ровно в
    // одном: одно в списках перекладывания есть, другого нет.
    test('соседнее поле переживает круг через память телефона', () async {
      final read = await _roundTrip();

      expect(read.mediaFileName, 'запись.m4a');
      expect(read.text, '2 gün: 19, 20 avqust · Toy');
      expect(read.type, 'text');
      expect(read.seq, 1);
    });

    test('ссылка на предложение переживает круг через память телефона', () async {
      final read = await _roundTrip();

      expect(
        read.offerId,
        'offer-42',
        reason: 'ссылка потерялась по дороге на диск — лента карточку не '
            'построит, потому что отличать якорь от обычного сообщения ей '
            'больше нечем',
      );
    });
  });
}
