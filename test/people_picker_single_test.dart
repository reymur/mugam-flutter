import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

import 'support/source_text.dart';

// ЛИСТ ВЫБОРА ЛЮДЕЙ НА ВЕЧЕР — ОДИН. Решение владельца 19.09.
//
// --- ЧТО ЭТОТ НАБОР УТВЕРЖДАЕТ, И ЧЕГО ОН НЕ УТВЕРЖДАЕТ ---
//
// **Он НЕ утверждает «лист выбора участников в приложении один».** Это было бы
// неправдой, и неправдой проверяемой: листов выбора людей в `lib` на 19.09
// ШЕСТЬ, из них многоместных четыре.
//
//   многоместные: состав вечера (`pick_people_sheet.dart`), добавление в
//   группу (`group_info_screen.dart`), создание группы
//   (`create_group_screen.dart`), кому видна история
//   (`create_status_screen.dart`);
//   одноместные: кому предложить работу (`pick_person_sheet.dart`), поиск
//   людей в списке чатов (`chats_screen.dart` — строго говоря не выбор, а
//   открытие переписки).
//
// До 19.09 многоместных было пять: пятым стоял `_ParticipantPickerDialog` в
// `agreements_screen.dart`, и он делал ровно то же дело, что
// `pick_people_sheet` — выбирал людей НА ВЕЧЕР. Сведены эти двое, и только
// они. Шапка без доли соврала бы про остальных (I39).
//
// --- ПОЧЕМУ ИЗ ДВУХ ВЫЖИЛ ИМЕННО ЭТОТ ---
//
// Не по виду и не по объёму, а по ИСТОЧНИКУ ДАННЫХ. Снятый диалог кормился
// Algolia, а индекс — снимок: `lastSeen` там отстаёт десятиминутным шагом
// (`ALGOLIA_LAST_SEEN_THROTTLE_MS`), окно свежести присутствия — 120 с, и
// `StaleClock` бьёт каждые 20 с по замершему значению. Отсюда кружок «в сети»
// в том окне гас у всех не позже чем через две минуты после открытия и больше
// не загорался. Оставшийся лист читает живой поток Firestore, и там он верен.
//
// **Врущих кружков это чинит ОДИН из четырёх, а не все** — N248: остаются
// лист добавления в группу, создание группы и поиск людей в списке чатов, все
// трое на Algolia. Сказано здесь, чтобы зелень этого набора не прочлась как
// «кружок починен везде» (I40: без знаменателя читатель достроит сам).
//
// --- ЧЕГО ЭТОТ НАБОР НЕ ЛОВИТ, НАЗВАНО СРАЗУ ---
//
// 1. ТРЕТИЙ ЛИСТ В НОВОМ ФАЙЛЕ СО СВОИМИ ИМЕНАМИ. Разбор смотрит на имена, а
//    не на смысл: напишет кто-нибудь свой `_PeoplePicker` — пройдёт насквозь.
// 2. ЧТО ЛИСТ ОТКРЫВАЕТСЯ И ЧТО-ТО ВОЗВРАЩАЕТ. Поднять его в вердикте нельзя
//    без живых `FirebaseAuth` и `musiciansProvider`; это глаза на трубке
//    (I55), а не текст.
// 3. ПОРЯДОК ВЕТВЕЙ В РАЗМЕТКЕ — на него не смотрит ни один сторож проекта
//    (I32).
// 4. ЧТО ЗОВУЩИЙ ДЕЛАЕТ С ОТВЕТОМ. Что карточка пишет сразу, а форма кладёт в
//    своё состояние, — это их собственные вердикты.

void main() {
  const screen = 'lib/features/agreements/screens/agreements_screen.dart';
  const sheet = 'lib/features/people/screens/pick_people_sheet.dart';
  const core = 'lib/features/people/widgets/person_picker_core.dart';

  late String screenCode;

  setUpAll(() => screenCode = readCode(screen));

  group('лист выбора людей на вечер — один', () {
    // УТВЕРЖДЕНИЕ НАЛИЧИЯ, значит само себе канарейка (I31): ослепни разбор —
    // совпадений станет ноль, и вердикт покраснеет, а не позеленеет.
    test('обе кнопки зовут ОДИН лист — ровно два вызова', () {
      final calls = 'pickPeopleForLineup(context)'.allMatches(screenCode).length;
      expect(
        calls,
        2,
        reason:
            'вызовов общего листа $calls вместо двух. Один — значит одна из '
            'кнопок («Öz adamlarımı çağır» или «+ Əlavə et») снова открывает '
            'что-то своё; ноль — лист написан и никем не позван; три и '
            'больше — появился третий вход, и решение 19.09 про один лист '
            'нарушено на деле при соблюдении на словах (I64)',
      );
    });

    test('лист объявлен ровно один раз и живёт в features/people', () {
      expect(File(sheet).existsSync(), isTrue,
          reason: 'лист выбора людей на вечер не найден по пути $sheet');
      final decl =
          'Future<List<String>?> pickPeopleForLineup('.allMatches(readCode(sheet)).length;
      expect(decl, 1,
          reason: 'объявлений листа $decl вместо одного');
    });

    // -----------------------------------------------------------------------
    // УТВЕРЖДЕНИЕ ОТСУТСТВИЯ — и вот ЕМУ канарейка обязательна (I31).
    //
    // Ослепший разбор даёт ноль; ноль здесь и есть искомое; значит слепота и
    // успех — один и тот же вывод. Канарейка ищет ТЕМ ЖЕ способом, тем же
    // `readCode` и по тому же файлу, заведомо существующее.
    // -----------------------------------------------------------------------
    test('КАНАРЕЙКА: тот же разбор видит содержимое экрана', () {
      // `_EventFormModal` — приватный класс ТОГО ЖЕ файла, живой и никуда не
      // девающийся: именно в нём стоит кнопка «+ Əlavə et». Ноль здесь
      // означает «разбор ослеп» (файл переехал, сменилось имя, `readCode`
      // вернул пустоту), а не «диалога нет».
      // ДВА, а не одно: виджет и его состояние
      // (`class _EventFormModalState extends ConsumerState<_EventFormModal>`).
      // Первая редакция ждала единицы и покраснела на верном — счёт отвечал
      // на соседний вопрос (I13). Число снято замером, а не выбрано.
      expect('class _EventFormModal'.allMatches(screenCode).length, 2,
          reason: 'разбор не видит заведомо существующего класса в том же '
              'файле — значит и «второго листа нет» он доказать не может');
      // Вторая канарейка, на кириллицу в этом же файле: подпись кнопки, ради
      // которой всё и делалось. Разбор по русскому тексту в этом проекте уже
      // слеп бывал (`\\w` и `\\b` на кириллице), поэтому проверяется отдельно.
      // В СЫРОМ файле подпись встречается четырежды, в коде — один раз:
      // остальные три живут в комментариях, которые `readCode` срезает. Это и
      // есть проверка, что срезание работает, а кириллица при этом не
      // теряется (в проекте разбор по русскому тексту слеп бывал дважды —
      // `\w` и `\b` на кириллице).
      expect('+ Əlavə et'.allMatches(screenCode).length, 1,
          reason: 'разбор не видит подписи кнопки — проверять ему нечего');
    });

    test('второго листа выбора на вечер в экране НЕТ', () {
      // Снятый класс — по имени. Комментарии `readCode` уже срезал, поэтому
      // запись о снятии, которая стоит на его месте и называет его имя, сюда
      // не попадает (I12: запрет и его объяснение состоят из одних слов).
      expect(screenCode.contains('_ParticipantPickerDialog'), isFalse,
          reason: 'второй лист выбора людей на вечер вернулся в код. Он '
              'кормится Algolia, а это снимок: кружок «в сети» на нём гаснет '
              'у всех через две минуты после открытия и больше не '
              'загорается (N248)');
      // И по ИСТОЧНИКУ, а не только по имени: переименованный диалог с тем же
      // нутром прошёл бы проверку выше насквозь.
      expect(screenCode.contains('UserSearchController'), isFalse,
          reason: 'экран вечеров снова ходит в Algolia за людьми. Людей на '
              'вечер берут из живого потока (`musiciansProvider`) — иначе '
              'кружок «в сети» врёт по устройству, а не по недосмотру');
    });

    // -----------------------------------------------------------------------
    // СКЛАДЫВАЕТ, А НЕ ЗАМЕНЯЕТ.
    //
    // Пропади это — «+ Əlavə et» снова станет заменой состава, и молча:
    // разница видна только тогда, когда состав был непуст, а на пустом
    // составе обе записи ведут себя одинаково.
    // -----------------------------------------------------------------------
    test('«+ Əlavə et» ПРИБАВЛЯЕТ к составу, а не заменяет его', () {
      expect(
        screenCode.contains('..._selectedParticipantUids,'),
        isTrue,
        reason: 'ответ листа кладётся в состав без прежнего состава — значит '
            '«добавить» снова стало «заменить». Подпись кнопки обещает '
            'первое',
      );
    });

    test('состав меняется ЧЕРЕЗ _applyParticipantSelection, а не мимо', () {
      // Та же болезнь, что N35, и тот же довод: за `_explicitlyRemoved` нет
      // серверного правила, поэтому путь, правящий состав сам, даёт не
      // отказ, а неверный исход — перенос из конфликта вернёт человека
      // обратно.
      expect(
        screenCode.contains('_applyParticipantSelection(merged)'),
        isTrue,
        reason: 'новый путь выбора участников правит состав мимо '
            '_applyParticipantSelection',
      );
    });

    // -----------------------------------------------------------------------
    // ФИЛЬТРЫ — В ОБЩЕЙ СЕРЕДИНЕ И ПО ЖИВЫМ ДАННЫМ.
    // -----------------------------------------------------------------------
    test('фильтры не потерялись вместе со снятым листом', () {
      final coreCode = readCode(core);
      expect(coreCode.contains('SearchFilters _filters'), isTrue,
          reason: 'фильтры уехали вместе со снятым листом. Решение владельца '
              '19.09: их переносим, а не выбрасываем');
      // МЕСТО ВЫЗОВА, А НЕ ГОЛОЕ ИМЯ. Имя лежит в файле и в комментарии, а
      // вызова там может уже не быть — сторож над сторожами ловит ровно это
      // и поймал первую редакцию строки.
      expect(coreCode.contains('where(_filters.matchesPerson)'), isTrue,
          reason: 'отбор по фильтрам не спрашивает общее правило');
    });

    test('отбор по фильтрам написан ОДИН раз', () {
      // Пять полей фильтра применяются в двух видах — запросом в индекс и по
      // живому человеку. Второй вид обязан быть один: было два написания
      // (`forward_sheet` и лист), и разошлись бы они молча.
      const rule = 'lib/features/search/screens/filter_sheet.dart';
      expect('bool matchesPerson(User u)'.allMatches(readCode(rule)).length, 1,
          reason: 'правило отбора по живому человеку объявлено не один раз');
      final fwd = readCode('lib/features/chat/screens/forward_sheet.dart');
      expect(fwd.contains('_filters.matchesPerson(user)'), isTrue,
          reason: 'пересылка снова сверяет фильтры своими руками — значит '
              'появилось второе написание тех же пяти полей');
    });

    test('у фильтров нет флага «а этому не показывать»', () {
      // I58: переключатель в объединённой функции — признак того, что в неё
      // сложены два дела. Фильтры общие ровно потому, что вопрос «кто мне
      // подходит» у обоих листов один.
      final coreCode = readCode(core);
      for (final flag in const [
        'showsFilters',
        'withFilters',
        'enableFilters',
        'hideFilters',
      ]) {
        expect(coreCode.contains(flag), isFalse,
            reason: 'в общей середине завёлся флаг $flag — значит фильтры '
                'показываются одному листу и прячутся от другого, а это два '
                'дела в одной функции (I58)');
      }
    });
  });

  // ---------------------------------------------------------------------
  // N249 — «Gələ bilmirəm» РОВНО ДВАЖДЫ В КОДЕ.
  //
  // Лежит в этом наборе, а не в отдельном файле, потому что обе правки — одна
  // работа 19.09 и один экран; заводить ради двух вердиктов третий файл значит
  // растащить разбор по местам, где его не найдут.
  //
  // ЧТО УТВЕРЖДАЕТСЯ: кнопка выхода в `agreements_screen.dart` встречается
  // дважды — подвальная форма экрана `DƏVƏT` (`_MyAnswerCard`, форма `footer`)
  // и отдельная кнопка в карточке вечера под правилом `offersEventExit`.
  // Третья — это снова двойник.
  //
  // УТВЕРЖДЕНИЕ НАЛИЧИЯ С ТОЧНЫМ ЧИСЛОМ, значит само себе канарейка (I31):
  // ослепни разбор — станет ноль, и вердикт покраснеет.
  //
  // ЧЕГО НЕ ЛОВИТ: что обе кнопки ведут в РАЗНЫЕ места экрана и что вторая
  // вообще нарисована. Это глаза на трубке (I55).
  // ---------------------------------------------------------------------
  group('«Gələ bilmirəm» — без двойника (N249)', () {
    test('в коде ровно две кнопки выхода', () {
      final screen = readCode(
        'lib/features/agreements/screens/agreements_screen.dart',
      );
      final n = "label: 'Gələ bilmirəm'".allMatches(screen).length;
      expect(
        n,
        2,
        reason:
            'кнопок выхода в коде $n вместо двух. Три — вернулся двойник из '
            'блока «Cavabınız» (N249): обе звали бы одну и ту же '
            '`leaveEventWithReason` с одними аргументами, то есть делали бы '
            'буквально одно. Одна — пропала дверь, и из вечера под вопросом '
            'стало не выйти (её условие даёт `offersEventExit`, а блок там '
            'скрыт `answersClosed`)',
      );
    });

    test('блок «Cavabınız» спрашивает ПРАВИЛО, а не складывает условие', () {
      // N250. Условие жило в разметке и разошлось с соседним ровно на
      // вышедшем: `answerFor` у него возвращает `left`, а не `null`.
      final screen = readCode(
        'lib/features/agreements/screens/agreements_screen.dart',
      );
      expect(screen.contains('if (showsAnswerBlock('), isTrue,
          reason: 'условие показа блока ответа вернулось в разметку. Условие '
              'в правиле прогоняется вердиктом, условие в разметке — ничем '
              '(I32), и в прошлый раз это стоило N250');
    });
  });
}
