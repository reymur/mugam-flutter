import 'package:flutter_test/flutter_test.dart';

import 'support/source_text.dart';

// КНОПКА «ÖZ ADAMLARIMI ÇAĞIR» — работа 7, шаг 4 (`docs/plan.md`), 08.09.
//
// СТОРОЖ ПО ИСХОДНИКУ, А НЕ ПО ЭКРАНУ, и это названо сразу. Поднять карточку
// вечера в widget-тесте нельзя без живых `FirebaseAuth`, `musiciansProvider`
// и потоков мероприятий; вердикт, поднимающий полпрода, проверял бы
// обстановку, а не правило — цена такой обстановки уже заплачена (N192).
//
// Поэтому здесь сторожатся ровно два утверждения, оба выразимые текстом:
// кнопка ОДНА и условия по `isAgree` у неё НЕТ. Что она открывает лист и
// возвращает выбранных — проверяется на трубке.

/// Срез: от начала блока кнопок владельца до «Dəyişiklik et».
///
/// Границы взяты ПО КОДУ, а не по комментарию: `readCode` снимает
/// комментарии, и якорь по ним дал бы пустоту — то есть зелёный вердикт от
/// слепоты (I31). Уехала граница — срез пуст, и соседний вердикт это
/// назовёт.
String _ownerButtonsBlock(String screen) {
  const from = 'if (isOwner) ...[';
  const to = "label: 'Dəyişiklik et',";
  final a = screen.indexOf(from);
  if (a < 0) return '';
  final b = screen.indexOf(to, a);
  if (b < 0) return '';
  return screen.substring(a, b);
}

void main() {
  final screen = readCode(
    'lib/features/agreements/screens/agreements_screen.dart',
  );

  group('кнопка «позвать своих» — шаг 4', () {
    // УТВЕРЖДЕНИЕ НАЛИЧИЯ, значит само себе канарейка (I31): ослепни разбор
    // — совпадений станет ноль, и вердикт покраснеет.
    test('кнопка есть, и она РОВНО ОДНА', () {
      final hits = 'Öz adamlarımı çağır'.allMatches(screen).length;
      expect(hits, 1,
          reason: 'ноль — кнопку сняли или переименовали; больше одной — '
              'появилось второе место вставки, а решение владельца 08.09 по '
              'первому вопросу работы 7 в том и состоит, что место ОДНО: '
              'карточка одна на договор и на личный вечер');
    });

    test('обработчик заведён и зовёт многоместный лист', () {
      expect(screen.contains('_callMyPeople('), isTrue);
      expect(screen.contains('pickPeopleForLineup(context)'), isTrue,
          reason: 'лист, написанный и никем не позванный, — это тот самый '
              'класс «написано и не подключено», ради которого шаг 4 '
              'делается сразу за шагом 3');
    });

    // ГЛАВНЫЙ ВЕРДИКТ ГРУППЫ: решение вопроса 1 соблюдено НА ДЕЛЕ, а не на
    // словах (I64 — проверять каждого, кто подпадает, а не наличие правила).
    //
    // «Позвать своих» — про вечер, а не про то, платят ли за него. Условие
    // по `isAgree` вернуло бы в показ различение, снятое шагом 6 12.08.
    test('у кнопки НЕТ условия по isAgree', () {
      final block = _ownerButtonsBlock(screen);
      expect(block, isNotEmpty,
          reason: 'кусок с кнопкой не найден — границы среза уехали, и '
              'вердикт ниже проверял бы пустоту (I31)');
      // Канарейка к самому срезу: кнопка внутри него ЕСТЬ. Без неё «isAgree
      // не найден» было бы истинно и на куске, взятом не оттуда.
      expect(block.contains('Öz adamlarımı çağır'), isTrue);
      expect(block.contains('isAgree'), isFalse,
          reason: 'решение владельца 08.09: кнопка на ОБОИХ видах вечера. '
              'Условие по isAgree здесь означает, что ответ на вопрос 1 '
              'нарушен на деле при соблюдении на словах');
    });

    // Условие по СОСТОЯНИЮ — законно и обязано остаться: звать людей в
    // прошедший или отменённый вечер бессмысленно, а кнопка, которой некуда
    // вести, читается как поломка (N65, N146).
    test('условие по состоянию у кнопки есть', () {
      final block = _ownerButtonsBlock(screen);
      expect(block.contains('_isPast(event)'), isTrue);
      // ЦЕЛОЕ ВЫРАЖЕНИЕ, А НЕ ГОЛОЕ ИМЯ: `contains('kStatusCancelled')`
      // было бы истинно от одного упоминания где угодно в срезе. Сторож над
      // сторожами поймал это в тот же заход и был прав.
      expect(block.contains('event.status != kStatusCancelled'), isTrue);
    });
  });
}
