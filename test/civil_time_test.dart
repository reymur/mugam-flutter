import 'package:flutter_test/flutter_test.dart';
import 'package:mugam_flutter/core/time/az_date_format.dart';

// ЗАПРЕТ N4, ЗАКРЫТЫЙ ТЕСТОМ, А НЕ КОММЕНТАРИЕМ.
//
// `date` мероприятия и `eventDate` чата — «плавающее гражданское время»:
// не момент на оси, а запись в календаре. Тədbir в 19:00 остаётся в 19:00
// там, где он проходит, независимо от того, в каком поясе смотрящий.
// Перевод их в UTC СОЗДАЛ БЫ баг там, где его нет — показанное время
// сдвинулось бы при поездке.
//
// Запрет записан комментариями в двух местах кода и строкой в реестре. Но
// комментарий защищает строку, а не класс (разбор 04.08): «привести всё к
// единой семантике» — правка, которую делают, дописывая рядом, а не
// правя эти две строки.
//
// Тест держит его иначе: он выполняется под ЧУЖИМ часовым поясом
// процесса. Любое приведение к UTC на пути записи или показа немедленно
// сдвинет ожидаемое значение и уронит его.
//
// Пояс задаётся переменной окружения TZ при запуске:
//   TZ=America/New_York flutter test test/civil_time_test.dart
// В обычном прогоне пояс машины бакинский, и тест всё равно осмыслен: он
// закрепляет, что разбор и показ идут БЕЗ арифметики по поясам.

void main() {
  group('плавающее гражданское время не сдвигается поясом (N4)', () {
    const iso = '2026-08-08T19:00:00.000';

    test('показ даты не зависит от пояса процесса', () {
      // Ни fmtEventDate, ни fmtEventTime не имеют права звать toUtc/toLocal:
      // строка без смещения — это стенные часы места проведения.
      expect(fmtEventDate(iso), '8 Avqust 2026');
      expect(fmtEventTime(iso), '19:00');
    });

    test('круг «разобрали — показали» сохраняет ровно то, что записано', () {
      final parsed = DateTime.parse(iso);
      expect(parsed.hour, 19);
      expect(parsed.minute, 0);
      // И обратно: то, что уйдёт в базу, снова без смещения.
      expect(parsed.toIso8601String(), iso);
      expect(parsed.toIso8601String().endsWith('Z'), isFalse,
          reason: 'суффикс Z означал бы момент на оси — это запрет N4');
    });

    test('полночь на границе суток не уезжает на другой день', () {
      // Самый чувствительный случай: любое смещение поясом видно сразу
      // сменой ДАТЫ, а не только часа.
      const midnight = '2026-01-01T00:30:00.000';
      expect(fmtEventDate(midnight), '1 Yanvar 2026');
      expect(fmtEventTime(midnight), '00:30');
    });

    test('конец суток тоже остаётся в своём дне', () {
      const late = '2026-12-31T23:45:00.000';
      expect(fmtEventDate(late), '31 Dekabr 2026');
      expect(fmtEventTime(late), '23:45');
    });
  });
}
