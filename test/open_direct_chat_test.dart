import 'package:flutter_test/flutter_test.dart';
import 'package:mugam_flutter/core/chat/open_direct_chat.dart';

// ОБЩИЙ ВХОД В ЧАТ — правило «можно ли вообще открывать».
//
// Проверяется здесь ПРАВИЛО, а не сам вход: у `openDirectChat` внутри переход
// и показ, а у `resolveDirectChatId` — обращение к Firestore, и то и другое в
// тесте проверять нечем. Правило вынесено отдельно ровно затем, чтобы его
// можно было прогнать (I27 — шаги проверки решаются до кода).
//
// ЧТО УПАДЁТ ПРИ ПОРЧЕ (называется ДО порчи — I46):
//   • снять `myUid != otherUid` — упадёт «чат с самим собой», один тест;
//   • снять любую проверку на пустоту — упадёт «пустой uid не человек»,
//     один тест;
//   • сломать правило целиком (вернуть `false` всегда) — упадёт «с обычным
//     собеседником открывать МОЖНО», то есть канарейка, и она здесь не
//     отдельная, а само утверждение (I31).

void main() {
  group('можно ли открывать личный чат', () {
    test('с обычным собеседником — МОЖНО (канарейка правила)', () {
      // Утверждение о наличии: ослепни правило, открывать станет нельзя ни с
      // кем, и это видно в первую же минуту, а не молчит как запрет.
      expect(
        canOpenDirectChat(myUid: 'me-uid', otherUid: 'other-uid'),
        isTrue,
      );
    });

    test('С САМИМ СОБОЙ — нельзя (N120 в общем месте)', () {
      // `getOrCreateDirectChat` такой запрос не отвергнет — он СОЗДАСТ
      // документ, где обе стороны один человек, и чат будет жить в списке
      // наравне с настоящими.
      expect(canOpenDirectChat(myUid: 'me-uid', otherUid: 'me-uid'), isFalse);
    });

    test('пустой uid не человек — ни с той, ни с другой стороны', () {
      // Без этого два пустых совпали бы и дали «чат с самим собой» там, где
      // на самом деле просто нет данных о людях.
      expect(canOpenDirectChat(myUid: '', otherUid: 'other-uid'), isFalse);
      expect(canOpenDirectChat(myUid: 'me-uid', otherUid: ''), isFalse);
      expect(canOpenDirectChat(myUid: '', otherUid: ''), isFalse);
    });
  });
}
