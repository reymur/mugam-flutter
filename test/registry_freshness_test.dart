import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

// N56 — реестр отстаёт от кода не случайно, а системно: за двое суток
// семь записей из девятнадцати числились открытыми при готовой правке.
// Причина у всех одна: правку сделали, строку реестра не тронули.
//
// ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ И ПОЧЕМУ ИМЕННО ЭТО. Проверить «относится ли
// правка к находке» механически нельзя — это смысл, а не текст. Но у
// наблюдавшегося отставания есть механический след: **чинящий коммит
// называет находку в заголовке**. N22 («Развести расписку… (N22)»),
// N29/N30/N31 («N29, N30, N31 и перенос участников»), N32 («N32: уборка
// activeUsers…») — все пять отставших вчера и обе сегодняшние помечены
// именно так. Значит правило выражается точно:
//
//   находка, названная в заголовке коммита, не может числиться открытой.
//
// Это не «напоминание писать в реестр» — такое тонет. Это красный тест:
// назвал находку в коммите, но не тронул её строку — суд встанет здесь.
//
// Проверено возвратом в день заведения: на состоянии реестра 07.08 до
// правки тест падал на N36 (щель закрылась выкладкой правил 06.08, а
// строка осталась «в проде открыта»), то есть находил настоящее
// отставание, а не пустоту.

/// Записи, которые коммитом не закрываются по своей природе, — и потому
/// изъяты из проверки. Список короткий намеренно: каждая строка здесь
/// ослабляет тест, поэтому у каждой стоит причина.
const _standing = <String, String>{
  // Накопительный список проверок «вдвоём»: коммиты правят его текст, а
  // закрывается он прогоном на устройствах, а не правкой кода.
  'N27': 'накопительный список проверок, закрывается прогоном',

  // ЗАВЕДЕНЫ КОММИТОМ, А НЕ ЗАКРЫТЫ ИМ — три случая 07.08, и все три
  // поймал этот сторож на моих же коммитах. Заголовок называет находку
  // потому, что коммит её ЗАПИСАЛ, а не потому, что починил; сторож же
  // читает «названа — значит работа сделана». Это не ложное
  // срабатывание: он спрашивает ровно то, что должен, и требует сказать
  // вслух, в каком из двух смыслов упомянута находка.
  'N63': 'правило работы, а не дефект кода: сторожа поставить не на что '
      '(решение сказано в самой находке), закрывается привычкой записывать '
      'решение в тот же заход',
  'N65': 'закрывается ЧАСТЯМИ: 4 обработчика из 6 сняты с главного экрана '
      '07.08; по «Şifrəni unutdum?» решение принято 07.08 (ссылка снята, '
      'сброс — работа 5а), закроется вместе с ней; «⋮» помечен заглушкой '
      'честно и решения не ждёт',
  'N66': 'записана 07.08 замером, чинится работой 5б (65 замен одним '
      'заходом); коммит, назвавший её, палитру не трогал. Прежнее имя '
      'работы — 6а, переименована при сведении двух порядков в один',

  // Заведена коммитом, который назвал её в заголовке, — четвёртый случай
  // того же рода, что три выше. Закрывается ЧАСТЯМИ и не кодом: из
  // четырёх столкнувшихся имён два вылечены переименованием («работа 6»,
  // «пункт N плана»), два остались («Этап N» — римские против арабских,
  // «прогон»). Сторожа нет намеренно: он был бы текстовым и споткнулся бы
  // о собственный разбор (I12) — сказано в самой находке словом «нет».
  'N69': 'одно имя на две работы: два имени из четырёх вылечены, два нет; '
      'сторож назван нецелесообразным в самой записи',
};

/// Номера работ, названные в ПРИЧИНАХ `_standing` (не в комментариях —
/// комментарии рассказывают историю и законно поминают мёртвые номера).
Set<String> _worksNamedInReasons(String source) {
  final block = source.substring(
    source.indexOf('const _standing'),
    source.indexOf('void main'),
  );
  final prose = block
      .split('\n')
      .where((l) => !l.trimLeft().startsWith('//'))
      .join('\n');
  // `\w` в Dart — это [A-Za-z0-9_], кириллицу он не берёт: `работ\w*\s+`
  // не совпадает с «работой 5б» вовсе. Первая редакция была написана
  // именно так и давала ПУСТО — зелено и бесполезно. Поймала это проверка
  // «нашлось хоть что-то» ниже (I13), а не глаз.
  return RegExp(r'работ[а-яё]*\s+(\d{1,2}[а-я]?)')
      .allMatches(prose)
      .map((m) => m.group(1)!)
      .toSet();
}

/// Номера из первого столбца таблицы «Порядок работ» в `docs/plan.md`.
Set<String> _worksInPlan(String plan) => RegExp(
      r'^\| \*{0,2}(\d{1,2}[а-я]?)\*{0,2} \|',
      multiLine: true,
    ).allMatches(plan).map((m) => m.group(1)!).toSet();

void main() {
  test('находка, названная в коммите, не числится открытой (N56)', () {
    final registry = File('AUDIT_TODO.md').readAsStringSync();

    final log = Process.runSync('git', ['log', '--format=%s']);
    expect(log.exitCode, 0, reason: 'git log недоступен: ${log.stderr}');

    final named = RegExp(r'\bN\d{1,2}\b')
        .allMatches(log.stdout as String)
        .map((m) => m.group(0)!)
        .toSet();

    final offenders = <String>[];
    for (final id in named) {
      if (_standing.containsKey(id)) continue;
      // Строка реестра начинается с «| N32 |» — берём её целиком.
      final row = RegExp('^\\| $id \\|.*\$', multiLine: true)
          .firstMatch(registry)
          ?.group(0);
      if (row == null) continue; // о находке говорят, а записи нет — не наше дело
      final closed = RegExp('закрыт', caseSensitive: false).hasMatch(row);
      if (!closed) offenders.add(id);
    }

    expect(
      offenders,
      isEmpty,
      reason: 'Эти находки названы в заголовках коммитов, то есть работа по '
          'ним делалась, но в реестре они не закрыты: '
          '${offenders.join(', ')}.\n'
          'Либо дописать статус (что именно сделано и чем проверено), либо '
          '— если находка правда ещё открыта, а коммит её лишь упоминал — '
          'внести её в список _standing с причиной. Правку заканчивают не '
          'коммитом, а строкой реестра (N56).',
    );
  });

  // N70 — СТОРОЖ, СЛЕДЯЩИЙ ЗА ОТСТАВАНИЕМ, ОТСТАЛ САМ. Проверять его было
  // некому: он и есть проверка. К 07.08 две причины в `_standing` из
  // четырёх говорили неправду — у N65 «ждут решения владельца» после
  // принятого решения, у N66 «чинится работой 6а» после переименования
  // работы в 5б. Тест при этом был зелёным: он читает КЛЮЧИ и не читает
  // ПРИЧИНЫ.
  //
  // Ниже три проверки на сам `_standing`. Что они ловят и чего нет —
  // сказано у каждой, потому что сторож, на который положатся шире его
  // возможностей, опаснее отсутствия сторожа.
  group('изъятия из проверки не протухают (N70)', () {
    final source = File('test/registry_freshness_test.dart').readAsStringSync();
    final registry = File('AUDIT_TODO.md').readAsStringSync();

    test('у каждого изъятия есть строка в реестре', () {
      // Ловит изъятие находки, которой нет вовсе, — опечатку в номере и
      // ссылку на запись, удалённую из реестра.
      final missing = _standing.keys
          .where((id) => !RegExp('^\\| $id \\|', multiLine: true)
              .hasMatch(registry))
          .toList();
      expect(missing, isEmpty,
          reason: 'Изъяты из проверки находки, которых в AUDIT_TODO.md нет: '
              '${missing.join(', ')}');
    });

    test('изъятие снимается, когда находка закрыта', () {
      // Изъятие ослабляет тест, поэтому живёт ровно пока находка открыта.
      // Ловит забытую строку, которая продолжает глушить сторожа после
      // того, как работа сделана.
      final stale = _standing.keys.where((id) {
        final row = RegExp('^\\| $id \\|.*\$', multiLine: true)
            .firstMatch(registry)
            ?.group(0);
        return row != null && RegExp('закрыт', caseSensitive: false)
            .hasMatch(row);
      }).toList();
      expect(stale, isEmpty,
          reason: 'Находка закрыта, а изъятие осталось и глушит сторожа: '
              '${stale.join(', ')}. Убрать строку из _standing.');
    });

    test('номера работ в причинах существуют в docs/plan.md', () {
      // Это и есть ответ на вопрос «можно ли проверять причины
      // механически»: ЧАСТЬЮ можно. Ссылка на несуществующий номер работы
      // роняет тест — «работой 6а» после переименования упала бы здесь.
      //
      // ЧЕГО НЕ ЛОВИТ, и это не мелочь: номер, который не исчез, а стал
      // значить ДРУГОЕ. Существуй сегодня работа 6а под новым смыслом,
      // причина осталась бы ложной, а проверка — зелёной. Это N69,
      // проявленный внутри собственного сторожа. Не ловит и утверждение
      // без номера: «ждут решения владельца» — та самая протухшая причина
      // N65 — здесь не видна ничем.
      final named = _worksNamedInReasons(source);
      final inPlan = _worksInPlan(File('docs/plan.md').readAsStringSync());

      // I13: сторож, считающий не то, молчит так же, как сторож, которому
      // нечего сказать. Оба разбора обязаны один раз показать своё число.
      expect(inPlan, isNotEmpty,
          reason: 'В docs/plan.md не разобран ни один номер работы — '
              'изменился формат таблицы, и проверка ниже стала пустой');
      expect(named, isNotEmpty,
          reason: 'В причинах _standing не найдено ни одного номера работы. '
              'Либо их правда нет, либо разбор перестал их видеть — '
              'второе неотличимо от первого по зелёному прогону');

      final unknown = named.difference(inPlan).toList();
      expect(unknown, isEmpty,
          reason: 'Причины в _standing ссылаются на работы, которых в '
              'docs/plan.md нет: ${unknown.join(', ')}. Разошлись после '
              'переименования — поправить причину, а не список работ');
    });
  });
}
