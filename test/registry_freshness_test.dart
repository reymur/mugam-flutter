/// СТОЛБЕЦ СОСТОЯНИЯ строки реестра, а не строка целиком.
///
/// Прежняя редакция искала слово «закрыт» по всей строке — то есть
/// проверяла, что слово ГДЕ-ТО ЕСТЬ, а не что находка закрыта. Разбор в
/// теле записи почти всегда поминает закрытие соседней находки, и слово
/// туда попадает само. Замер 07.08: **две записи из 67 (N42, N50) были
/// открыты по состоянию и читались сторожем как закрытые.** Назови любую
/// в заголовке коммита — сторож промолчал бы.
///
/// Состояние — ПОСЛЕДНЯЯ непустая ячейка: у 66 строк из 67 их четыре, у
/// N43 шесть (в теле есть `|` внутри кода), и последняя всё равно она.
/// РАЗБИЕНИЕ СТРОКИ НА ЯЧЕЙКИ, УМЕЮЩЕЕ ЧИТАТЬ ОБРАТНЫЕ КАВЫЧКИ (N183, 30.08).
///
/// Здесь стояло простое `row.split('|')`, и вот чем это кончилось. Правило
/// I6 требует ставить рядом с числом КОМАНДУ, которой оно снято; команды
/// сплошь и рядом содержат трубу и чередование (`grep -c "a\|b"`, `… | wc
/// -l`). То есть **два правила проекта тянут в разные стороны**: одно велит
/// писать в тело команду, другое разбирает тело трубой как границей ячейки.
///
/// **ЗАМЕР 30.08, И ОН ШИРЕ, ЧЕМ ЗВЁЗДОЧКИ ИЗ N183: у 24 строк реестра из
/// 184 ячеек не три, то есть «состоянием» бралcя кусок тела.** Снятие
/// вставок в обратных кавычках лечит 18 из 24; у оставшихся шести (N140,
/// N116, N110, N95, N93, N90) труба стоит вне кавычек — там внутри тела
/// лежит своя табличка, — но у всех шести последняя ячейка **всё равно
/// состояние**, проверено глазами поимённо.
///
/// **Нашлось это не разбором, а тем, что разбор запустили ради другого.**
/// Строка N121 сломалась В ЭТОТ ЖЕ ДЕНЬ, моей собственной правкой: я
/// дописал в тело `grep` с чередованием, и состояние съехало на обрывок
/// команды. Прогон при этом остался ЗЕЛЁНЫМ — ровно потому, что
/// самопроверка смотрела только на записи, начинающиеся словом «открыт», а
/// обрывок команды таким словом не начинается. **Слепота N183 спрятала
/// поломку, внесённую при починке N183.**
List<String> _cells(String row) {
  final out = <String>[];
  final buf = StringBuffer();
  var inCode = false;
  for (final ch in row.split('')) {
    if (ch == '`') inCode = !inCode;
    if (ch == '|' && !inCode) {
      out.add(buf.toString().trim());
      buf.clear();
    } else {
      buf.write(ch);
    }
  }
  out.add(buf.toString().trim());
  return out.where((c) => c.isNotEmpty).toList();
}

String? _statusOf(String registry, String id) {
  final row = RegExp('^\\| $id \\|(.*)\$', multiLine: true)
      .firstMatch(registry)
      ?.group(1);
  if (row == null) return null;
  final cells = _cells(row);
  return cells.isEmpty ? null : cells.last;
}

/// Ведущая разметка, снятая ДО разбора слова состояния.
///
/// **Не образец под звёздочки, и это требование владельца 29.08 дословно:**
/// «не подгонкой образца под звёздочки — это заткнёт сегодняшний случай и
/// оставит завтрашний». Поэтому снимается РАЗМЕТКА как класс — жирный,
/// курсив, обратные кавычки, пробелы, — а не конкретный её вид. Завтрашнее
/// `__открыт__` или `` `открыт` `` пройдёт здесь само.
String _withoutLeadMarkup(String s) =>
    s.replaceFirst(RegExp(r'^[*_`\s]+'), '');

/// Первое слово состояния — без разметки и без знаков препинания.
String _stateWord(String status) {
  final m = RegExp(r'[а-яёa-z]+', caseSensitive: false)
      .firstMatch(_withoutLeadMarkup(status));
  return (m?.group(0) ?? '').toLowerCase();
}

/// СЛОВА СОСТОЯНИЯ, КОТОРЫЕ НЕ «ОТКРЫТ» И НЕ «ЗАКРЫТ», — ПЕРЕЧИСЛЕНЫ, А НЕ
/// ПОСЧИТАНЫ.
///
/// **Это канарейка к сужению самого сторожа, и без неё починка N183
/// держалась бы на честном слове.** Проверка «ни одна открытая не читается
/// закрытой» утверждает ОТСУТСТВИЕ: сузься разбор обратно (сними снятие
/// разметки — и `**открыт 19.08**` перестанет опознаваться), список
/// расхождений останется ПУСТЫМ, и сторож зазеленеет, рассматривая
/// тридцать четыре записи вместо ста восьмидесяти четырёх. Ровно так он и
/// жил до 30.08.
///
/// Здешний набор утверждает НАЛИЧИЕ: каждое непонятое состояние обязано
/// начинаться одним из этих восьми слов. Сузься разбор — и в непонятые
/// посыплются `открыт`/`закрыт` под разметкой, которых в наборе нет, и
/// проверка покраснеет В ТОТ ЖЕ ЗАХОД, назвав слово.
///
/// **Замер 30.08: непонятых 12 при 184 записях**, и все двенадцать — вот
/// эти восемь слов. Список не запрещает завести девятое: он требует
/// вписать его сюда руками, то есть заметить.
const _otherStateWords = <String>{
  'в', // «в работе» — N38, N39, N40, N46, N47
  'половина', // N45
  'отложен', // N48
  'долг', // N162
  'поправлено', // N135
  'записано', // N134
  'починен', // N125
  'чинится', // N116
};

/// Закрыта ли находка по тексту её состояния.
///
/// «не закрыт» содержит «закрыт» — поэтому отрицание снимается ДО поиска,
/// а не проверяется после. Сегодня в столбцах состояния такой формы нет
/// ни одной, но она законна и появится молча.
///
/// **ПРОБЕЛ МЕЖДУ «НЕ» И «ЗАКРЫТ» НЕОБЯЗАТЕЛЕН, И ЭТО КУПЛЕНО СЛУЧАЕМ, А НЕ
/// ПРЕДУСМОТРЕНО (N183, 29.08).** Здесь стояло `replaceAll('не закрыт', '')`
/// — снималось только раздельное написание. Слово «незакрытым» пишется
/// слитно, внутри него сидит «закрыт», и запись с ним читалась как ЗАКРЫТАЯ.
/// Поймано это не сторожем: 29.08 сторож упал на собственном сообщении
/// коммита, где стояло «остаётся НЕЗАКРЫТЫМ одно», и фразу тогда просто
/// переписали в обход. Обход лечил тот вечер и оставлял правило неверным.
bool _readsAsClosed(String status) => status
    .toLowerCase()
    .replaceAll(RegExp(r'не\s*закрыт'), '')
    .contains('закрыт');

