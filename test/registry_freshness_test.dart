      // ЖИВОЙ СЛУЧАЙ, А НЕ ВЫДУМАННЫЙ: ровно эта фраза стояла 29.08 в
      // сообщении коммита («остаётся НЕЗАКРЫТЫМ одно»), уронила сторожа
