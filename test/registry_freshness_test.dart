      expect(ids, isNotEmpty, reason: 'записей вида «| N12 |» не найдено вовсе');

      final open = <String>[];
      final misread = <String>[];
      for (final id in ids) {
        final status = _statusOf(registry, id);
        expect(status, isNotNull, reason: '$id: состояние не разобрано');
        if (!status!.toLowerCase().startsWith('открыт')) continue;
        open.add(id);
        if (_readsAsClosed(status)) misread.add('$id ($status)');
      }

      // I13: соседка к разбору. Без неё «неверно прочитанных нет» и
      // «открытых не нашлось вовсе» — один и тот же зелёный вывод.
      expect(open, isNotEmpty,
          reason: 'ни одна запись не начинается словом «открыт» — либо все '
              'закрыты, либо разбор состояния сломан');
      expect(misread, isEmpty,
          reason: 'Сторож читает открытую запись как закрытую: '
              '${misread.join('; ')}');
    });

    // N69, лечение: НОМЕР, НАЗВАННЫЙ ВНЕ СВОЕГО ФАЙЛА, НАЗЫВАЕТ ФАЙЛ.
    //
    // Единица работы зовётся в проекте пятью словами — работа, пункт,
    // этап, шаг, часть, — и каждое пронумеровано своей нумерацией.
    // Перепись 07.08: 245 мест, до 29 разных номеров у одного слова.
    //
    // ПЕРЕИМЕНОВЫВАТЬ ВСЕ 245 НЕ НАДО, и причина не в цене — иначе
    // следующий прочтёт «245 мест» и решит, что мы поленились:
    //   • 209 из них — архив, разборы и датированные свидетельства.
    //     Переписать их значит ПОДДЕЛАТЬ запись: она говорит, что было
    //     видно в тот день и под теми именами (I7 — «устарела находка» и
    //     «устарело её доказательство» лечатся по-разному);
    //   • каждое переименование САМО вводит новое имя. N69 родилась ровно
    //     так: второе столкновение завелось при починке первого, в тот же
    //     заход, теми же руками;
    //   • 25 мест в самом `docs/plan.md` в уточнении не нуждаются — внутри
    //     плана «пункт 14» однозначен, файл называет себя сам.
    //
    // Остаются 11 мест, где номер написан ВНЕ своего файла и потому
    // посылает не туда: столбцы состояния реестра (по ним решают, что
    // делать дальше) и раздел 0 `handoff.md` (точка входа). Их и сторожит
    // проверка ниже.
    //
    // ЧЕГО ОНА НЕ ЛОВИТ, и это написано здесь, а не выяснится потом:
    // **она видит, что имя файла есть, и не видит, что оно НЕВЕРНОЕ.**
    // «Пункт 14 `docs/plan.md`» и «пункт 14 `docs/job-offer-plan.md`»
    // для неё одинаковы. То есть лечение от N69 несёт внутри себя ту же
    // N69 — существование имени против его тождества (N71).
    //
    // Имена в «ёлочках» пропускаются намеренно: «работа 6» в кавычках —
    // это имя, О КОТОРОМ говорят, а не указатель, куда идти.
    test('номер вне своего файла называет файл (N69)', () {
      final unit = RegExp(
        r'(?<![А-Яа-яA-Za-z])(работ|пункт|этап|шаг|част)[а-яё]*\s+'
        r'(№\s*)?(\d{1,2}[а-яё]?|[IVX]{1,3})(?![\dА-Яа-я])',
        caseSensitive: false,
      );
      final qualifier = RegExp(
        r'\.md|Этапа? I\b|Этапа? II\b|реестра',
        caseSensitive: false,
      );
      String stripNames(String s) => s.replaceAll(RegExp('«[^»]*»'), '');

      final places = <String, String>{};
      for (final m
          in RegExp(r'^\| (N\d+) \|(.*)$', multiLine: true)
              .allMatches(registry)) {
        final status = _statusOf(registry, m.group(1)!);
        if (status != null) places['AUDIT_TODO.md ${m.group(1)}'] = status;
      }
      final handoff = File('docs/handoff.md').readAsStringSync();
      places['handoff.md раздел 0'] =
          handoff.substring(0, handoff.indexOf('## 1а.'));

      // I13: без этого «нарушителей нет» и «разбор ослеп» — один вывод.
      final seen = places.values
          .map((v) => unit.allMatches(stripNames(v)).length)
          .fold<int>(0, (a, b) => a + b);
      expect(seen, greaterThan(0),
          reason: 'ни одного «работа/пункт/этап/шаг/часть N» не разобрано — '
              'сломался разбор, а не исчезли номера');

      final bare = <String>[];
      places.forEach((where, text) {
        for (final m in unit.allMatches(stripNames(text))) {
          if (!qualifier.hasMatch(text)) {
            bare.add('$where: «${m.group(0)}» без имени файла');
          }
        }
      });
      expect(bare, isEmpty,
          reason: 'Номер работы назван вне своего файла и файла не называет. '
              'Пять слов — работа, пункт, этап, шаг, часть — нумерованы в '
              'проекте по-разному, и голый номер посылает не туда (N69):\n'
              '${bare.join('\n')}');
    });

    test('изъятие снимается, когда находка закрыта', () {
      // Изъятие ослабляет тест, поэтому живёт ровно пока находка открыта.
      // Ловит забытую строку, которая продолжает глушить сторожа после
      // того, как работа сделана.
      final stale = _standing.keys.where((id) {
        final status = _statusOf(registry, id);
        return status != null && _readsAsClosed(status);
      }).toList();
      expect(stale, isEmpty,
          reason: 'Находка закрыта, а изъятие осталось и глушит сторожа: '
              '${stale.join(', ')}. Убрать строку из _standing.');
    });

    test('номера работ в причинах существуют в docs/plan.md', () {
      // Это и есть ответ на вопрос «можно ли проверять причины
      // механически»: ЧАСТЬЮ можно. Ссылка на несуществующий номер работы
      // роняет тест — «работой 6а» после переименования упала бы здесь.
      //
      // ЧЕГО НЕ ЛОВИТ, и это не мелочь: номер, который не исчез, а стал
      // значить ДРУГОЕ. Существуй сегодня работа 6а под новым смыслом,
      // причина осталась бы ложной, а проверка — зелёной. Это N69,
      // проявленный внутри собственного сторожа. Не ловит и утверждение
      // без номера: «ждут решения владельца» — та самая протухшая причина
      // N65 — здесь не видна ничем.
      final named = _worksNamedInReasons(source);
      final inPlan = _worksInPlan(File('docs/plan.md').readAsStringSync());

      // I13: сторож, считающий не то, молчит так же, как сторож, которому
      // нечего сказать. Оба разбора обязаны один раз показать своё число.
      expect(inPlan, isNotEmpty,
          reason: 'В docs/plan.md не разобран ни один номер работы — '
              'изменился формат таблицы, и проверка ниже стала пустой');
      expect(named, isNotEmpty,
          reason: 'В причинах _standing не найдено ни одного номера работы. '
              'Либо их правда нет, либо разбор перестал их видеть — '
              'второе неотличимо от первого по зелёному прогону');

      final unknown = named.difference(inPlan).toList();
      expect(unknown, isEmpty,
          reason: 'Причины в _standing ссылаются на работы, которых в '
              'docs/plan.md нет: ${unknown.join(', ')}. Разошлись после '
              'переименования — поправить причину, а не список работ');
    });
  });
