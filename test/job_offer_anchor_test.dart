import 'package:flutter_test/flutter_test.dart';
import 'package:mugam_flutter/firebase/models.dart';

// ЯКОРЬ ПРЕДЛОЖЕНИЯ В ЛЕНТЕ.
//
// Предложение уходит в переписку ОБЫЧНЫМ сообщением `type: 'text'` с полем
// `offerId`. Тип не меняется намеренно: старая сборка про `offerId` не знает
// и покажет текст, а с новым типом у неё был бы пустой пузырь.
//
// Значит новая сборка отличает предложение по НАЛИЧИЮ ПОЛЯ, и от того,
// доезжает ли поле до модели, зависит вообще всё: без него лента не может
// ни нарисовать строку иначе, ни сделать её нажимаемой.
//
// ЭТОТ НАБОР ЗАВЕДЁН ПОТОМУ, ЧТО ПОЛЕ ЧУТЬ НЕ ПОТЕРЯЛОСЬ МОЛЧА. Правка
// `fromFirestore` не применилась (не совпал отступ в замене), и `offerId`
// остался бы всегда `null`: модель собиралась бы без ошибок, анализатор
// молчал бы, а предложения в ленте просто никогда не стали бы нажимаемыми —
// и выглядело бы это как «не доделали показ», а не как «поле не читается».

void main() {
  group('offerId доезжает от документа до модели', () {
    test('поле читается из данных', () {
      final m = Message.fromFirestore('m1', {
        'senderId': 'boss',
        'text': '5 gün: 26, 27 avqust · Toy',
        'type': 'text',
        'offerId': 'offer-42',
      });
      expect(m.offerId, 'offer-42');
    });

    // Обычное сообщение ссылки не имеет — и это признак, по которому лента
    // отличает одно от другого.
    test('у обычного сообщения ссылки нет', () {
      final m = Message.fromFirestore('m2', {
        'senderId': 'boss',
        'text': 'Salam',
        'type': 'text',
      });
      expect(m.offerId, isNull);
    });

    // Сообщения до 14.08 ссылки не имеют и иметь не могут: взяться ей
    // неоткуда. Они остаются обычным текстом навсегда — решение, а не
    // недоделка, и чинить это не надо.
    test('чужой тип поля не роняет разбор, а даёт null', () {
      final m = Message.fromFirestore('m3', {
        'senderId': 'boss',
        'text': 'Salam',
        'type': 'text',
        'offerId': 42,
      });
      expect(m.offerId, isNull);
    });
  });
}
