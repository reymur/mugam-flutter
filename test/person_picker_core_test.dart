import 'package:flutter_test/flutter_test.dart';
import 'package:mugam_flutter/features/job_offer/screens/person_picker_core.dart';
import 'package:mugam_flutter/firebase/models.dart';

import 'support/source_text.dart';

// ВЫНОС СЕРЕДИНЫ ДВУХ ЛИСТОВ — работа 7, шаг 2 (`docs/plan.md`), 08.09.
//
// Вердикты заведены вместе с выносом и НЕ ЯВЛЯЮТСЯ его целью: цель — не
// дать правилу «кого показывать в списке» разойтись между двумя листами.
// Но пока правило жило внутри состояния виджета, проверить его было нечем
// вовсе — тот же довод, по которому вынесены `event_edit` и
// `agreement_cancel`.
//
// ЧТО ЭТИ ВЕРДИКТЫ НЕ ДОКАЗЫВАЮТ, сказано сразу: они проверяют ПРАВИЛО, а
// не то, что лист по-прежнему открывается и предложение уходит. Это
// проверяется сборкой на трубку — условие приёмки шага 2, решение
// владельца 08.09. Тест зовёт правило напрямую, а прод идёт длиннее на три
// звена (I55).

User _u(String id,
        {String name = '', String instrument = '', String city = ''}) =>
    User(
      id: id,
      name: name,
      emoji: '',
      instrument: instrument,
      city: city,
      rating: 0,
      reviews: 0,
      available: true,
      goldRing: false,
      online: false,
      bio: '',
    );

void main() {
  group('кого показывать в списке выбора людей', () {
    final latinI = [
      _u('me', name: 'Mən'),
      _u('x', name: 'Ilya', city: 'Bakı'),
    ];

    final all = [
      _u('me', name: 'Mən'),
      _u('a', name: 'Rafael', instrument: 'Gitara', city: 'Bakı'),
      _u('b', name: 'Teymur', instrument: 'Tar', city: 'Gəncə'),
      _u('c', name: 'Elvin', instrument: 'Nağara', city: 'Bakı'),
    ];

    test('СЕБЯ в списке нет никогда', () {
      // Ни в одноместном листе, ни в многоместном: предложить работу себе и
      // позвать себя в свой же состав одинаково бессмысленны.
      final r = filterPeople(all, myUid: 'me', query: '');
      expect(r.map((u) => u.id), isNot(contains('me')));
      // Соседка: список не опустел вовсе. Без неё «меня нет» было бы
      // истинно и на пустом ответе (I31).
      expect(r, hasLength(3));
    });

    test('пустой запрос — все, кроме себя', () {
      expect(
        filterPeople(all, myUid: 'me', query: '   ').map((u) => u.id),
        ['a', 'b', 'c'],
      );
    });

    // ТРИ ПОЛЯ, А НЕ ОДНО ИМЯ, и каждое проверено порознь: человек ищет и
    // «Rafael», и «gitara», и «Gəncə». Поиск по одному имени заставил бы
    // помнить имя, а помнят чаще инструмент.
    test('ищет по имени', () {
      expect(filterPeople(all, myUid: 'me', query: 'rafa').map((u) => u.id),
          ['a']);
    });

    test('ищет по инструменту', () {
      // ОТБОР ПО ПОДСТРОКЕ, А НЕ ПО СЛОВУ, и вердикт записан по ЗАМЕРУ, а
      // не по замыслу: «tar» находит и `Tar`, и `Gitara`. Я ждал одного
      // `Tar` — факт разошёлся с ожиданием, и прав оказался код: отбор и
      // должен быть подстрочным, иначе «gita» не найдёт гитариста.
      expect(filterPeople(all, myUid: 'me', query: 'tar').map((u) => u.id),
          ['a', 'b']);
      // Соседка, чтобы «находит обоих» не читалось как «находит всех»:
      // Nağara под «tar» не подходит.
      expect(filterPeople(all, myUid: 'me', query: 'tar').map((u) => u.id),
          isNot(contains('c')));
    });

    test('ищет по городу', () {
      expect(filterPeople(all, myUid: 'me', query: 'gəncə').map((u) => u.id),
          ['b']);
    });

    test('пробелы по краям не важны, регистр — для латиницы', () {
      expect(filterPeople(all, myUid: 'me', query: '  bakı ').map((u) => u.id),
          ['a', 'c']);
      expect(filterPeople(all, myUid: 'me', query: 'RAFAEL').map((u) => u.id),
          ['a']);
    });

    // N208 — ПОЧИНЕНО 08.09. ВЕРДИКТ ПЕРЕПИСАН, А НЕ УДАЛЁН.
    //
    // ЗДЕСЬ СТОЯЛО ОБРАТНОЕ — «заглавная „I“ города НЕ находит его же
    // строчную „ı“», с `isEmpty` и с припиской «если стало непусто, поиск
    // починили, и этот вердикт надо переписать вместе с починкой».
    // Требование владельца 08.09: переписать, не удалять. День настал, и
    // вердикт стоит на своём месте с обратным знаком — иначе завтра никто
    // не узнает, что здесь была болезнь.
    //
    // ПРОБА «ДО» СДЕЛАНА ВЛАДЕЛЬЦЕМ НА ТРУБКЕ 08.09, на сборке шага 2, где
    // починки ещё не было. Без неё «после» ничего не доказывало бы: зелёный
    // вердикт на исправленном коде одинаков и там, где болезни не было
    // вовсе.
    //
    // ЗАМЕР ЯЗЫКА, 08.09: `'BAKI'.toLowerCase()` → `baki`, а
    // `'Bakı'.toLowerCase()` → `bakı` — не совпадают; `'İstanbul'` и
    // `'GƏNCƏ'` приводятся верно. Чинилась ОДНА пара из трёх, `I`/`ı`.
    test('заглавная «I» города находит его же строчную «ı» (N208)', () {
      expect(filterPeople(all, myUid: 'me', query: 'BAKI').map((u) => u.id),
          ['a', 'c'],
          reason: 'N208: поиск сравнивает через azLowerCase. Стало пусто — '
              'значит вернулся голый toLowerCase, и человек, набравший '
              'город заглавными, снова не найдёт никого');
      // Обе стороны дают одно и то же — иначе «находит» держалось бы на
      // совпадении, а не на правиле.
      expect(filterPeople(all, myUid: 'me', query: 'BAKI').map((u) => u.id),
          filterPeople(all, myUid: 'me', query: 'bakı').map((u) => u.id));
      // Канарейка к обоим: отбор всё ещё отбирает, а не возвращает всех.
      expect(filterPeople(all, myUid: 'me', query: 'BAKI'),
          isNot(hasLength(all.length)));
      // Вторая половина замера: на «ə» слепоты не было и нет.
      expect(filterPeople(all, myUid: 'me', query: 'GƏNCƏ').map((u) => u.id),
          ['b']);
    });

    // ЦЕНА ПРАВКИ, ЗАПИСАННАЯ ВЕРДИКТОМ, А НЕ ТОЛЬКО СЛОВАМИ.
    //
    // Имя с ЛАТИНСКОЙ `I` приводится к `ı`. Пока обе стороны идут через одну
    // функцию, они сходятся друг с другом — это и проверяется. Расходятся
    // они только в паре «данные с латинской `I`» против «запроса с `i`», и
    // это та же плата, что принята в `azUpperCase`. В проде таких имён ноль
    // из 12 (замер 08.09).
    test('латинская «I» в имени: обе стороны сходятся между собой (N208)', () {
      final withLatinI = [...latinI];
      expect(filterPeople(withLatinI, myUid: 'me', query: 'Ilya').map((u) => u.id),
          ['x']);
      expect(filterPeople(withLatinI, myUid: 'me', query: 'ILYA').map((u) => u.id),
          ['x']);
      // А вот это — названная цена, а не недосмотр: запрос с дотошной `i`
      // не находит имя, написанное латинской `I`.
      expect(filterPeople(withLatinI, myUid: 'me', query: 'ilya'), isEmpty,
          reason: 'плата за azLowerCase, названная до правки: латинская I '
              'уходит в ı, и запрос с дотошной i её не находит');
    });

    test('никто не подошёл — пусто, а не все', () {
      // Обратная половина: без неё «отбор находит» было бы истинно и у
      // отбора, который не отбирает вовсе (I14).
      expect(filterPeople(all, myUid: 'me', query: 'zzz'), isEmpty);
    });

    test('пустой uid — себя не вычёркиваем, но и не роняем', () {
      // Третья ветвь `viewerUid` существует в проде (`job_offer_sheet`),
      // и правило обязано её пережить: пустой uid не совпадает ни с чьим
      // id, значит список приходит целиком.
      expect(filterPeople(all, myUid: '', query: ''), hasLength(4));
    });
  });

  group('лист выбора показывает, кто в сети (18.09)', () {
    // ЗАЧЕМ ПО ИСХОДНИКУ. Кружок — это разметка, а её прогнать нечем (I32).
    // Проверяемо здесь одно, но главное: что правило спрашивается ТО ЖЕ, а не
    // пишется рядом второе.
    //
    // ЦЕНА ВТОРОГО ПРАВИЛА ИЗМЕРЕНА НЕ НАМИ: `isActuallyOnline` обслуживает
    // зелёную точку в двенадцати файлах. Заведи лист своё — человек был бы
    // зелёным в чате и серым здесь, и разошлись бы они молча (N49).
    late String code;

    setUpAll(() {
      code = readCode('lib/features/job_offer/screens/person_picker_core.dart');
    });

    test('кружок судит ТЕМ ЖЕ правилом, что чат и остальные', () {
      expect(code.contains('user.isActuallyOnline ? kGreen : kMuted'), isTrue,
          reason: 'Лист выбора решает «в сети ли он» сам. Два правила об '
              'одном расходятся молча — человек зелёный в чате и серый тут.');
    });

    test('КРУЖОК ОБНОВЛЯЕТСЯ ПО ВРЕМЕНИ — тем же приёмом и числом, что чат', () {
      // ЗАЧЕМ. `isActuallyOnline` сравнивает `lastSeen` с `DateTime.now()`:
      // ответ зависит от ВРЕМЕНИ, а не только от данных. Поток перерисует
      // список лишь когда изменится документ — от хода времени он не
      // сработает ни разу, и кружок замрёт на том, каким был при открытии.
      //
      // ЧИСЛО ОДНО НА ТРИ МЕСТА, и вердикт сторожит именно это: с разными
      // числами один человек гас бы в чате и горел в списке, а различить это
      // было бы нечем.
      expect(code.contains('Duration(seconds: 20)'), isTrue,
          reason: 'Число перерисовки разошлось с чатом и экраном контакта.');
      expect(code.contains('Timer.periodic(_presenceRefreshInterval'), isTrue,
          reason: 'Перерисовка по времени снята — кружок замрёт на миге '
              'открытия списка.');
      expect(code.contains('_presenceRefreshTimer?.cancel()'), isTrue,
          reason: 'Таймер не снимается при закрытии — он продолжит будить '
              'закрытый список.');
    });

    test('ТАЙМЕР ОДИН НА ВЕСЬ СПИСОК, А НЕ НА КАЖДУЮ СТРОКУ', () {
      // Перерисовку просит тот, кто список ДЕРЖИТ. Заведись таймер в строке —
      // их стало бы по одному на человека, и каждый будил бы экран сам.
      //
      // ПЕРВАЯ РЕДАКЦИЯ ЭТОГО ВЕРДИКТА БЫЛА НЕВЕРНА ДВАЖДЫ, и обе ошибки
      // поймали не глаза: срез «от `class PersonRow` до конца файла» захватил
      // и класс списка ниже (в файле строка объявлена ПЕРВОЙ), а поиск голого
      // слова `Timer` поймал сторож сторожей — такое имя есть в файле всегда.
      //
      // ФОРМА ТЕПЕРЬ СЧИТАЮЩАЯ И ТОЧНАЯ: полей-таймеров во всём файле ровно
      // одно. Появится второе — вердикт покраснеет, где бы оно ни завелось.
      expect('Timer? _presenceRefreshTimer'.allMatches(code).length, 1,
          reason: 'Полей-таймеров в файле не одно. Второй таймер — это либо '
              'перерисовка на каждую строку, либо забытый старый.');
    });

    test('ЛИШНИХ ЧТЕНИЙ НЕТ — строке нечем читать поток', () {
      // `online` и `lastSeen` приходят тем же документом `users/{uid}`, что
      // имя, фото и инструмент; список и так держит целого `User`. Отдельный
      // поток присутствия стоил бы по чтению НА КАЖДУЮ СТРОКУ списка.
      //
      // ПЕРВАЯ РЕДАКЦИЯ ЭТОГО ВЕРДИКТА ИСКАЛА ИМЯ `presenceProvider` И БЫЛА
      // НЕГОДНОЙ: такого имени в проекте нет вовсе (`grep -rn
      // "presenceProvider" lib` → 0), то есть проверка не могла провалиться
      // никогда (I9). Поймал её сторож сторожей, а не я.
      //
      // ПРОВЕРЯЕМОЕ ВМЕСТО ПРАВДОПОДОБНОГО: строка — `StatelessWidget`, у неё
      // нет `ref`, и прочитать провайдер ей НЕЧЕМ. Это не намерение, а
      // устройство: заведи кто-нибудь чтение присутствия на строку, ему
      // придётся сменить тип виджета, и вердикт покраснеет.
      expect(code.contains('class PersonRow extends StatelessWidget'), isTrue,
          reason: 'Строка человека перестала быть StatelessWidget — значит '
              'она получила `ref` и может читать поток на каждую строку.');
      // Канарейка к утверждению выше: разбор файла вообще не пуст.
      expect(code.contains('CircleAvatar('), isTrue,
          reason: 'канарейка: строка человека не читается — вердикт выше '
              'зелен даром');
    });
  });
}
