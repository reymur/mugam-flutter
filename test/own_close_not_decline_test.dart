import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

// СТОРОЖ НА ПРИПИСАННЫЙ ОТКАЗ (N195).
//
// ЧТО ЧИНИЛОСЬ. Плагин выбирает между «человек отклонил» и «звонок
// завершён» по одному условию — `answerCall == nil && outgoingCall == nil`
// (`SwiftFlutterCallkitIncomingPlugin.swift:688–715`) — и про то, КТО
// запросил закрытие окна, не спрашивает вовсе: `CXEndCallAction` приходит
// одинаковый и от пальца человека, и от нашего
// `FlutterCallkitIncoming.endCall(...)`. Поэтому наше собственное закрытие
// (звонящий отменил → `_watchForRemoteEnd` → `endCall`) возвращалось к нам
// событием `ACTION_CALL_DECLINE`, и мы писали в прод отказ от имени
// человека, который ничего не нажимал. Замер 03.09: 2 документа `calls` из
// 25 со статусом `declined`, приписанным вызываемому.
//
// ПОЧЕМУ СТОРОЖ ТЕКСТОВЫЙ, А НЕ ПОВЕДЕНЧЕСКИЙ. Событие приходит с нативной
// стороны через `EventChannel`, которого в тесте нет; подделать его значило
// бы проверять подделку. Здесь проверяется ПРОВОДКА — что пометка ставится,
// спрашивается и снимается, — а поведение проверяется на трубке.
//
// ЧЕГО ЭТОТ СТОРОЖ НЕ ЛОВИТ (границы пишутся вместе со сторожем):
//   - он не видит, что пометка снимается ИМЕННО по тому звонку: совпадение
//     `callId` в двух местах он сверяет как текст, а не как значение;
//   - он ничего не говорит о том, приходит ли событие вообще;
//   - он смотрит на один файл. Появись второй писатель `respondToCall` с
//     `accept: false` — этот сторож промолчит.
void main() {
  late String code;
  late String raw;

  String codeOnly(String t) =>
      t.split('\n').where((l) => !l.trimLeft().startsWith('//')).join('\n');

  setUpAll(() {
    final f = File('lib/core/calls/callkit_service.dart');
    expect(f.existsSync(), isTrue, reason: 'callkit_service.dart пропал');
    raw = f.readAsStringSync();
    code = codeOnly(raw);
  });

  test('КАНАРЕЙКА: файл прочитан, отсечение работает и не съело код', () {
    // Отсечение здесь обязательно и это ИЗМЕРЕНО, а не предположено: слова
    // `_closedByUs` и `respondToCall` стоят в разборе выше по файлу, и
    // счёт по всему тексту насчитал бы их как живые.
    expect(raw.length, greaterThan(10000));
    expect(
      code.length,
      lessThan(raw.length),
      reason: 'комментарии не отсечены — вердикты ниже считают разбор',
    );
    // ПОРОГ ВЗЯТ ЗАМЕРОМ, А НЕ НА ГЛАЗ, И ЭТО ПОПРАВКА, А НЕ ЗАМЫСЕЛ.
    // Здесь стояло `raw.length ~/ 3` — и вердикт покраснел НА ИСПРАВНОМ
    // ДЕРЕВЕ: файл на две трети состоит из разбора (9464 знака кода из
    // 30 518, замер 03.09), то есть треть — это и есть норма, а не признак
    // поломки. Ложная тревога и пропуск — одна болезнь (I14), и лечится она
    // одинаково: назвать, каким вывод обязан быть НА ИСПРАВНОМ.
    expect(
      code.length,
      greaterThan(raw.length ~/ 5),
      reason: 'отсечение съело код: осталось ${code.length} из ${raw.length}',
    );
    // КАНАРЕЙКА ИЩЕТ НЕ ТО, ЧТО СТЕРЕГУТ ВЕРДИКТЫ, И ЭТО ПОПРАВКА, КУПЛЕННАЯ
    // ПОРЧЕЙ, А НЕ ЗАМЫСЕЛ. Здесь стояло `_closedByUs` с порогом «не меньше
    // трёх» — и порча «снять пометку из endCall» уронила ЕЁ ВМЕСТЕ с
    // названным вердиктом: названо было одно падение, случилось два.
    // Причина не в числе, а в предмете: канарейка стерегла ровно то же, что
    // и вердикты, то есть была вторым вердиктом, а не проверкой инструмента.
    // Ослепни разбор — покраснеют все; сломайся починка — обязан краснеть
    // только свой вердикт.
    //
    // Поэтому ищется заведомо существующее и К ПОЧИНКЕ ОТНОШЕНИЯ НЕ
    // ИМЕЮЩЕЕ: `_callkitIdByCallId` — карта, живущая в этом файле с самого
    // начала и ни одним вердиктом ниже не проверяемая.
    final mentions = '_callkitIdByCallId'.allMatches(code).length;
    expect(
      mentions,
      greaterThanOrEqualTo(5),
      reason: 'разбор нашёл $mentions упоминаний карты звонков — он слеп, а '
          'не «в файле пусто»',
    );
  });

  test('пометка ставится ПЕРЕД закрытием окна, а не после', () {
    // Порядок — не украшение: событие отказа приходит В ОТВЕТ на строку
    // закрытия и может опередить возврат из await. Пометка после закрытия
    // оставила бы щель ровно того же вида, что N194.
    final mark = code.indexOf('_closedByUs.add(callId)');
    final close = code.indexOf('FlutterCallkitIncoming.endCall(callkitId)');
    expect(mark, greaterThan(0), reason: 'пометка не ставится вовсе');
    expect(close, greaterThan(0), reason: 'закрытие окна не зовётся');
    expect(
      mark,
      lessThan(close),
      reason: 'пометка стоит ПОСЛЕ закрытия окна — между ними щель, и отказ, '
          'пришедший в неё, снова будет приписан человеку',
    );
    expect(
      close - mark,
      lessThan(400),
      reason: 'между пометкой и закрытием ${close - mark} знаков — они '
          'разъехались, и это уже не одно действие',
    );
  });

  group('срез ветви отказа', () {
    late String branch;

    setUpAll(() {
      final from = code.indexOf('case CallEventActionCallDecline(');
      expect(from, greaterThan(0), reason: 'ветвь отказа не найдена');
      final to = code.indexOf('case CallEventActionCallTimeout(', from);
      expect(to, greaterThan(from), reason: 'конец ветви не найден');
      branch = code.substring(from, to);
    });

    test('КАНАРЕЙКА: срез не пуст и не съел половину файла', () {
      // Срез по именам-границам доказывает, что кусок ТОТ, и не доказывает,
      // что он целый (N104) — поэтому длина названа числом.
      expect(
        branch.length,
        inInclusiveRange(150, 1500),
        reason: 'срез ветви длиной ${branch.length} — границы уехали',
      );
    });

    test('ветвь спрашивает пометку и снимает её тем же чтением', () {
      expect(
        branch.contains('_closedByUs.remove(callId)'),
        isTrue,
        reason: 'обработчик отказа не спрашивает, не мы ли закрыли окно — '
            'значит своё закрытие снова уйдёт в прод как отказ человека',
      );
    });

    test('своё закрытие НЕ пишет отказ в прод', () {
      final ask = branch.indexOf('if (_closedByUs.remove(callId))');
      final respond = branch.indexOf('respondToCall(');
      expect(ask, greaterThan(0), reason: 'развилки по пометке нет');
      expect(respond, greaterThan(0), reason: 'отказ не пишется вовсе — '
          'значит сломан и ЧУЖОЙ отказ, а не только свой');
      expect(
        ask,
        lessThan(respond),
        reason: 'запись отказа стоит ДО проверки пометки — проверка ничего '
            'не решает, отказ уйдёт в прод в обоих случаях',
      );
      // Внутри ветви «закрыли мы» записи отказа быть не должно вовсе.
      final own = branch.substring(ask, respond);
      expect(
        own.contains('respondToCall('),
        isFalse,
        reason: 'внутри ветви своего закрытия всё равно пишется отказ',
      );
      expect(
        own.contains('break;'),
        isTrue,
        reason: 'ветвь своего закрытия не выходит — исполнение провалится '
            'дальше, в запись отказа',
      );
    });

    test('чужой отказ по-прежнему пишется — иначе починили в ноль', () {
      // Утверждение НАЛИЧИЯ, значит само себе канарейка (I31). Без него
      // «отказ не приписывается» выполнялось бы и полным отключением
      // отказов, а это была бы поломка дороже исходной.
      expect(
        branch.contains('respondToCall(callId: callId, accept: false)'),
        isTrue,
        reason: 'запись чужого отказа снята — теперь не работает отклонение '
            'вообще, а не только приписанное',
      );
    });

    test('своё закрытие метится в _applied, чтобы выдача не повторила его', () {
      // N194 × N195: нативный делегат кладёт КАЖДЫЙ отказ в отложенные,
      // включая тот, что мы здесь распознали как своё закрытие. Без пометки
      // он дождался бы следующего запуска в течение минуты, и выдача
      // применила бы отказ, от которого мы отказались.
      final mark = branch.indexOf(r"_applied.add('decline:$callId')");
      final ask = branch.indexOf('if (_closedByUs.remove(callId))');
      expect(mark, greaterThan(0), reason: 'отказ не метится в _applied');
      expect(
        mark,
        lessThan(ask),
        reason: 'пометка в _applied стоит ПОСЛЕ развилки — на своём закрытии '
            'она не выполнится, и выдача применит отказ следующим запуском',
      );
    });
  });

  group('срез ветви завершения (N198)', () {
    late String branch;

    setUpAll(() {
      final from = code.indexOf('case CallEventActionCallEnded(');
      expect(from, greaterThan(0), reason: 'ветвь завершения не найдена');
      final to = code.indexOf('default:', from);
      expect(to, greaterThan(from), reason: 'конец ветви не найден');
      branch = code.substring(from, to);
    });

    test('КАНАРЕЙКА: срез не пуст и не съел половину файла', () {
      expect(
        branch.length,
        inInclusiveRange(150, 1500),
        reason: 'срез ветви длиной ${branch.length} — границы уехали',
      );
    });

    test('ветвь завершения тоже спрашивает пометку', () {
      // ПОЧЕМУ ВЕТВЕЙ ДВЕ, А НЕ ОДНА. Наше закрытие окна возвращается разным
      // событием: `outgoingCall` в плагине — защёлка, взводится при первом
      // исходящем звонке с трубки и не сбрасывается. Не звонил — придёт
      // DECLINE (N195), звонил хоть раз — ENDED (N198). Починка одной ветви
      // работает ровно для половины людей, и по какому признаку эта половина
      // делится, из кода не видно ниоткуда.
      expect(
        branch.contains('_closedByUs.remove(callId)'),
        isTrue,
        reason: 'обработчик завершения не спрашивает, не мы ли закрыли окно — '
            'значит наше закрытие снова затрёт настоящий отказ человека на '
            'ended, как в звонке Z6VxywLZ 03.09',
      );
    });

    test('своё закрытие НЕ пишет endCall в прод', () {
      final ask = branch.indexOf('if (_closedByUs.remove(callId))');
      final write = branch.indexOf('firestoreService.endCall(');
      expect(ask, greaterThan(0), reason: 'развилки по пометке нет');
      expect(write, greaterThan(0),
          reason: 'endCall не пишется вовсе — значит сломано и настоящее '
              'завершение с системного экрана CallKit');
      expect(
        ask,
        lessThan(write),
        reason: 'запись endCall стоит ДО проверки пометки — проверка ничего '
            'не решает, затирание останется',
      );
      final own = branch.substring(ask, write);
      expect(
        own.contains('firestoreService.endCall('),
        isFalse,
        reason: 'внутри ветви своего закрытия всё равно пишется endCall',
      );
      expect(
        own.contains('break;'),
        isTrue,
        reason: 'ветвь своего закрытия не выходит — исполнение провалится '
            'дальше, в запись endCall',
      );
    });

    test('чужое завершение по-прежнему пишется — иначе починили в ноль', () {
      // Утверждение НАЛИЧИЯ, само себе канарейка (I31). Без него «затирания
      // нет» выполнялось бы и полным отключением записи завершения — а это
      // случай, который ничем больше не покрыт: отбой с системного экрана
      // CallKit идёт мимо нашего кода целиком.
      expect(
        branch.contains('await firestoreService.endCall(callId: callId)'),
        isTrue,
        reason: 'запись настоящего завершения снята — отбой с системного '
            'экрана перестанет доходить до второй стороны',
      );
    });

    test('прежний довод «это no-op» остался только ЦИТАТОЙ, снятой явно', () {
      // ПЕРВАЯ РЕДАКЦИЯ ЭТОГО ВЕРДИКТА ТРЕБОВАЛА, ЧТОБЫ ФРАЗЫ В ФАЙЛЕ НЕ
      // БЫЛО ВОВСЕ, И ПОКРАСНЕЛА НА ПОЧИНЕННОМ ДЕРЕВЕ. Причина — I12: снятый
      // довод и его снятие состоят из одних и тех же слов. Правка привела
      // фразу обратно в файл как ЦИТАТУ («здесь стояло …, и это было
      // неверно»), а разбор не отличал цитату от живого утверждения.
      //
      // Выбрасывать цитату нельзя: неверный довод, снятый молча, возвращается
      // вместе с поломкой, потому что следующему он покажется разумным.
      // Поэтому проверяется не отсутствие, а ФОРМА: вхождение ровно одно и
      // стоит под явной пометкой о снятии.
      final raw = File('lib/core/calls/callkit_service.dart').readAsStringSync();
      const phrase = 'no-op write on an already';
      final hits = phrase.allMatches(raw).toList();
      expect(
        hits.length,
        1,
        reason: 'вхождений прежнего довода ${hits.length}, а допустимо одно — '
            'цитата под пометкой о снятии. Ноль означал бы, что цитату '
            'выбросили и снятие стало неотличимо от «так и не было»; больше '
            'одного — что довод вернулся живым',
      );
      final before = raw.substring(
        (hits.first.start - 500).clamp(0, raw.length),
        hits.first.start,
      );
      expect(
        before.contains('ЗДЕСЬ СТОЯЛО'),
        isTrue,
        reason: 'довод «перезапись безвредна» стоит в файле БЕЗ пометки о том, '
            'что он снят. Документ бывает не ended, а declined — и тогда это '
            'затирание отказа человека',
      );
      // КАНАРЕЙКА к разбору: он находит в этом же файле заведомо
      // существующее, значит ноль выше означал бы уборку, а не слепоту.
      expect(
        'CallEventActionCallEnded'.allMatches(raw).length,
        greaterThanOrEqualTo(1),
        reason: 'разбор не видит даже имени ветви — он слеп, а не «довод убран»',
      );
    });
  });
}
