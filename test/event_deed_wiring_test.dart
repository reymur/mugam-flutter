import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

// СТОРОЖ НА ПРОВОДКУ ПОСТУПКА ДО УВЕДОМЛЕНИЯ (N213).
//
// **ЧТО СЛУЧИЛОСЬ И ПОЧЕМУ ЭТОГО НЕ ЗАМЕТИЛИ МЕСЯЦ.** Клиент пишет
// `lastActionType: 'ownerCancelled'` с 12–13.08. `planUpdatePushes` ветвится
// по этому полю, ветви такому имени не было, и оно проваливалось в
// `default` — то есть владелец отменял личный вечер, а состав не узнавал
// ничего. Ни один сторож этого не видел, и не мог: у клиента всё верно, у
// сервера всё верно, неверна ГРАНИЦА между ними. Подтверждено делом 11.09.
//
// **ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ, И ЭТО НЕ ПОВЕДЕНИЕ.** Поведение проверяет
// `functions/test/event-notifications.test.ts` — он зовёт `planUpdatePushes`
// и смотрит, что вышло. Он молчит ровно об одном: **есть ли ветвь у имени,
// которое клиент действительно пишет.** Забудь ветвь — там всё зелено, а на
// трубке тишина.
//
// **УСТРОЙСТВО: ТАБЛИЦА, А НЕ ЗАПРЕТ.** У каждого имени поступка обязан
// стоять ответ, что с ним происходит: ветвь в `switch`, обработка в другом
// месте, либо **молчание с номером находки**. Третье — не поблажка, а
// запись долга: сегодня трое молчат нарочно, и таблица не даёт их забыть.
//
// **ИЗЪЯТИЕ НЕ ПРОТУХАЕТ, и это здесь главное.** Заведи ветвь для молчащего
// и не поправь таблицу — сторож покраснеет. То есть починка не может пройти
// мимо этой записи, а без такого условия список молчащих через месяц стал бы
// описывать позавчерашний код.
//
// **УТВЕРЖДЕНИЕ НАЛИЧИЯ — САМО СЕБЕ КАНАРЕЙКА (I31)**, и обе половины
// разбирают ОДНИМ И ТЕМ ЖЕ выражением: ослепни оно — множество ветвей
// опустеет, и `case`-половина покраснеет первой, назвав имена. Отдельная
// соседка на «нашлось хоть что-то» стоит ниже с числами.
//
// **ЧЕГО ЭТОТ СТОРОЖ НЕ ЛОВИТ** (иначе на него положатся шире умения):
//   • он читает ИСХОДНИКИ, а не поведение: ветвь может стоять и быть
//     пустой, слать не тому или не то. Это дело поведенческого набора;
//   • он не проверяет, что клиент это имя ДЕЙСТВИТЕЛЬНО пишет: каталог
//     `event_deed_line.dart` отвечает «какие поступки мы знаем», а не
//     «какие из них случаются». `ownerRestored` вон в типе сервера есть, а
//     писателя у него нет ни одного;
//   • он ничего не знает про `firestore.rules`: имя, которое правила не
//     пропустят, будет здесь выглядеть проведённым;
//   • он смотрит ОДИН серверный файл. Ветвь, заведённая в другом, ему
//     невидима — и потому «обработано вне `switch`» проверяется по
//     названному месту, а не по факту.

/// Что происходит с каждым поступком на сервере.
///
/// Ключ — литерал имени, как его пишет клиент. Значение — ответ, и ответов
/// ровно три вида:
///
///   `_case`      — ветвь в `switch` внутри `planUpdatePushes`;
///   `_elsewhere` — разбирается вне `switch`; в скобках названо, чем;
///   `_silent`    — уведомления НЕТ, и это известно; в скобках номер находки.
const Map<String, String> _coverage = {
  // --- разбирается вне `switch`, и место названо -----------------------
  'created': '$_elsewhere onPersonalEventCreated → pushAdded',
  'replaced': '$_elsewhere onPersonalEventCreated → pushReplaced',
  'agreed': '$_elsewhere onPersonalEventCreated выходит НАРОЧНО: обе '
      'стороны уже узнали из карточки предложения (N130)',
  'left': '$_elsewhere ветвь leftViaAnswers, а не имя поступка (N121)',
  'edited': '$_elsewhere ветвь fieldsChanged → pushEdited',
  'memberLeft': '$_elsewhere пишет СЕРВЕР (markEventUnsettled) и там же '
      'шлёт pushUnsettled',
  'workCancelled': '$_elsewhere пишет СЕРВЕР '
      '(unsettleChildrenOnParentCancel) и там же шлёт pushUnsettled',

  // --- своя ветвь в switch ---------------------------------------------
  'cancelRequested': _case,
  'cancelConfirmed': _case,
  'cancelWithdrawn': _case,
  'cancelDeclined': _case,
  // Заведена 11.09. До неё — месяц молчания на отмене личного вечера.
  'ownerCancelled': _case,

  // --- МОЛЧИТ, И ЭТО ДОЛГ, А НЕ УСТРОЙСТВО -----------------------------
  //
  // Все три — та же дыра, что была у `ownerCancelled`, только с другими
  // именами. Не чинятся этим заходом решением владельца: починка N213 едет
  // в выкладку функций одной переменной (I48).
  'ownerFirm': '$_silent N214 — владелец вернул «Dəqiq», состав не узнаёт',
  'ownerDoubt': '$_silent N215 — владелец поставил «İş dəqiq deyil», состав '
      'не узнаёт, ХОТЯ ОКОШКО ОБЕЩАЕТ «iştirakçılar xəbər tutacaq»',
  'restored': '$_silent N216 — вечер выведен из-под вопроса, остальные не '
      'узнают',
};

const String _case = 'ВЕТВЬ';
const String _elsewhere = 'ИНАЧЕ:';
const String _silent = 'МОЛЧИТ:';

void main() {
  final deedFile =
      File('lib/core/agreements/event_deed_line.dart').readAsStringSync();
  final serverFile =
      File('functions/src/eventNotifications.ts').readAsStringSync();

  // Каталог имён у клиента: `const String kDeedXxx = 'значение';`
  final deeds = RegExp(r"const String kDeed\w+ = '([a-zA-Z]+)';")
      .allMatches(deedFile)
      .map((m) => m.group(1)!)
      .toSet();

  // Ветви у сервера: `case "значение": {`
  final cases = RegExp(r'case "([a-zA-Z]+)":')
      .allMatches(serverFile)
      .map((m) => m.group(1)!)
      .toSet();

  group('проводка поступка до уведомления (N213)', () {
    // СОСЕДКА, И ОНА ПАДАЕТ НА НУЛЕ. Без неё «расхождений нет» и «разбор
    // ослеп» дают один зелёный вывод. Числа названы вслух (I13): «не пусто»
    // молчит о том, что нашлось два из пятнадцати.
    test('КАНАРЕЙКА: оба разбора вообще что-то находят', () {
      expect(deeds.length, 15,
          reason: 'каталог поступков разобрался не целиком: $deeds');
      expect(cases.length, greaterThanOrEqualTo(5),
          reason: 'ветви в switch не разбираются: $cases');
    });

    // НОВОЕ ИМЯ НЕ ПРОСКОЧИТ БЕЗ ОТВЕТА. Именно так и родилась N213: имя
    // завели, а что с ним делает сервер — не спросили.
    test('у каждого поступка каталога есть ответ в таблице', () {
      expect(deeds.difference(_coverage.keys.toSet()), isEmpty,
          reason: 'поступок заведён, а что с ним делает сервер — не сказано');
      expect(_coverage.keys.toSet().difference(deeds), isEmpty,
          reason: 'в таблице имя, которого в каталоге больше нет');
    });

    for (final entry in _coverage.entries) {
      final deed = entry.key;
      final answer = entry.value;

      if (answer == _case) {
        test('$deed — ветвь в planUpdatePushes на месте', () {
          expect(cases, contains(deed),
              reason: 'ветвь снята: $deed снова проваливается в default, '
                  'и уведомления по нему не будет НИ ОДНОГО');
        });
      } else if (answer.startsWith(_silent)) {
        // ИЗЪЯТИЕ НЕ ПРОТУХАЕТ. Появилась ветвь — молчания больше нет,
        // значит строка врёт, и её надо переписать в `_case`.
        test('$deed — молчание всё ещё молчание ($answer)', () {
          expect(cases, isNot(contains(deed)),
              reason: 'ветвь для $deed завели, а таблица всё ещё числит его '
                  'молчащим — поправить строку и закрыть находку');
        });
      } else {
        // «Обработано вне switch» доказывается ОТСУТСТВИЕМ ветви: заведись
        // она, разбор пошёл бы двумя дорогами разом.
        test('$deed — ветви нет, разбирается иначе ($answer)', () {
          expect(cases, isNot(contains(deed)),
              reason: 'у $deed появилась ветвь, а таблица говорит, что он '
                  'разбирается в другом месте — теперь их два');
        });
      }
    }

    // ДОЛГ НАЗВАН ЧИСЛОМ, А НЕ ОЩУЩЕНИЕМ (I40: знаменатель обязателен).
    //
    // Без него список молчащих читался бы как «уведомления сломаны». Доля
    // говорит другое: из пятнадцати поступков молчат трое, и все трое
    // названы поимённо строкой выше.
    test('молчащих ровно трое из пятнадцати, и это долг', () {
      final silent = _coverage.entries
          .where((e) => e.value.startsWith(_silent))
          .map((e) => e.key)
          .toSet();
      expect(silent, {'ownerFirm', 'ownerDoubt', 'restored'});
      expect(deeds.length, 15);
    });
  });
}
