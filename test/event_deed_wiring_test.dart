import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

// СТОРОЖ НА ПРОВОДКУ ПОСТУПКА ДО УВЕДОМЛЕНИЯ (N213).
//
// **ЧТО СЛУЧИЛОСЬ И ПОЧЕМУ ЭТОГО НЕ ЗАМЕТИЛИ МЕСЯЦ.** Клиент пишет
// `lastActionType: 'ownerCancelled'` с 12–13.08. `planUpdatePushes` ветвится
// по этому полю, ветви такому имени не было, и оно проваливалось в
// `default` — то есть владелец отменял личный вечер, а состав не узнавал
// ничего. Ни один сторож этого не видел, и не мог: у клиента всё верно, у
// сервера всё верно, неверна ГРАНИЦА между ними. Подтверждено делом 11.09.
//
// **ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ, И ЭТО НЕ ПОВЕДЕНИЕ.** Поведение проверяет
// `functions/test/event-notifications.test.ts` — он зовёт `planUpdatePushes`
// и смотрит, что вышло. Он молчит ровно об одном: **есть ли ветвь у имени,
// которое клиент действительно пишет.** Забудь ветвь — там всё зелено, а на
// трубке тишина.
//
// **УСТРОЙСТВО: ТАБЛИЦА, А НЕ ЗАПРЕТ.** У каждого имени поступка обязан
// стоять ответ, что с ним происходит: живая ветвь, **инертная ветвь**,
// обработка в другом месте, либо молчание с номером находки.
//
// **ЧЕТВЁРТЫЙ ВИД ОТВЕТА (`_inert`) ЗАВЕДЁН 11.09 ПО N218, И ОН ЖЕ ЗДЕСЬ
// ГЛАВНЫЙ УРОК.** До него ветвь без писателя стояла как обычная — то есть
// сторож утверждал ровно то, на чём споткнулся его автор: **«ветвь есть»
// читается как «работает», а между ними стоит писатель.** Живых ветвей
// сегодня ДВЕ из восьми, и это число проверяется вердиктом, а не прозой.
//
// **НА 11.09 МОЛЧАЩИХ НОЛЬ.** Заведён этот сторож был при троих (N214, N215,
// N216), и все трое починены в тот же день; третий вид ответа оставлен —
// он понадобится первому же поступку, которому уведомления не полагается.
// Пустота списка утверждается отдельным вердиктом: у нуля нет
// отличительного значения, и «вычистили» от «перестали заполнять» иначе не
// отличить (I37).
//
// **ИЗЪЯТИЕ НЕ ПРОТУХАЕТ, и это здесь главное.** Заведи ветвь для молчащего
// и не поправь таблицу — сторож покраснеет. То есть починка не может пройти
// мимо этой записи, а без такого условия список молчащих через месяц стал бы
// описывать позавчерашний код.
//
// **УТВЕРЖДЕНИЕ НАЛИЧИЯ — САМО СЕБЕ КАНАРЕЙКА (I31)**, и обе половины
// разбирают ОДНИМ И ТЕМ ЖЕ выражением: ослепни оно — множество ветвей
// опустеет, и `case`-половина покраснеет первой, назвав имена. Отдельная
// соседка на «нашлось хоть что-то» стоит ниже с числами.
//
// **ЧЕГО ЭТОТ СТОРОЖ НЕ ЛОВИТ** (иначе на него положатся шире умения):
//   • он читает ИСХОДНИКИ, а не поведение: ветвь может стоять и быть
//     пустой, слать не тому или не то. Это дело поведенческого набора;
//   • **он НЕ проверяет, что имя кто-то действительно пишет, и это
//     ограничение уже стоило дефекта — N218.** Каталог отвечает «какие
//     поступки мы знаем», а не «какие из них случаются». Разделение на
//     `_case` и `_inert` — не механизм, а СЛОВО: кто правит таблицу, обязан
//     назвать кнопку. Не может назвать — это `_inert`;
//   • он ничего не знает про `firestore.rules`: имя, которое правила не
//     пропустят, будет здесь выглядеть проведённым;
//   • он смотрит ОДИН серверный файл. Ветвь, заведённая в другом, ему
//     невидима — и потому «обработано вне `switch`» проверяется по
//     названному месту, а не по факту.

/// Что происходит с каждым поступком на сервере.
///
/// Ключ — литерал имени, как его пишет клиент. Значение — ответ, и ответов
/// **четыре** вида:
///
///   `_case`      — ветвь в `switch`, И писателя можно назвать кнопкой;
///   `_inert`     — ветвь есть, писателя НЕТ (N218, N219);
///   `_elsewhere` — разбирается вне `switch`; в скобках названо, чем;
///   `_silent`    — уведомления НЕТ, и это известно; в скобках номер находки.
///
/// **Разница между первым и вторым — та самая, на которой я ошибся 11.09:**
/// «ветвь есть» не значит «работает», между ними стоит писатель.
const Map<String, String> _coverage = {
  // --- разбирается вне `switch`, и место названо -----------------------
  'created': '$_elsewhere onPersonalEventCreated → pushAdded',
  'replaced': '$_elsewhere onPersonalEventCreated → pushReplaced',
  'agreed': '$_elsewhere onPersonalEventCreated выходит НАРОЧНО: обе '
      'стороны уже узнали из карточки предложения (N130)',
  'left': '$_elsewhere ветвь leftViaAnswers, а не имя поступка (N121)',
  'edited': '$_elsewhere ветвь fieldsChanged → pushEdited',
  'memberLeft': '$_elsewhere пишет СЕРВЕР (markEventUnsettled) и там же '
      'шлёт pushUnsettled',
  'workCancelled': '$_elsewhere писателя НЕТ с 12.09 — '
      'unsettleChildrenOnParentCancel снят; имя живёт в данных прода, '
      'карточка его читает, ветви не нужно',

  // --- ВЕТВЬ ЕСТЬ И ЖИВОЙ ПИСАТЕЛЬ ТОЖЕ: кнопку можно назвать пальцем -----
  //
  // Заведена 11.09. До неё — месяц молчания на отмене личного вечера.
  // Пишется кнопкой «Ləğv et» в карточке (`_cancelOwnEvent`).
  'ownerCancelled': _case,
  // Пишется кнопкой «Yenə də davam edirik» / «Onsuz davam edirəm»
  // (`_restoreEvent`, показ решает `showsRestore`).
  'restored': _case,

  // --- ВЕТВЬ ЕСТЬ, ПИСАТЕЛЯ НЕТ. ИНЕРТНА, И ЭТО РЕШЕНИЕ (N218, N219) ------
  //
  // **ЗДЕСЬ СТОЯЛО `_case` У ВСЕХ ШЕСТИ, И ЭТО ВВОДИЛО В ЗАБЛУЖДЕНИЕ.**
  // `_case` отвечает на «есть ли ветвь», а читалось как «работает». Между
  // этими двумя стоит писатель, и у шестерых ниже его нет.
  //
  // Четыре хода отмены договорённости: их экран снят `32bd8e4` 13.08 по
  // принципу «приложение НЕ ведёт переговоры», а половины в правилах, в
  // сервисе и здесь остались. `ownerFirm`/`ownerDoubt`: их окошко снято тем
  // же коммитом.
  //
  // **ИНЕРТНОСТЬ — СВОЙСТВО, А НЕ НЕДОДЕЛКА** (I48): сервер готов заранее,
  // ровно как ветвь `leftViaAnswers` в своё время. Появится кнопка —
  // заработает в тот же день, и окна молчания между двумя выкладками не
  // будет.
  'cancelRequested': _inert,
  'cancelConfirmed': _inert,
  'cancelWithdrawn': _inert,
  'cancelDeclined': _inert,
  'ownerFirm': _inert,
  'ownerDoubt': _inert,

  // --- МОЛЧИТ, И ЭТО ДОЛГ, А НЕ УСТРОЙСТВО -----------------------------
  //
  // **СЕЙЧАС ЗДЕСЬ ПУСТО, и пустота эта утверждается вердиктом ниже, а не
  // подразумевается.** Ноль нельзя найти по нему самому: список, из
  // которого молчащих вычистили, и список, который перестали заполнять,
  // выглядят одинаково (I37). Поэтому вердикт называет ноль вместе со
  // знаменателем — «молчащих ноль при 15 поступках».
  //
  // Строка сюда возвращается, как только заведут поступок, которому
  // уведомления не полагается: формат — `'имя': '$_silent N### — чем
  // молчание оправдано'`.
};

const String _case = 'ВЕТВЬ';
const String _elsewhere = 'ИНАЧЕ:';
const String _silent = 'МОЛЧИТ:';

/// Ветвь есть, а писателя у имени нет: нажать это в приложении нечем.
///
/// **Четвёртый вид ответа заведён 11.09 находкой N218**, и до неё такие
/// имена стояли как `_case` — то есть сторож утверждал ровно то, на чём я и
/// ошибся: «ветвь есть» читалось как «работает».
///
/// **Проверяется он ТАК ЖЕ, как `_case`** — ветвь обязана быть на месте, —
/// и отличается только тем, что говорит читателю. Отличить живого писателя
/// от мёртвого разбором нельзя (между литералом и пальцем стоит условие
/// показа), поэтому здесь работает СЛОВО, а не механизм, и это сказано
/// прямо, а не обойдено.
const String _inert = 'ИНЕРТНА';

void main() {
  final deedFile =
      File('lib/core/agreements/event_deed_line.dart').readAsStringSync();
  final serverFile =
      File('functions/src/eventNotifications.ts').readAsStringSync();

  // Каталог имён у клиента: `const String kDeedXxx = 'значение';`
  final deeds = RegExp(r"const String kDeed\w+ = '([a-zA-Z]+)';")
      .allMatches(deedFile)
      .map((m) => m.group(1)!)
      .toSet();

  // Ветви у сервера: `case "значение": {`
  final cases = RegExp(r'case "([a-zA-Z]+)":')
      .allMatches(serverFile)
      .map((m) => m.group(1)!)
      .toSet();

  group('проводка поступка до уведомления (N213)', () {
    // СОСЕДКА, И ОНА ПАДАЕТ НА НУЛЕ. Без неё «расхождений нет» и «разбор
    // ослеп» дают один зелёный вывод. Числа названы вслух (I13): «не пусто»
    // молчит о том, что нашлось два из пятнадцати.
    test('КАНАРЕЙКА: оба разбора вообще что-то находят', () {
      expect(deeds.length, 15,
          reason: 'каталог поступков разобрался не целиком: $deeds');
      expect(cases.length, greaterThanOrEqualTo(5),
          reason: 'ветви в switch не разбираются: $cases');
    });

    // НОВОЕ ИМЯ НЕ ПРОСКОЧИТ БЕЗ ОТВЕТА. Именно так и родилась N213: имя
    // завели, а что с ним делает сервер — не спросили.
    test('у каждого поступка каталога есть ответ в таблице', () {
      expect(deeds.difference(_coverage.keys.toSet()), isEmpty,
          reason: 'поступок заведён, а что с ним делает сервер — не сказано');
      expect(_coverage.keys.toSet().difference(deeds), isEmpty,
          reason: 'в таблице имя, которого в каталоге больше нет');
    });

    for (final entry in _coverage.entries) {
      final deed = entry.key;
      final answer = entry.value;

      if (answer == _case || answer == _inert) {
        final tail = answer == _inert ? ' (ИНЕРТНА: писателя нет)' : '';
        test('$deed — ветвь в planUpdatePushes на месте$tail', () {
          expect(cases, contains(deed),
              reason: 'ветвь снята: $deed снова проваливается в default, '
                  'и уведомления по нему не будет НИ ОДНОГО');
        });
      } else if (answer.startsWith(_silent)) {
        // ИЗЪЯТИЕ НЕ ПРОТУХАЕТ. Появилась ветвь — молчания больше нет,
        // значит строка врёт, и её надо переписать в `_case`.
        test('$deed — молчание всё ещё молчание ($answer)', () {
          expect(cases, isNot(contains(deed)),
              reason: 'ветвь для $deed завели, а таблица всё ещё числит его '
                  'молчащим — поправить строку и закрыть находку');
        });
      } else {
        // «Обработано вне switch» доказывается ОТСУТСТВИЕМ ветви: заведись
        // она, разбор пошёл бы двумя дорогами разом.
        test('$deed — ветви нет, разбирается иначе ($answer)', () {
          expect(cases, isNot(contains(deed)),
              reason: 'у $deed появилась ветвь, а таблица говорит, что он '
                  'разбирается в другом месте — теперь их два');
        });
      }
    }

    // ДОЛГ НАЗВАН ЧИСЛОМ, А НЕ ОЩУЩЕНИЕМ (I40: знаменатель обязателен).
    //
    // **11.09 ЭТО ЧИСЛО СТАЛО НУЛЁМ, и вердикт переписан, а не снят.**
    // Снять его было бы худшим из возможных: «молчащих не осталось» и
    // «сторож перестал их считать» дают один и тот же зелёный вывод, а
    // отличить их нечем — у нуля нет отличительного значения (I37).
    //
    // Поэтому ноль стоит **вместе со знаменателем и с составом**: пятнадцать
    // поступков разобраны, **восемь** своей ветвью, семь вне `switch`, ноль
    // молчащих. Сложение названо вслух (I13): 8 + 7 + 0 ≠ 15 покраснеет.
    //
    // **ЗДЕСЬ СТОЯЛО «ПЯТЬ», И ЭТО ПОЙМАЛ САМ ВЕРДИКТ 11.09** — число
    // осталось от редакции, где ветвей было пять, а починка N214/N215/N216
    // довела их до восьми. Ровно тот случай, ради которого разбиение и
    // складывается вслух: два числа порознь правдоподобны, ловит их только
    // арифметика между ними и третьим местом.
    test('молчащих НОЛЬ при 15; ветвей 8, но ЖИВЫХ из них 2', () {
      final silent = _coverage.entries
          .where((e) => e.value.startsWith(_silent))
          .map((e) => e.key)
          .toSet();
      final withCase = _coverage.entries
          .where((e) => e.value == _case)
          .map((e) => e.key)
          .toSet();
      final elsewhere = _coverage.entries
          .where((e) => e.value.startsWith(_elsewhere))
          .map((e) => e.key)
          .toSet();

      expect(silent, isEmpty,
          reason: 'молчащие снова появились: $silent. Это не обязательно '
              'поломка — но обязательно решение, и у него должен быть '
              'номер находки');
      final inert = _coverage.entries
          .where((e) => e.value == _inert)
          .map((e) => e.key)
          .toSet();
      // ЖИВЫХ ВЕТВЕЙ ДВЕ ИЗ ВОСЬМИ, и число стоит здесь, а не в прозе,
      // потому что проза не краснеет. Живая — та, у которой можно назвать
      // кнопку: «Ləğv et» и «Yenə də davam edirik».
      expect(withCase, {'ownerCancelled', 'restored'});
      expect(inert.length, 6);
      expect(withCase.length + inert.length, 8);
      expect(elsewhere.length, 7);
      // Третье место, где то же число считается иначе, — сам каталог.
      expect(silent.length + withCase.length + inert.length + elsewhere.length,
          deeds.length);
      expect(deeds.length, 15);
    });
  });
}
