import 'dart:io';

/// Чтение исходника для текстовых сторожей — одно на всех.
///
/// **Два дефекта, найденных обходом сторожей 07.08, и оба лечатся здесь,
/// а не в каждом стороже по отдельности:**
///
/// 1. **Слепота к кавычкам.** Сторож искал `'members'` с одинарными, а
///    `"members"` для Dart — ровно то же самое. То есть он был слеп
///    наполовину: тот, кто напишет ключ двойными, пройдёт насквозь.
///    Проверено прогоном по живому файлу: одинарные ловятся, двойные —
///    нет.
/// 2. **Спотыкание о собственный разбор** (I12). Сторож считает
///    вхождения, а рядом лежит комментарий, объясняющий, чего нельзя
///    делать, — и он же попадает в счёт. Пример из того же обхода: я
///    испортил файл строкой-КОММЕНТАРИЕМ, и сторож «одна дорога»
///    сработал, хотя кода не прибавилось.
///
/// Поэтому текст для сторожа берётся отсюда: без комментариев и с
/// кавычками, сведёнными к одному виду.
String readCode(String path) {
  final raw = File(path).readAsStringSync();
  final withoutComments = raw
      .split('\n')
      .where((l) {
        final t = l.trimLeft();
        return !t.startsWith('//');
      })
      .join('\n');
  // Двойные кавычки — те же одинарные. Сводится ПОСЛЕ снятия
  // комментариев, чтобы разбор дефекта в тексте не влиял ни на что.
  return withoutComments.replaceAll('"', "'");
}

/// То же, но строками — для сторожей, которым нужен номер строки.
List<String> readCodeLines(String path) => readCode(path).split('\n');
