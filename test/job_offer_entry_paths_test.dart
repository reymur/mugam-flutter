import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

// ДОРОГА К ПРЕДЛОЖЕНИЮ РАБОТЫ ИЗ ЧАТА — ОДНА.
//
// 14.08 строка «İş təklif et» переехала из меню «⋮» в шапке чата в лист
// вложений, и старая снята ТЕМ ЖЕ ЗАХОДОМ. Сторож стоит затем, что снятие
// нечем удержать: вернуть строку в шапку — три строки кода, и выглядеть это
// будет совершенно безобидно.
//
// ПОЧЕМУ ЭТО ВАЖНЕЕ, ЧЕМ КАЖЕТСЯ. Два пути к одной операции в этом проекте
// чинились уже не раз (N35, N40, `leaveGroup`/`removeGroupMember`, две
// дороги в чат), и каждый раз один из путей молча делал не то: расходились
// они не сразу, а тогда, когда правку внесли в один и забыли про второй.
//
// СТОРОЖ УТВЕРЖДАЕТ ЧИСЛО, ЗНАЧИТ САМ СЕБЕ КАНАРЕЙКА (I31): ослепни разбор
// — он насчитает ноль, ноль не равен единице, тест покраснеет. Молча
// позеленеть он не умеет. Плюс отдельная канарейка на сам обход: пять
// вызывающих общей точки — число, снятое `grep -rn "proposeJobOffer(" lib`
// 14.08, и оно же держит вторую половину правила.

List<File> _dartFiles() => Directory('lib')
    .listSync(recursive: true)
    .whereType<File>()
    .where((f) => f.path.endsWith('.dart'))
    .toList();

/// СУЖЕНО ДО КОДА С ПЕРВОГО ПРОГОНА, И ЭТО НЕ ПРЕДОСТОРОЖНОСТЬ — ЗАМЕР.
///
/// Первая редакция считала фразу по всему файлу и насчитала **29 при одной
/// настоящей**: подпись пункта неизбежно стоит в комментариях, которыми эта
/// самая работа и объясняется (только в `chat_screen.dart` — 10 упоминаний,
/// из них код одно). Это I12 дословно: сторож, сравнивающий текст,
/// спотыкается о разбор того самого дефекта, который сторожит. Лечится тем
/// же, чем у сторожа цветов, — комментарии снимаются до разбора.
String _code(File f) => f
    .readAsStringSync()
    .split('\n')
    .map((l) {
      final i = l.indexOf('//');
      return i == -1 ? l : l.substring(0, i);
    })
    .join('\n');

int _countIn(List<File> files, String needle) =>
    files.fold(0, (sum, f) => sum + needle.allMatches(_code(f)).length);

void main() {
  test('дорога к предложению работы из чата ровно одна', () {
    final files = _dartFiles();
    expect(
      files.length,
      greaterThan(100),
      reason: 'обход не видит исходников — считать нечего',
    );

    // СЧЁТ ПО ФАЙЛУ ЧАТА, А НЕ ПО ВСЕМУ `lib`, и первая редакция ошибалась
    // именно здесь: она требовала одного вхождения на всё приложение и
    // насчитала три. Все три законны — это три РАЗНЫХ входа (главный экран,
    // чат, карточка музыканта), и подпись у них общая по делу. Требование
    // же — про чат: одна дорога В ЧАТЕ, а не одна на приложение.
    final chat = files.firstWhere(
      (f) => f.path.endsWith('chat_screen.dart'),
    );
    expect(
      'İş təklif et'.allMatches(_code(chat)).length,
      1,
      reason: 'В чате пункт «İş təklif et» должен быть ровно один. Появился '
          'второй — значит старую дорогу в шапке вернули «пока пусть будет».',
    );

    // И он живёт в листе вложений, а не где-то ещё.
    expect(_countIn(files, "ValueKey('attach-job-offer')"), 1);
  });

  test('все входы зовут ОДНУ точку, и их пять', () {
    final files = _dartFiles();
    final callers = files
        .where((f) => f.readAsStringSync().contains('proposeJobOffer(context'))
        .map((f) => f.path.split('/').last)
        .toList()
      ..sort();

    // СОСТАВ, А НЕ КОЛИЧЕСТВО (I13): недосчитать список незаметно нельзя,
    // он сам называет, кого не хватает. Пятеро поимённо — снято
    // `grep -rn "proposeJobOffer(" lib` 14.08.
    expect(callers, [
      'agreements_screen.dart',
      'chat_screen.dart',
      'day_screen.dart',
      'home_screen.dart',
      'user_profile_screen.dart',
    ]);
  });
}
