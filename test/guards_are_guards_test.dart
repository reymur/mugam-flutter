import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

// МЕХАНИЗМ ВМЕСТО ВНИМАТЕЛЬНОСТИ — два сторожа над сторожами.
//
// Повод: 07.08 правило «сторож обязан проверять ВЫЗОВ, а не наличие»
// было выведено и через час нарушено трижды подряд его же автором. Четыре
// таких случая за сутки (I10, конвейер, I14, этот), и общее у всех одно:
// **правило есть, механизма нет**. Значит либо механизм, либо честное
// «его не существует» — но не обещание быть внимательнее.
//
// Здесь два, и они закрывают РАЗНОЕ. Чего они не закрывают — сказано в
// третьем разделе, прямо в этом файле, чтобы на них не полагались шире.

void main() {
  group('1. Объявление без вызова ловит анализатор', () {
    // Проверено на живом случае 07.08: снял вызов
    // `_buildSelectedDayAnswer` из сборки экрана — анализатор сказал
    // «The declaration isn't referenced» (unused_element). То есть на
    // «написан, но не подключён» механизм В ЯЗЫКЕ УЖЕ ЕСТЬ, он просто не
    // был воротами: предупреждения никто не читал.
    //
    // Здесь они становятся воротами. Медленно (несколько секунд), зато
    // это единственная проверка, которая ловит дефект в БОЕВОМ коде, а
    // не в тексте теста.
    // СУДИТ КОД ВОЗВРАТА, А НЕ ТЕКСТ — переписано 07.08.
    //
    // Прежняя редакция считала строки со словами `warning •` и `error •`.
    // Это I14 внутри собственного сторожа: сменись формат вывода — строк
    // не найдётся, и «предупреждений нет» станет неотличимо от «я разучился
    // их узнавать». Зелено и бесполезно.
    //
    // Ключ — `--no-fatal-infos`. Голый `flutter analyze lib` возвращает 1
    // и на чистом дереве: у нас 37 замечаний уровня `info`, и они приняты.
    // То есть код возврата без этого флага severity не различает вовсе.
    // Замерено 07.08, обе стороны:
    //   чисто                       → 0
    //   один мёртвый приватный метод → 1 + «The declaration … isn't referenced»
    // Текст теперь идёт только в сообщение об ошибке и ни на что не влияет.
    //
    // ГРАНИЦА, ЗАПИСАННАЯ ЗДЕСЬ ПО РЕШЕНИЮ ВЛАДЕЛЬЦА 29.08 (N185).
    //
    // **Этот сторож смотрит `lib` и НЕ смотрит `test`.** Аргумент в вызове
    // ниже — один, и это не описка: он про БОЕВОЙ код, а не про тесты.
    // Сломанный тестовый файл он пропускает молча, и «зелёный сторож
    // анализатора» не означает «в тестах чисто».
    //
    // **Почему это стоит здесь, а не в реестре.** Читают не реестр, а вызов;
    // а вызов выглядит полным — `flutter analyze` с аргументом, который
    // легко принять за «весь проект». Записано в шапке, чтобы следующий не
    // опёрся на сторожа шире, чем тот умеет: сторож, на который полагаются
    // шире его возможностей, опаснее отсутствующего.
    //
    // **Расширять на `test/` НЕ НАДО СЕЙЧАС — это отдельная работа**
    // (решение владельца 29.08). Причина не в лени: у тестового дерева свои
    // замечания и свой уровень шума, и включить его воротами — значит
    // сперва разобрать этот шум, иначе сторож покраснеет на чистом дереве и
    // будет снят целиком вместе с верной частью (I25).
    //
    // **Родня — тот же класс на стороне функций:** `tsc` там читает только
    // `src`, а тесты собирает `ts-jest` в момент прогона. Ворота выкладки
    // из-за этого 29.08 переведены с `npm run build` на `npm test`; сам
    // `pretest: tsc` решением владельца НЕ трогается — он отвечает на «прод
    // собирается», и это верный вопрос. Опасен был не он, а чтение его
    // зелёного как «и тесты в порядке».
    test('в lib/ нет предупреждений анализатора', () {
      final r = Process.runSync(
        'flutter',
        ['analyze', '--no-fatal-infos', 'lib'],
      );
      final out = '${r.stdout}${r.stderr}';

      // Соседка к самому запуску: код возврата 0 честен, только если
      // анализатор правда отработал. Не запустись он вовсе — молчание
      // было бы таким же нулём.
      expect(
        RegExp(r'issues found|No issues found').hasMatch(out),
        isTrue,
        reason: 'flutter analyze не отчитался ни одной итоговой строкой — '
            'похоже, он не запускался. Вывод:\n$out',
      );

      expect(
        r.exitCode,
        0,
        reason: 'Анализатор ругается, и среди его слов бывает единственное '
            'свидетельство того, что работа не доделана: '
            '«The declaration \'_x\' isn\'t referenced» — метод написан и '
            'никем не зовётся. Так 07.08 дважды прошла правка, где сторож '
            'проверял НАЛИЧИЕ метода, а вызова уже не было:\n$out',
      );
    }, timeout: const Timeout(Duration(minutes: 3)));
  });

  group('2. Сторож, довольный одним лишь объявлением', () {
    // Прямая проверка той ошибки, что была допущена трижды:
    // `screen.contains('_имяМетода(')` истинно уже потому, что метод
    // ОБЪЯВЛЕН в том же файле. Такой сторож не может провалиться при
    // снятом вызове — I9, только про сторожа.
    // Разрешённые места — с причиной у каждого, а не «известное
    // исключение». Здесь стог сена НЕ ФАЙЛ, а маленький кусок,
    // выдранный из него: в такой строке объявления метода быть не может
    // по построению, и сторож в ней проверяет ровно то, что написано.
    // КЛЮЧ — ФАЙЛ И ИМЯ, А НЕ НОМЕР СТРОКИ. Прежде было `путь:строка`, и
    // 07.08 это сломалось само: правка выше по файлу сдвинула строки, и
    // список перестал совпадать. Красный от сдвига — полбеды, он громкий.
    // Беда вторая и тихая: на освободившийся номер может СЪЕХАТЬ ДРУГАЯ
    // строка и молча получить чужое разрешение. Имя не съезжает.
    const allowed = <String, String>{
      'test/event_edit_test.dart:participantUids':
          'стог вообще не исходник, а множество ключей В ПАМЯТИ '
          '(`kEventDocKeys`): это обычная проверка состава, не текстовый '
          'сторож',
      'test/source_invariants_test.dart:arrayRemove':
          'не вердикт, а ФИЛЬТР внутри обхода: стог — одна строка файла, и '
          'совпадение лишь отбирает её в кандидаты, судит же следующая '
          'проверка',
      'test/source_invariants_test.dart:partnerName':
          'вердикт обратный — `isFalse`, «имени тут быть не должно». Мимо '
          'дефекта: он про «имя есть, значит вызвано». Рядом стоит соседка '
          '`rows isNotEmpty` (I13), поэтому пустой разбор не пройдёт молча',
      // Прежнее изъятие `_findUser` снято: с расширением сторожа на голое
      // имя оно перестало совпадать вовсе — там `contains('_findUser(')`,
      // со скобкой, то есть уже правильная форма.
    };

    test('в текстовых сторожах нет contains по голому имени', () {
      final offenders = <String>[];
      for (final f in Directory('test').listSync(recursive: true)) {
        if (f is! File || !f.path.endsWith('.dart')) continue;
        if (f.path.endsWith('guards_are_guards_test.dart')) continue;
        final lines = f.readAsStringSync().split('\n');
        for (var i = 0; i < lines.length; i++) {
          final l = lines[i];
          if (l.trimLeft().startsWith('//')) continue;
          // РАСШИРЕНО 07.08 с приватных имён на любые. Прежняя редакция
          // смотрела только на `_имя`, и слепой оставалась ПОЛОВИНА
          // пространства имён: `gate.contains('resolveStartPath')` проходил
          // насквозь, хотя это ровно тот же дефект — имя УПОМЯНУТО, а не
          // вызвано. Форма «голый идентификатор целиком в кавычках»:
          // `contains('name(')` и `contains('a == b')` не ловятся намеренно,
          // они и есть правильное лечение.
          final m =
              RegExp(r"\.contains\(\s*'([A-Za-z_]\w*)'\s*\)").firstMatch(l);
          if (m != null && !allowed.containsKey('${f.path}:${m.group(1)}')) {
            offenders.add('${f.path}:${i + 1}: ${m.group(1)}');
          }
        }
      }
      expect(
        offenders,
        isEmpty,
        reason: 'Сторож доволен одним лишь УПОМИНАНИЕМ имени (с 07.08 — '
            'любого, не только приватного): '
            'оно есть в файле всегда, вызова там может уже не быть. '
            'Считать вхождения (`allMatches(...).length >= 2`) или искать '
            'место вызова:\n${offenders.join('\n')}',
      );
    });
  });

  group('3. Чего эти двое НЕ ловят — сказано здесь, а не выяснится потом', () {
    test('список слепых зон записан рядом со сторожами', () {
      // Не проверка кода, а место, где границы нельзя не прочитать:
      // сторож, на который полагаются шире его возможностей, опаснее
      // отсутствующего.
      //
      // 1. ПУБЛИЧНЫЕ имена в БОЕВОМ коде. `unused_element` молчит про
      //    них: публичный метод может звать кто угодно снаружи, и
      //    анализатор этого не знает. Сторож №2 с 07.08 закрывает лишь
      //    половину дыры — он ловит публичное имя в ТЕКСТЕ ТЕСТА
      //    (`contains('resolveStartPath')`), но написанный и никем не
      //    зовомый публичный метод в `lib/` по-прежнему не ловит НИКТО.
      // 2. ВЫЗОВ ЕСТЬ, А ТОЛКУ НЕТ. Метод зовётся, виджет строится — и
      //    не ставится в дерево, или ставится под `if`, который никогда
      //    не истинен. Оба сторожа скажут «всё на месте».
      // 3. СТОРОЖ, СЛИШКОМ УЗКИЙ ПО ФОРМЕ. `const DayScreen()` против
      //    `Expanded(child: DayScreen())` — то же самое для человека и
      //    разное для текста. **Механизма на это не существует**: узнать
      //    из текста, какие написания равнозначны, нельзя. Единственное,
      //    что это ловит, — проверка возвратом, то есть порча живого
      //    файла и прогон. Она и поймала все три случая 07.08.
      expect(true, isTrue);
    });
  });
}
