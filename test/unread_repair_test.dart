import 'dart:async';

import 'package:flutter_test/flutter_test.dart';
import 'package:mugam_flutter/core/chat/unread_repair.dart';

import 'support/source_text.dart';

// ЯВНАЯ ПОЧИНКА ЗАЛИПШЕГО СЧЁТЧИКА — вторая половина N246.
//
// До 18.09 починка была побочным действием пустой перерисовки раз в двадцать
// секунд: решение принималось внутри `build`, а повторить неудавшуюся запись
// мог только будильник, потому что сама запись отказ проглатывала.
//
// ЧЕГО ЭТИ ВЕРДИКТЫ НЕ ДОКАЗЫВАЮТ. Они про решение и заслонку. Что починка
// ВЫЗВАНА из нужного места и что человек увидел на карточке правильное число
// — это сторож по исходникам ниже и глаза на трубке (I55).

void main() {
  group('чей счётчик', () {
    test('мой, а не чужой', () {
      // Поле — карта на ОБЩЕМ документе чата. Сложи все записи, и получишь
      // чужое непрочитанное вместе со своим.
      final meta = {
        'unreadCount': {'me': 3, 'other': 7},
      };
      expect(myUnreadCount(meta, 'me'), 3);
      expect(myUnreadCount(meta, 'other'), 7);
    });

    test('поля нет вовсе — ноль, а не отказ', () {
      expect(myUnreadCount(const <String, dynamic>{}, 'me'), 0);
      expect(myUnreadCount(null, 'me'), 0);
    });

    test('моей записи в карте нет — ноль', () {
      expect(myUnreadCount({'unreadCount': {'other': 4}}, 'me'), 0);
    });

    test('чужой тип в поле — ноль, а не падение', () {
      // Документ чата пишут трое: наш клиент, наш сервер и правка руками в
      // консоли. Жёсткое приведение здесь падало бы на чужой записи (I49);
      // умолчание безвредно ровно потому, что ноль значит «чинить нечего».
      expect(myUnreadCount({'unreadCount': 5}, 'me'), 0);
      expect(myUnreadCount({'unreadCount': {'me': 'три'}}, 'me'), 0);
    });

    test('uid пуст — ноль', () {
      expect(myUnreadCount({'unreadCount': {'': 9}}, ''), 0);
    });
  });

  group('чинить или нет', () {
    test('счётчик больше нуля и есть кому чинить — ЧИНИТЬ', () {
      expect(shouldRepairUnread(unread: 1, uid: 'me'), isTrue);
    });

    test('счётчик ноль — НЕ чинить, в этом сходимость', () {
      // Без этого починка звала бы себя по каждому снимку вечно: запись
      // меняет документ, документ даёт снимок, снимок зовёт починку.
      expect(shouldRepairUnread(unread: 0, uid: 'me'), isFalse);
    });

    test('uid пуст — не чинить', () {
      expect(shouldRepairUnread(unread: 5, uid: ''), isFalse);
    });
  });

  group('заслонка «запись в полёте»', () {
    test('пока запись летит, второй не начинают', () async {
      final gate = UnreadRepairGate();
      final hold = Completer<void>();
      var writes = 0;

      final first = gate.run('chat-1', () {
        writes++;
        return hold.future;
      });
      expect(gate.inFlightCount, 1);

      final second = await gate.run('chat-1', () async => writes++);
      expect(second, isFalse, reason: 'вторая запись начата поверх летящей');
      expect(writes, 1);

      hold.complete();
      expect(await first, isTrue);
    });

    test('другой чат не ждёт чужой записи', () async {
      // Заслонка на ЧАТ, а не на всё приложение: иначе один медленный чат
      // задерживал бы починку во всех остальных.
      final gate = UnreadRepairGate();
      final hold = Completer<void>();
      unawaited(gate.run('chat-1', () => hold.future));

      expect(await gate.run('chat-2', () async {}), isTrue);
      hold.complete();
    });

    test('после успеха заслонка снята — следующий снимок пишет снова',
        () async {
      final gate = UnreadRepairGate();
      var writes = 0;
      expect(await gate.run('chat-1', () async => writes++), isTrue);
      expect(gate.inFlightCount, 0);
      expect(await gate.run('chat-1', () async => writes++), isTrue);
      expect(writes, 2);
    });

    testWidgets('ПОСЛЕ ОТКАЗА ЗАСЛОНКА СНЯТА — следующий снимок пишет снова',
        (tester) async {
      // ГЛАВНЫЙ ВЕРДИКТ ЭТОЙ РАБОТЫ, и вот почему.
      //
      // Прежняя заслонка ставилась ДО записи и при отказе не снималась. Одна
      // неудачная запись закрывала чат от повторной попытки — и починить его
      // мог только будильник, который для этого и стоял. Ровно ту же цену
      // назвал `_recordDeliveries`, когда заводил у себя откат пометки.
      //
      // `testWidgets` здесь не украшение: обычный `test` считает незамеченным
      // исключением любой отказ, пойманный не сразу, а этот вердикт про то,
      // что отказ ВИДЕН вызывающему.
      final gate = UnreadRepairGate();
      var writes = 0;

      await expectLater(
        gate.run('chat-1', () async {
          writes++;
          throw StateError('запись не прошла');
        }),
        throwsStateError,
        reason: 'отказ проглочен — вызывающему нечем узнать, что надо снова',
      );
      expect(gate.inFlightCount, 0,
          reason: 'после отказа заслонка осталась: чат закрыт от повторной '
              'попытки до конца сессии, и вернуть его может только будильник '
              '— тот самый, который эта работа снимает');

      expect(await gate.run('chat-1', () async => writes++), isTrue);
      expect(writes, 2);
    });
  });

  group('сторож: служба не глотает отказ', () {
    // ВСЕ ТРИ ВЕРДИКТА УТВЕРЖДАЮТ НАЛИЧИЕ, значит каждый сам себе канарейка
    // (I31): ослепни разбор — он даст ноль, ноль не равен ожидаемому, сторож
    // покраснеет в тот же заход.
    //
    // ЧЕГО ОНИ НЕ ЛОВЯТ, поимённо:
    //
    // 1. НЕ ПРОВЕРЯЮТ ПОВЕДЕНИЕ БАЗЫ. Что `update` и правда пишет ноль —
    //    здесь не проверяется ничем: службу без подделки Firestore не
    //    позвать. Это глаза на трубке и замер прода.
    // 2. НЕ ЛОВЯТ ТРЕТЬЕГО ЧИТАТЕЛЯ. Появись у счётчика ещё один обнулятель
    //    мимо этого метода — разбор пройдёт мимо.
    // 3. СРЕЗ ПО ИМЕНАМ-ГРАНИЦАМ. Уехавшая за границу половина тела
    //    оставила бы сторожа зелёным про огрызок (N104), поэтому в срезе
    //    проверяются ОБА конца: и заслонка в начале, и отказ в конце.
    // 4. НЕ ПРОВЕРЯЮТ, ЧТО СЛУШАТЕЛЬ СРАБАТЫВАЕТ НА ПЕРВОМ СНИМКЕ. Вся
    //    починка держится на том, что `ref.listen` зовёт обработчик при
    //    переходе провайдера из загрузки в данные, — то есть на поведении
    //    Riverpod, а не нашего кода. Сломайся оно при обновлении
    //    зависимости, счётчик перестал бы чиниться при входе в чат, и ни
    //    один вердикт здесь этого не заметит. **Проверяется глазами:**
    //    войти в чат с ненулевым числом на карточке и увидеть, что оно
    //    пропало (в проде на 18.09 таких чатов шесть — замер в N247).

    const service = 'lib/firebase/firestore_service.dart';

    String resetBody() {
      final code = readCode(service);
      final from = code.indexOf('Future<bool> resetUnreadCount(');
      expect(from, greaterThan(-1),
          reason: 'метода с таким именем в службе нет — разбор ослеп либо '
              'метод переименован');
      // `\n  }\n`, а НЕ `\n  }` — граница, на которой срез обрывался молча.
      // Список параметров закрывается строкой `  }) async {`, и короткий
      // образец находил именно её: срез выходил в четыре строки, обе
      // проверки ниже краснели «нет заслонки, нет отказа», хотя в коде было
      // и то и другое. Поймали оба конца среза, ради чего они и стоят (N104).
      final to = code.indexOf('\n  }\n', from);
      expect(to, greaterThan(from), reason: 'конец тела метода не найден');
      return code.substring(from, to);
    }

    test('СЛУЖБА ОТВЕЧАЕТ, А НЕ МОЛЧИТ: возвращает bool, не void', () {
      // Прежняя подпись была `Future<void>`, и в этом всё дело: у
      // вызывающего не было признака, по которому пробовать снова, и
      // единственным повтором оказался будильник раз в двадцать секунд.
      final code = readCode(service);
      expect(code.contains('Future<bool> resetUnreadCount('), isTrue);
      expect(code.contains('Future<void> resetUnreadCount('), isFalse,
          reason: 'подпись вернулась к молчаливой — вместе с ней вернётся и '
              'нужда в будильнике');
    });

    test('починка идёт через заслонку «запись в полёте»', () {
      expect(resetBody().contains('_unreadRepairGate.run('), isTrue,
          reason: 'обнуление пошло мимо заслонки: две записи подряд на один '
              'чат снова возможны');
    });

    test('ОСТЫВАНИЕ ПРЕВЬЮ ОТКАТЫВАЕТСЯ ПРИ ОТКАЗЕ', () {
      // ВТОРОЙ НАХЛЕБНИК ТОГО ЖЕ ТАЙМЕРА, и в реестре N246 он назван не был
      // — там записано «третье дело» в единственном числе. Болезнь у него та
      // же: отметка остывания ставится до вызова и при отказе оставалась
      // стоять, закрывая чат от повторной попытки на тридцать секунд.
      //
      // Перевести счётчик и снять таймер, не тронув превью, значило бы молча
      // ослабить вторую починку — ровно то, про что N246 и заведена.
      final code = readCode('lib/firebase/firestore_service.dart');
      final from = code.indexOf('Future<void> refreshChatPreviewIfStale(');
      expect(from, greaterThan(-1), reason: 'метода нет — разбор ослеп');
      final to = code.indexOf('\n  }\n', from);
      expect(to, greaterThan(from), reason: 'конец тела метода не найден');
      final body = code.substring(from, to);
      expect(body.contains('httpsCallable('), isTrue,
          reason: 'КАНАРЕЙКА: в срезе нет самого вызова, значит срез не тот '
              'или не целый (N104)');
      expect(body.contains('_lastPreviewRefreshAt.remove(chatId);'), isTrue,
          reason: 'откат остывания снят: неудавшийся вызов снова закрывает '
              'чат на тридцать секунд, а вернуться к нему нечем — таймера '
              'больше нет');
    });

    const screen = 'lib/features/chat/screens/chat_screen.dart';

    /// Срез слушателя `chatMetaProvider` — от его начала до закрывающей
    /// строки того же отступа.
    String listenerBody() {
      final code = readCode(screen);
      final from = code.indexOf('ref.listen(chatMetaProvider(');
      expect(from, greaterThan(-1),
          reason: 'слушателя снимка в экране чата нет — починку опять ведёт '
              'что-то другое, либо разбор ослеп');
      final to = code.indexOf('\n    });', from);
      expect(to, greaterThan(from), reason: 'конец тела слушателя не найден');
      return code.substring(from, to);
    }

    test('ПОЧИНКУ ВЕДЁТ СЛУШАТЕЛЬ СНИМКА, а не build', () {
      // Весь смысл второй половины N246. Пока решение принималось внутри
      // `build`, повторить его могла только пустая перерисовка по таймеру.
      final body = listenerBody();
      expect(body.contains('resetUnreadCount('), isTrue,
          reason: 'слушатель есть, а обнуления в нём нет');
      expect(body.contains('shouldRepairUnread('), isTrue,
          reason: 'правило снова написано на месте, а не позвано из '
              'core/chat/unread_repair.dart');
    });

    test('ОБНУЛЕНИЕ ЗОВЁТСЯ РОВНО ОДИН РАЗ, и это тот самый вызов', () {
      // Считается СОСТАВ, а не наличие (I13): второй вызов, добавленный
      // где-нибудь в `build`, вернул бы ровно ту дорогу, которую эта работа
      // убирает, и «вызов есть» об этом промолчало бы.
      final code = readCode(screen);
      final calls = 'resetUnreadCount('.allMatches(code).toList();
      expect(calls.length, 1,
          reason: 'обнуление счётчика зовётся ${calls.length} раз(а) вместо '
              'одного — вторая дорога к тому же полю расходится молча');
      expect(listenerBody().contains('resetUnreadCount('), isTrue,
          reason: 'единственный вызов оказался не в слушателе');
    });

    test('ПУСТОГО `setState` ПО ТАЙМЕРУ В ЭКРАНЕ ЧАТА НЕТ', () {
      // Ради этого всё и делалось. Утверждение ОТСУТСТВИЯ, значит рядом
      // канарейка (I31): ослепни разбор — он даст ноль, ноль и есть искомое,
      // и сторож зазеленеет собственной слепотой.
      //
      // ПОЧЕМУ ИМЕННО `Timer.periodic`, а не «таймер вообще»: одиночные
      // `Timer` в этом файле законны и нужны — отложенное стирание
      // сообщения (`_purgeTimers`), гашение подсветки, заслонка «печатает».
      // Запрет на них покраснел бы на здоровом (I14).
      final screenCode = readCode(screen);
      expect('Timer.periodic'.allMatches(screenCode).length, 0,
          reason: 'в экран чата вернулась перерисовка по расписанию. Она '
              'обслуживает ВСЁ, что зависит от повторного захода в build, и '
              'список подопечных не называет — так и потерялись три дела из '
              'четырёх (N246)');
      expect(
        'Timer.periodic'
            .allMatches(readCode('lib/core/time/stale_clock.dart'))
            .length,
        1,
        reason: 'КАНАРЕЙКА: тот же разбор не видит таймера там, где он '
            'заведомо есть, — значит и «в экране чата его нет» он доказать '
            'не может',
      );
    });

    test('ограничителя по часам больше нет', () {
      // Утверждение ОТСУТСТВИЯ, значит рядом канарейка (I31): тот же разбор
      // обязан найти соседнее поле-гвард, которое в файле заведомо есть.
      //
      // ИЩЕТСЯ ОБЪЯВЛЕНИЕ С ТИПОМ, А НЕ ГОЛОЕ ИМЯ, и это не стиль: голое имя
      // есть в файле всегда — хотя бы в комментарии, объясняющем, почему
      // поля больше нет, — и сторож на нём доволен упоминанием вместо
      // предмета. Форму подсказал сам прогон: `guards_are_guards_test`
      // покраснел на первой редакции этого вердикта.
      final code = readCode(screen);
      expect(code.contains('DateTime? _lastUnreadRepairAt;'), isFalse,
          reason: 'ограничитель на пять секунд вернулся — а он был нужен '
              'только потому, что починка жила в build');
      expect(code.contains('String? _lastMarkedReadMsgId;'), isTrue,
          reason: 'КАНАРЕЙКА: разбор не видит соседнего поля-гварда, которое '
              'в файле есть, — значит и «ограничителя нет» он не доказывает');
    });

    test('ОТКАЗ ВОЗВРАЩАЕТСЯ ОТКАЗОМ', () {
      // Второй конец среза — он же доказательство, что срез целый.
      expect(resetBody().contains('return false;'), isTrue,
          reason: 'отказ снова выдаётся за успех: вызывающий не узнает, что '
              'чинить придётся снова');
    });
  });
}
