/// ОБОДОК ИСТОРИИ ВОКРУГ ПОРТРЕТА — ПРАВИЛО, ОБА НАЖАТИЯ И СВОИ ЧАСЫ В ОДНОМ
/// МЕСТЕ.
///
/// **Работа 18.09, та же болезнь и то же лечение, что у кружка «в сети».**
///
/// --- ЧТО БЫЛО ДО ---
///
/// Решение «есть ли у человека живая история» было написано РУКАМИ в
/// одиннадцати местах десяти файлов (замер 18.09: `grep -rn "hasActiveStatus"
/// lib` — 48 строк, из них 6 комментарии и 1 объявление). Сам ободок при этом
/// ОДИН — `AvatarRing`, свёрнут 16.09, копий нет. То есть общей была картинка,
/// а размножено было правило и поведение вокруг неё: развилка, обход к
/// просмотрщику, длинное нажатие, подписка зовущего на свой профиль.
///
/// Слипались эти одиннадцать копий молча, и вот чем это стоило: правило «у
/// СЕБЯ ободок не золотой» было соблюдено в ДВУХ местах из одиннадцати
/// (профиль и участник группы), а в остальных девяти своя история светилась
/// золотом, как чужая непросмотренная. Заметить это было нечем: каждое место
/// по отдельности выглядит правильным.
///
/// --- ПОЧЕМУ У ОБОДКА СВОИ ЧАСЫ ---
///
/// `User.hasActiveStatus` сравнивает `mostRecentStatusExpiresAt` с
/// `DateTime.now()`: ответ зависит от ВРЕМЕНИ, а не только от данных. Поток
/// Firestore перерисовывает экран, лишь когда меняется документ, — от того,
/// что просто идёт время, он не сработает ни разу. Значит истёкшая история
/// оставалась бы с ободком до тех пор, пока не изменится документ или человек
/// не откроет экран заново.
///
/// Это и держало на себе два таймера, которые 18.09 едва не сняли, приняв за
/// таймеры кружка (`about_contact_screen`, `chat_screen`). Теперь часы внутри
/// виджета: вставил ободок — обновление пришло с ним само, забыть его негде.
///
/// **Будильник ОБЩИЙ с кружком** — `StaleClock`, разбор там же. Своего срока
/// ободку не нужно (история живёт сутки, двадцать секунд опоздания не значат
/// ничего), а свой будильник означал бы ДВА таймера на одном портрете: в
/// девяти местах из одиннадцати кружок и ободок сидят на одной фотографии.
///
/// --- ПОЧЕМУ ЗДЕСЬ, А НЕ В `shared/widgets` РЯДОМ С `AvatarRing` ---
///
/// Виджет сам открывает просмотр истории, то есть импортирует
/// `UserStatusViewerScreen`. Общему слою тянуть за собой экран возможности —
/// перевёрнутая слоёность: `shared` обязан быть тем, что можно взять, не взяв
/// с собой пол-приложения. `AvatarRing` остаётся в `shared`, потому что он
/// ровно картинка и ничего не открывает.
///
/// --- ЧТО ЭТОТ ВИДЖЕТ НЕ РЕШАЕТ ---
///
/// Он не отвечает за то, ГДЕ стоит и что лежит рядом: `Stack`, `Positioned`,
/// кружок «в сети» остаются у зовущего. И он не решает, показывать ли себя
/// вовсе, — в списке чатов у группы портрет не человека, и туда его просто не
/// ставят.
class StatusRing extends StatelessWidget {
  /// Человек, чей портрет рисуется. **Пустого принимает нарочно**: в шести
  /// местах из одиннадцати живой документ ещё не приехал, и там стояло
  /// `user?.hasActiveStatus == true`. Пусто — ветвь «истории нет».
  final User? user;

  /// Мой uid. Нужен на три вещи сразу: подписаться на мой профиль (в нём
  /// лежит отметка «когда я в последний раз смотрел этого человека»), передать
  /// его просмотрщику и **отличить себя** — см. `hasUnviewed` ниже.
  final String currentUid;

  /// Поперечник всего портрета вместе с ободком. У всех одиннадцати это
  /// `размер * 1.2`, но само число разное: 36, 40, 44, 46, 48, 58, 96, 140.
  final double size;

  /// Запасной знак, когда фотографии нет. Обеим ветвям он ОДИН и тот же.
  final String? fallbackEmoji;

  /// ВИД ВЕТВИ «ИСТОРИИ НЕТ» — и только её.
  ///
  /// **Почему именно эта ветвь настраивается, а вторая нет.** Сверены все
  /// одиннадцать мест (18.09): ветвь «история есть» у них ДОСЛОВНО одинакова,
  /// отличается только размером; ветвь «истории нет» у каждого своя — где
  /// ободка нет вовсе (`ringWidth: 0`), где он `kBorder` толщиной 1, 1.5 или
  /// 3, где золотой у отмеченного человека, где золотой у выбранного в списке.
  ///
  /// То есть общее здесь — ПРАВИЛО и ПОВЕДЕНИЕ, разное — вид одной ветви. Оно
  /// и переносится параметрами, а не приводится к одному виду: приведение
  /// молча изменило бы вид одиннадцати экранов, чего владелец не просил.
  final Color? plainRingColor;

  /// Толщина ободка в ветви «истории нет». **Ноль означает «ободка нет»** —
  /// так стоит у четырёх из одиннадцати. Умолчание 2.5 — умолчание самого
  /// `AvatarRing`.
  final double plainRingWidth;

  /// Размер запасного знака в ветви «истории нет».
  ///
  /// **Тоже только у этой ветви, и это не недосмотр.** В ветви «история есть»
  /// ни одно из одиннадцати мест его не задавало — там знак берёт умолчание
  /// `AvatarRing` (`size * 0.45`), а в ветви «истории нет» прибит числом: 16,
  /// 18, 20, 24, 48, 64. Уравняй их — изменился бы вид там, где его не
  /// трогали.
  final double? plainFallbackFontSize;

  const StatusRing({
    super.key,
    required this.user,
    required this.currentUid,
    required this.size,
    this.fallbackEmoji,
    this.plainRingColor,
    this.plainRingWidth = 2.5,
    this.plainFallbackFontSize,
  });

  @override
  Widget build(BuildContext context) {
    // ЧАСЫ СНАРУЖИ, ПОДПИСКА НА ПРОФИЛЬ ВНУТРИ — порядок именно такой.
    //
    // `AnimatedBuilder` даёт удар часов: по нему всё ниже пересчитывается со
    // свежим `DateTime.now()`, ничего не читая из базы. Отписка при этом не
    // пишется вовсе — её делает он сам.
    //
    // `Consumer` внутри, а не `ConsumerWidget` снаружи, потому что `ref`
    // берётся там, где он и используется: взяв его снаружи, пришлось бы
    // звать `ref.watch` из чужого построителя.
    return AnimatedBuilder(
      animation: StaleClock.instance,
      builder: (context, _) => Consumer(builder: _ring),
    );
  }

  Widget _ring(BuildContext context, WidgetRef ref, Widget? _) {
    final u = user;
    // ПРАВИЛО ОДНО И ЖИВЁТ В МОДЕЛИ (`models.dart`). Здесь оно только
    // спрашивается — второго написания срока годности в проекте нет, и заводить
    // его руками нельзя: разошлись бы два ответа на один вопрос.
    if (u == null || !u.hasActiveStatus) {
      final photo = u?.photoURL;
      return GestureDetector(
        onTap: photo != null ? () => showFullImage(context, photo) : null,
        child: AvatarRing(
          photoURL: photo,
          fallbackEmoji: fallbackEmoji,
          hasUnviewed: false,
          size: size,
          ringColor: plainRingColor,
          ringWidth: plainRingWidth,
          fallbackFontSize: plainFallbackFontSize,
        ),
      );
    }

    // У СЕБЯ ОБОДОК НИКОГДА НЕ ЗОЛОТОЙ.
    //
    // **Выводится из данных, переключателя не требует** — и в этом всё дело.
    // До 18.09 правило жило у зовущих флагами (`!isMe`, `!isOwnProfile`) и
    // было соблюдено в двух местах из одиннадцати; здесь оно действует на всех
    // одиннадцать, потому что вопрос «это я?» виджет задаёт сам.
    //
    // Смысл: золото значит «есть что посмотреть впервые». Своя история
    // просмотрена по определению — её только что выложил тот, кто смотрит.
    final isMine = u.id == currentUid;
    // Подписка на свой профиль берётся ТОЛЬКО когда она и правда нужна: у
    // истёкшей истории и у своей собственной спрашивать нечего, а лишний
    // слушатель на каждой строке списка — это лишний слушатель на каждой
    // строке списка.
    final viewer = isMine ? null : ref.watch(currentUserProvider(currentUid)).value;
    final hasUnviewed = !isMine && (viewer?.hasUnviewedStatusFrom(u) ?? false);

    void openStatusViewer() => Navigator.push(
          context,
          MaterialPageRoute(
            builder: (_) => UserStatusViewerScreen(
              ownerUid: u.id,
              currentUid: currentUid,
              initialUser: u,
            ),
          ),
        );

    return GestureDetector(
      onTap: openStatusViewer,
      onLongPress: () => showAvatarLongPressMenu(
        context,
        photoURL: u.photoURL,
        onViewStatus: openStatusViewer,
      ),
      child: AvatarRing(
        photoURL: u.photoURL,
        fallbackEmoji: fallbackEmoji,
        hasUnviewed: hasUnviewed,
        size: size,
      ),
    );
  }
}
