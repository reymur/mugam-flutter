/// ЗАНЯТОСТЬ ДЛЯ СЕТОК, ГДЕ ЧЕЛОВЕК ВЫБИРАЕТ ДНИ — и, что важнее, ответ на
/// вопрос, знаем ли мы её вообще.
///
/// Один поставщик на оба листа: `JobOfferAnswerSheet` (музыкант отмечает, на
/// какие дни может) и `JobOfferDaysSheet` (работодатель набирает дни
/// предложения). Оба выбирали вслепую до 25.08, и починка у них общая, потому
/// что вопрос общий — свои занятые дни; расходятся листы только в том, что
/// рисуют, и это остаётся у них (I58: общей становится часть до расхождения).
///
/// --- ГЛАВНОЕ ЗДЕСЬ — НЕ ЗАНЯТОСТЬ, А РАЗЛИЧЕНИЕ ТРЁХ СОСТОЯНИЙ ---
///
/// Пустая сетка читается как «всё свободно», то есть как утверждение, которого
/// мы не делали. Поэтому у ответа две части: набор дней И признак [BusyDays.known].
///
///   • **не знаем** — любой из двух потоков ещё не ответил ИЛИ отказал, либо
///     uid пуст. Дней ноль, [BusyDays.known] — `false`, лист говорит это
///     словами ([kBusyUnknownLine]);
///   • **знаем, занятых нет** — оба потока ответили, набор пуст. Лист молчит:
///     молчание значит «посмотрели, предупреждать не о чем»;
///   • **знаем, занятые есть** — клетки покрашены, лист поясняет, что выбрать
///     их всё равно можно ([kBusyPickableLine]).
///
/// **Признак незнания механический: `asData == null` у ОБОИХ потоков** — а не
/// «список пуст». Приём взят у `agreements_screen.dart:3702` вместе с доводом:
/// документ приходит владельцу одним потоком, второй стороне — другим, и
/// решить по одному пришедшему значит соврать половине людей. Здесь то же
/// самое: свои вечера идут первым потоком, чужие — вторым, и половина
/// занятости выглядит как вся.
///
/// **Второй признак, глубже, уже стоит в самих потоках:** пустой снимок ИЗ
/// КЭША они не отдают вовсе (`firestore_service.dart:3607` и `:3626`, правило
/// N14). Значит `asData != null` означает «сервер ответил либо в кэше есть
/// настоящие данные», а не «Firestore что-то пробормотал»: пустая сетка от
/// офлайнового старта не появится, провайдер останется в загрузке.
///
/// --- ОТКАЗ ПОТОКА СЛИТ С ЗАГРУЗКОЙ НА ЭКРАНЕ, И ЭТО РЕШЕНИЕ ВЛАДЕЛЬЦА 25.08 ---
///
/// Довод дословно: **отдельная строка на отказ объясняет человеку нашу
/// поломку, а не его дело.** Сторона слияния безопасная — отказ правил или
/// обрыв связи дают «не знаем», а не «свободно» (I14).
///
/// **Но различие не потеряно в коде** (I47): отказ отличим от загрузки прямо
/// здесь, `hasError` рядом с `asData`, и если однажды понадобится своё слово —
/// добавится оно, не трогая расчёта. **Записано долгом:** отказ этих двух
/// потоков сегодня не виден никому — ни человеку, ни нам; станет частым, узнаем
/// не от приложения (`AUDIT_TODO.md`, долг рядом с N160).
///
/// --- ПУСТОЙ uid — «НЕ ЗНАЕМ», А НЕ «СВОБОДЕН» ---
///
/// `viewerUid` в листе предложения имеет третью ветвь `''`
/// (`job_offer_sheet.dart:266-269`), и она переворачивает замысел молча.
/// `dayRoleOf` при пустом uid считает занятым ВСЁ (`day_role.dart:181`) —
/// ложная тревога, видная сразу. Но запрос `where('ownerUid', isEqualTo: '')`
/// вернёт **ноль документов**, значит на выходе вышел бы пустой набор с видом
/// «знаем: всё свободно» — то есть ровно наоборот, тихо и в опасную сторону.
/// Поэтому пустой uid отвечается «не знаем» ДО потоков.
library;

import 'package:flutter_riverpod/flutter_riverpod.dart';

import '../../core/agreements/occupied_days.dart';
import '../../core/job_offer/offer_draft.dart';
import '../../firebase/firestore_service.dart';
import '../../firebase/models.dart';

/// «Твои занятые дни пока не показываются». Одна строка на оба листа: сказать
/// это двумя копиями значит дать им разойтись в первой же правке (N66 — брать
/// именем, а не копией).
const String kBusyUnknownLine = 'məşğul günlərin hələ göstərilmir';

/// «Занятые дни тоже можно выбрать». Занятость — сведения, а не преграда:
/// две работы в один вечер бывают законны, и решает человек.
const String kBusyPickableLine = 'məşğul günləri də seçə bilərsən';

/// Ответ поставщика: какие дни заняты И знаем ли мы это.
///
/// **Два поля, а не одно, и слить их нельзя ни в какую сторону** (I47).
/// Пустой набор без [known] отвечал бы на два разных вопроса одинаково: «я
/// свободен» и «мы не смотрели». Первое — сведения, второе — молчание, и
/// человек, отмечающий дни, поступает по ним по-разному.
class BusyDays {
  /// Знаем: вот эти дни заняты, и вот чем (карта может быть и пустой — это
  /// ответ «занятых нет», а не отсутствие ответа).
  const BusyDays(this.eventsByDay) : known = true;

  /// Не знаем: потоки молчат, отказали, либо спрашивать не за кого.
  const BusyDays.unknown() : eventsByDay = const {}, known = false;

  /// Занятые сутки → вечера, которые их занимают. Ключ — запись `2026-08-25`,
  /// та же, какой сетка спрашивает про клетку (`isoDay`).
  ///
  /// **Вечера лежат здесь, а не рядом отдельным набором дат**, потому что два
  /// поля разъехались бы: набор сказал бы «занято», список оказался бы пуст, и
  /// каждое выглядело бы правильным порознь.
  final Map<String, List<PersonalEvent>> eventsByDay;

  /// Ответ вообще состоялся.
  final bool known;

  /// Занятые дни — для сетки, которой нужен только ответ «красить или нет».
  Set<String> get days => eventsByDay.keys.toSet();

  /// Чем занят этот день. Пусто — день свободен **или** мы не знаем; кто
  /// спрашивает про показ, различает это по [known].
  List<PersonalEvent> on(String isoDay) =>
      eventsByDay[isoDay] ?? const <PersonalEvent>[];
}

/// Занятые дни человека [uid] для сеток выбора.
///
/// **`Provider`, а не расчёт в виджете, ровно ради проверяемости:** правило
/// внутри `build` не достаётся ни одному тесту (та же причина, по которой в
/// `core` уехали `agreementCardState` и `conflictEventsOnDay`). Здесь его
/// можно подменить, прочитать и испортить.
///
/// **Семейство по uid и без `autoDispose` — как у самих потоков**
/// (`firestore_service.dart:4164-4174`): подписка на календарь уже жива, если
/// в этой сессии открывали календарь или дневной экран, и лист присоединяется
/// к ней даром. Не открывали — это ровно один запрос, тот же самый.
///
/// **Подписка на ВЕСЬ календарь, а не на месяц, и выбора тут нет:** оба потока
/// идут без `limit` и без диапазона дат. Поэтому листание сеток по месяцам
/// (`answer-month-prev/next`, `offer-month-prev/next`) не стоит ни одного
/// чтения и не заводит нового состояния загрузки на каждый месяц.
final busyDaysProvider = Provider.family<BusyDays, String>((ref, uid) {
  // ДО ПОТОКОВ, а не после: см. «пустой uid» в шапке файла.
  if (uid.isEmpty) return const BusyDays.unknown();

  final own = ref.watch(personalEventsProvider(uid));
  final asParticipant = ref.watch(eventsAsParticipantProvider(uid));

  // ЖДЁМ ОБОИХ. `asData == null` — это и загрузка, и отказ; оба означают «не
  // знаем», и оба обязаны выглядеть так, а не пустым календарём.
  if (own.asData == null || asParticipant.asData == null) {
    return const BusyDays.unknown();
  }

  return BusyDays({
    for (final entry in occupiedEventsByDayOf(
      own: own.asData!.value,
      asParticipant: asParticipant.asData!.value,
      uid: uid,
    ).entries)
      isoDay(entry.key): entry.value,
  });
});
