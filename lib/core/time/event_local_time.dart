/// Время мероприятия из строки `date` — ОДНО правило на показ и на
/// раскладку по дням.
///
/// **Зачем отдельной функцией, а не двумя разборами по месту.** Дневной
/// экран решает, в какой день попадёт мероприятие, а карточка показывает
/// его час. Разойдись эти два разбора — и человек увидит карточку под
/// заголовком «Sabah» со временем сегодняшнего вечера, причём каждая
/// сторона по отдельности выглядела бы правильной (ровно N58).
///
/// **Два формата в проде, перепись 07.08 по 72 мероприятиям:**
/// - **56** — плавающее гражданское время, `2026-08-28T16:00:00.000`.
///   Toy в 16:00 остаётся в 16:00 там, где он проходит, независимо от
///   того, в каком поясе стоит телефон смотрящего. Это и есть замысел,
///   записанный в `az_date_format.dart`.
/// - **13** — момент в UTC, `2026-06-30T05:41:41.000Z`. Пишет их не эта
///   сборка: все 13 созданы 25–28 июня, самое свежее мероприятие без `Z`
///   — вчерашнее. Формат легаси, но записи живы.
/// - **3** — с микросекундами, разбираются как плавающие.
///
/// **Почему 13 записей нельзя оставить как есть.** `DateTime.parse` на
/// строке с `Z` возвращает момент в UTC, и `.hour` у него — час по
/// Гринвичу. В Баку это −4 часа: мероприятие, показанное как «21:00»,
/// на деле в 01:00 СЛЕДУЮЩЕГО дня. На экране-дне это не косметика, а
/// попадание в чужие сутки.
///
/// Сегодня все 13 в прошлом, и дневной экран смотрит вперёд — то есть
/// прямо сейчас они его не задевают. **Но это везение, а не свойство**
/// (решение владельца 07.08: считать условием правильности, а не
/// отдельной находкой): пока `mugam-v2` жив (N62), запись такого формата
/// может появиться снова, и появится она сразу в будущем.
///
/// Правило: строка с `Z` — настоящий момент, приводится к местному
/// времени; строка без `Z` — плавающее время, разбирается как есть.
/// Неразбираемая строка даёт `null`, а не «сегодня»: мероприятие без
/// даты не должно всплывать сегодняшним.
DateTime? eventLocalDateTime(String iso) {
  if (iso.isEmpty) return null;
  final parsed = DateTime.tryParse(iso);
  if (parsed == null) return null;
  return parsed.isUtc ? parsed.toLocal() : parsed;
}

/// Календарные сутки мероприятия — то, по чему оно раскладывается на
/// дневном экране. Часы отброшены, поэтому сравнение суток не зависит от
/// времени внутри них.
DateTime? eventDay(String iso) {
  final d = eventLocalDateTime(iso);
  return d == null ? null : DateTime(d.year, d.month, d.day);
}
