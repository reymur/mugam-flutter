import 'dart:async';

import 'package:flutter/foundation.dart';

/// ОДИН БУДИЛЬНИК НА ВСЁ, ЧТО ПРОТУХАЕТ ОТ ХОДА ВРЕМЕНИ.
///
/// --- ЗАЧЕМ ОН НУЖЕН ВООБЩЕ ---
///
/// Есть вопросы, ответ на которые зависит не только от данных, но и от
/// ВРЕМЕНИ: «в сети ли человек» (`User.isActuallyOnline` сравнивает `lastSeen`
/// с `DateTime.now()`) и «жива ли его история» (`User.hasActiveStatus`
/// сравнивает `mostRecentStatusExpiresAt` с `DateTime.now()`). Поток Firestore
/// перерисовывает экран, лишь когда меняется ДОКУМЕНТ; от того, что просто
/// идёт время, он не сработает ни разу. Значит показанное замирает на том,
/// каким было в миг открытия: человек вышел минуту назад, а кружок всё
/// зелёный; история истекла в полдень, а ободок горит до вечера.
///
/// Лечится это пустой перерисовкой по таймеру. Пока таймер живёт ОТДЕЛЬНО от
/// того, что он оживляет, его надо помнить и заводить руками у каждого
/// зовущего — а забыть его нечем: замерший кружок выглядит точно так же, как
/// живой, и расходятся они только со временем. Так и вышло: 18.09 при одном
/// живом таймере в проекте было **десять замерших кружков в восьми файлах**.
///
/// Поэтому таймер прячется ВНУТРЬ виджета, которому он нужен, а сюда выносится
/// то, что у всех таких виджетов общее, — сам будильник.
///
/// --- ПОЧЕМУ ОДИН НА ВСЕХ, А НЕ ПО ОДНОМУ НА ВИДЖЕТ ---
///
/// На экране со списком бывает два десятка портретов, и на каждом сидят и
/// кружок, и ободок. Личный таймер у каждого не был бы бедой по нагрузке
/// (перерисовка ПУСТАЯ: ни одного нового чтения из базы), но дал бы две
/// настоящие беды: каждый считал бы от своего рождения и мигал бы вразнобой,
/// и выключать их пришлось бы в сорока местах.
///
/// Здесь будильник заводится, когда появляется ПЕРВЫЙ слушатель, и снимается,
/// когда уходит ПОСЛЕДНИЙ. Зовущий об этом не знает и знать не должен.
///
/// --- СЛЕДУЮЩЕМУ, КТО ПРИДЁТ СЮДА С ТРЕТЬИМ ДЕЛОМ ---
///
/// Сюда захочется посадить «был в сети 5 минут назад» (шаг — минута) или
/// обратный отсчёт до начала вечера (шаг — секунда), и первым побуждением
/// будет завести второй таймер со своим шагом. **Правильный ответ — один
/// будильник, а кому нужно реже, тот считает удары.** Два будильника на одном
/// экране означают два несогласованных мига перерисовки и два места, где
/// можно забыть отписку; ради более редкого шага это не окупается никогда.
/// Кому нужно ЧАЩЕ двадцати секунд — тому нужен не этот будильник, а свой
/// внутри своего виджета, и тогда разница обязана быть записана здесь.
///
/// --- ПОЧЕМУ `ChangeNotifier`, А НЕ СВОЙ СПИСОК СЛУШАТЕЛЕЙ ---
///
/// Это стандартный путь Flutter, и он снимает то, что в своём списке
/// приходится держать руками: пара `addListener`/`removeListener` у зовущего
/// не пишется вовсе — её делает `AnimatedBuilder`. Забытая отписка при своём
/// списке роняла десять вердиктов из одиннадцати (замер порчей 18.09), то есть
/// стоила ровно того, чего стоит любое «не забыть».

/// Через сколько будильник бьёт.
///
/// **Одно число на весь проект, и это его смысл.** Возьми каждое место своё —
/// один и тот же человек гас бы в чате и горел в списке, и различить это было
/// бы нечем.
///
/// Двадцать секунд выбраны по самому быстрому из подписчиков — кружку «в
/// сети»: он обязан погаснуть в пределах десятков секунд после протухания
/// отметки, а само сердцебиение и так пишется раз в 30 секунд
/// (`PresenceService._heartbeatInterval`). Ободку истории такая частота не
/// нужна вовсе — история живёт сутки, — но **свой, более редкий будильник ему
/// не заводится**: см. абзац о третьем деле выше.
const Duration staleClockInterval = Duration(seconds: 20);

/// Будильник для всего, что протухает само по себе.
///
/// Слушают его через `AnimatedBuilder(animation: StaleClock.instance, …)` —
/// тогда отписка не пишется руками и не может быть забыта.
class StaleClock extends ChangeNotifier {
  StaleClock._();

  static final StaleClock instance = StaleClock._();

  Timer? _timer;

  /// Слушатели, известные нам ПОИМЁННО, в добавление к списку самого
  /// `ChangeNotifier`.
  ///
  /// Свой список тут не дублирование, а плата за две вещи, которых у
  /// `ChangeNotifier` нет: он не отдаёт ни числа слушателей (только
  /// `hasListeners`), ни возможности отпустить всех разом — а второе нужно
  /// сбросу перед вердиктом (см. [resetForTest]).
  final List<VoidCallback> _listeners = <VoidCallback>[];

  /// Сколько будильников заведено ЗА ВСЮ ЖИЗНЬ, а не сколько сейчас.
  ///
  /// Считается ради одного вердикта, и повод записан замером: проверка «сейчас
  /// заведён один» держится на поле `_timer`, а поле остаётся непустым и после
  /// того, как сам таймер умер вместе со своей зоной. Значит поле отвечает на
  /// «просили ли завести», а не на «сколько их живёт», и завести двадцать штук
  /// оно бы не заметило. Счётчик отвечает прямо.
  int timersStarted = 0;

  int get listenerCount => _listeners.length;

  bool get isRunning => _timer != null;

  @override
  void addListener(VoidCallback listener) {
    super.addListener(listener);
    _listeners.add(listener);
    if (_timer == null) {
      _timer = Timer.periodic(staleClockInterval, (_) => notifyListeners());
      timersStarted++;
    }
  }

  @override
  void removeListener(VoidCallback listener) {
    super.removeListener(listener);
    _listeners.remove(listener);
    if (_listeners.isEmpty) {
      _timer?.cancel();
      _timer = null;
    }
  }

  /// Только для вердиктов: вернуть будильник в состояние «никого нет».
  ///
  /// Нужен потому, что будильник ОДИН НА ВСЁ ПРИЛОЖЕНИЕ — то самое свойство,
  /// ради которого он и заведён. В проде это благо, а в прогоне означает, что
  /// вердикты видят чужой след: у каждого теста своя зона времени, а поля
  /// общие, и оставшийся от соседа таймер молча не даёт завести новый. Без
  /// сброса половина вердиктов проверяла бы порядок их объявления.
  @visibleForTesting
  void resetForTest() {
    _timer?.cancel();
    _timer = null;
    for (final listener in _listeners.toList()) {
      super.removeListener(listener);
    }
    _listeners.clear();
    timersStarted = 0;
  }
}

/// Сколько будильников сейчас заведено: 0 или 1, и никогда больше.
@visibleForTesting
int get staleClockTimerCount => StaleClock.instance.isRunning ? 1 : 0;

/// Сколько виджетов сейчас слушает общий будильник.
@visibleForTesting
int get staleClockListenerCount => StaleClock.instance.listenerCount;

/// Сколько будильников заведено с начала прогона (или с последнего сброса).
@visibleForTesting
int get staleClockTimersStarted => StaleClock.instance.timersStarted;

/// Сбросить общий будильник перед вердиктом.
@visibleForTesting
void staleClockResetForTest() => StaleClock.instance.resetForTest();
