/// Единое соглашение о том, как в этом проекте записывается **момент
/// времени** в поле-строку (N4).
///
/// Всегда UTC с суффиксом `Z`. Раньше все такие поля писались как
/// `DateTime.now().toIso8601String()` — без смещения, то есть строка
/// «13:00» не несла в себе, чьи это 13:00. Пока писатель и читатель в
/// одном часовом поясе, всё сходится; как только они расходятся, момент
/// восстанавливается неверно на разницу поясов.
///
/// Это не теория: 02.08 сторонний скрипт записал `recipientAgreedAt` по
/// UTC, приложение читало отметку «просмотрено» в локальном — сравнение
/// «новее ли сигнал» дало ложь, и поздравительное окно у инициатора
/// просто не появилось. Молча.
///
/// Самое дорогое последствие того же класса — `deletedAt`: по нему
/// заводится таймер на пять минут, после которого сообщение удаляется
/// **безвозвратно**, причём таймер работает у обеих сторон, и срабатывает
/// тот, чей раньше. При читателе западнее писателя разница уходит в
/// минус, `remaining` становится нулём — и удаление происходит
/// немедленно вместо пяти минут.
///
/// ---
///
/// **Почему UTC-строка, а не `FieldValue.serverTimestamp()`**, хотя
/// серверное время авторитетнее (не зависит ещё и от неверных часов
/// устройства):
///
/// 1. Серверная метка — сентинел: до подтверждения сервером клиент видит
///    `null`. А отсечка `clearedBy` читается синхронно, до первого кадра
///    экрана чата — на этом построена вся защита Этапа 4. Пустое значение
///    там вернуло бы состояние «не знаю», которое оттуда как раз убирали
///    (N13).
/// 2. Меняется тип на проводе (String → Timestamp), то есть переписывать
///    пришлось бы не только запись, но и всё чтение и локальное
///    хранилище.
/// 3. Ломается офлайн: клиентское время пишется сразу, серверное — нет.
///
/// UTC-строка чинит ровно то, что сломано — потерянный часовой пояс, — не
/// трогая ни тип, ни модель доверия. Зависимость от часов устройства
/// остаётся; это отдельная, гораздо большая задача.
///
/// ---
///
/// **Чтение править не требуется.** `DateTime.tryParse` для строки с `Z`
/// возвращает момент в UTC, а `isAfter`/`isBefore`/`difference` сравнивают
/// абсолютные мгновения независимо от флага `isUtc`. По той же причине
/// безопасно и переходное окно: старая сборка понимает `Z`, а новая
/// читает строку без смещения как локальную — и в одном поясе получает
/// верный момент.
///
/// **А вот отображать полученный момент надо через `.toLocal()`** —
/// `DateFormat.format` рисует то, что ему дали, и UTC-момент покажет
/// временем UTC (см. `_formatInfoTime` в message_info_screen.dart).
///
/// ---
///
/// **Чего сюда приводить НЕЛЬЗЯ.** Есть второй класс времени —
/// «плавающее» гражданское: дата и час события (`eventDate` на чате,
/// `date` у договора). Свадьба в 20:00 остаётся в 20:00, даже если
/// участник улетел в другой пояс; это не момент на оси, а запись в
/// календаре. Перевод такого значения в UTC сдвинет показанное время при
/// смене пояса, то есть создаст баг там, где его нет. Эти поля
/// намеренно остаются локальными — см. запрет в реестре (N4).
String nowInstantIso() => DateTime.now().toUtc().toIso8601String();
