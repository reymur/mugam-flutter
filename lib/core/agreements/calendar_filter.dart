/// ФИЛЬТР КАЛЕНДАРЯ — шаг 5 работы «договоры и мероприятия — одна сущность»
/// (`docs/plan.md`).
///
/// **Что происходит: вкладка «Müqavilələr» превращается в ФИЛЬТР.** Сегодня
/// договоры живут отдельным списком со своим отбором (`e.isAgree`) и своей
/// сортировкой; после этого шага тот же набор виден внутри календаря, без
/// ухода на другой экран.
///
/// **Отбор вынесен сюда, а не написан в экране, по той же причине, что и
/// правила конфликта:** его читают ДВА места — сетка месяца и содержимое
/// выбранного дня, — и разойдись они, ошибки не возникнет нигде: просто в
/// сетке день будет помечен, а под сеткой пусто. Заметить это можно только
/// глазами, и однажды так уже было (N74).
///
/// **Вкладка при этом ОСТАЁТСЯ и работает как раньше — до конца работы.**
/// Пока фильтр не сверен с ней составом, она единственная дорога к договорам,
/// и снести её значило бы остаться без обеих при первой же ошибке.
library;

import '../../firebase/models.dart';

/// Что показывает календарь.
enum CalendarFilter {
  /// Всё подряд — договоры и обычные мероприятия вперемешку. Это нынешнее
  /// поведение, и оно остаётся умолчанием.
  all,

  /// Только договоры. Тот же признак, по которому отбирает вкладка
  /// «Müqavilələr», — иначе два места ответят по-разному на один вопрос.
  agreements,
}

/// Отобрать по фильтру.
///
/// **Признак ровно один — `isAgree`, и он тот же, что у вкладки.** Соблазн
/// написать здесь «умнее» (по наличию `partnerUid`, по `agreementChatId`)
/// надо назвать и отвергнуть: сверка после этого шага делается СОСТАВОМ
/// против вкладки, и любое расхождение в признаке превратит проверку в спор
/// о том, кто прав, вместо ответа «одно и то же или нет».
///
/// Пустой список фильтр не выдумывает: `all` возвращает то же самое, что
/// получил. Копия не делается — вызывающий список не правит.
List<PersonalEvent> applyCalendarFilter(
  List<PersonalEvent> events,
  CalendarFilter filter,
) =>
    switch (filter) {
      CalendarFilter.all => events,
      CalendarFilter.agreements => events.where((e) => e.isAgree).toList(),
    };

/// Надпись на переключателе. Слово «договор» здесь ЕЩЁ ЕСТЬ, и это временно.
///
/// По решению 10.08 оно уходит с экранов — но **после** сверки, а не вместе с
/// ней: поменяй мы разом и отбор, и надписи, при расхождении не разобрать, что
/// сместилось. Пока фильтр называется тем же словом, что вкладка, с которой
/// его сверяют.
String calendarFilterLabel(CalendarFilter filter) => switch (filter) {
      CalendarFilter.all => 'Hamısı',
      CalendarFilter.agreements => 'Müqavilələr',
    };
