/// ОТВЕТ УЧАСТНИКА — шаг 1 работы «договоры и мероприятия — одна сущность»
/// (`docs/plan.md`).
///
/// **На этом шаге поле НИКТО НЕ ЧИТАЕТ.** Оно пишется рядом с `musicians` и
/// ничего не меняет в поведении. Смысл отдельного шага — чтобы запись
/// поработала на живых данных задолго до того, как от неё начнёт что-то
/// зависеть: иначе первая настоящая запись пришлась бы на шаг 4, который
/// необратим (решение владельца 10.08, довод записан в плане).
///
/// ЗАЧЕМ ПОЛЕ ВООБЩЕ. Сегодня `musicians` несёт три службы разом: право
/// видеть (`isParty()` в правилах и запросы `arrayContains`), состав («кто
/// идёт») и занятость вечера. Решение «любое добавление — приглашение, в
/// состав только после согласия» разрывает первые две: приглашённый обязан
/// ВИДЕТЬ вечер, чтобы ответить, а в составе его ещё нет. Отсюда разделение:
///
///   `musicians` — кто ВИДИТ (доступ, плоский массив uid — не трогать),
///   `answers`   — кто ИДЁТ (карта uid → ответ).
///
/// **Почему `musicians` обязан остаться плоским массивом:** на нём стоят
/// правило чтения и запросы `where('musicians', arrayContains: uid)`, а
/// Firestore не умеет `arrayContains` по объектам и не фильтрует по ключам
/// карты. Список объектов сломал бы и доступ, и выборку разом.
library;

/// Три ответа участника. Значения — строки в документе, поэтому они здесь
/// ЛИТЕРАЛАМИ рядом с именем: проход по исходникам, сторожащий имена (как у
/// имён поступков в `firestore_service.dart`), читает литералы, и вынос
/// значения за константу сделал бы его невидимым ровно там, где он сторожит.
const String kAnswerGoing = 'going';
const String kAnswerWaiting = 'waiting';
const String kAnswerCant = 'cant';

/// ПЯТОЕ ЗНАЧЕНИЕ — «вышел из состава» (решение автора 12.08).
///
/// **Заменяет прежний выход через `musicians`.** Раньше участник вычёркивал
/// себя из состава, то есть менял ОБЩИЙ список; теперь он пишет свой ключ и
/// **остаётся в списке** — под именем стоит «İşdən çıxdı». Уход перестал быть
/// событием вечера и стал ответом человека: под вопросом один человек, а не
/// вечер.
const String kAnswerLeft = 'left';

/// Все допустимые ответы — одним местом, чтобы проверка «значение из набора»
/// не переписывалась в каждом читателе своими словами.
const Set<String> kEventAnswers = {
  kAnswerGoing,
  kAnswerWaiting,
  kAnswerCant,
  kAnswerLeft,
};

/// ЧЕТВЁРТОЕ СОСТОЯНИЕ — **читаемое, но никогда не записываемое** (шаг 4).
///
/// «Вопрос НЕ ЗАДАН» — не то же самое, что «задан, ответа нет». Оба без
/// `going`, но у них **разный адресат следующего хода**:
///
///   `notAsked` — действовать должен ВЛАДЕЛЕЦ: позвать по-настоящему;
///   `waiting`  — действовать должен ПРИГЛАШЁННЫЙ: ответить.
///
/// Показать первому «ждём ответа» — соврать владельцу, что он свою часть уже
/// сделал. Это **N99 в данных**: «отказался» и «не ответил» — разные вещи, и
/// экран, сливший их, врёт про ожидание.
///
/// **В карте его нет и быть не может: оно И ЕСТЬ отсутствие ключа.** Поэтому
/// оно не входит в [kEventAnswers] — тот набор про то, что бывает записано.
///
/// Заведено 11.08 после того, как первая редакция шага 4 сливала оба случая в
/// `waiting` — то есть нарушала I47 («свести два разных незнания к одному
/// ответу значит потерять возможность отличить поломку от нормы») на
/// следующий день после того, как I47 было записано.
const String kAnswerNotAsked = 'notAsked';

/// ОТМЕТКА: КАРТУ ЗАПОЛНЯЛ ВЛАДЕЛЕЦ — заведена 11.08 по N115.
///
/// **ИМЯ НАЗЫВАЕТ ПИСАТЕЛЯ, А НЕ СМЫСЛ, и это выбрано нарочно.** «Карта полна»
/// или «версия 2» описывают состояние — и следующий, увидев такое имя, спокойно
/// поставит отметку из любого места, где карта показалась ему полной, в том
/// числе из ответа участника. Имя `answersWrittenByOwner` этого сделать не даёт:
/// поставить его из участника — значит написать неправду прямо в поле.
///
/// **Ставят его РОВНО ТРИ писателя, все пишущие карту ЦЕЛИКОМ по составу:**
/// `addPersonalEvent` (создание), `eventEditUpdate` (правка состава) и сервер
/// `onChatUpdated` (рождение договора из согласия).
///
/// **УЧАСТНИК ПОСТАВИТЬ ЕГО НЕ МОЖЕТ — не по договорённости, а по выложенному
/// правилу.** `answersForSelf()` в `firestore.rules` требует
/// `changedKeys().hasOnly(['answers'])`: любое второе поле в той же записи, и
/// сервер отказывает целиком. Это проверено `assertFails` в
/// `functions/test/answers-rules.test.ts`.
const String kAnswersWrittenByOwner = 'answersWrittenByOwner';

/// ПРАВИЛО ШАГА 1: какой `answers` соответствует этому составу.
///
/// **Сегодня — все «идут», и это не заглушка, а честный перевод.** До
/// разделения смыслов «есть в `musicians`» и означало «идёт»: другого способа
/// оказаться в составе не было. Поэтому перевод старого смысла в новое поле —
/// не выдумка задним числом, а запись того же самого другими словами.
///
/// «Ждём» появится на шаге 4, когда добавление станет приглашением. Менять
/// это правило раньше нельзя: получится, что человек, которого владелец уже
/// вписал, вдруг «не подтвердил» — при том что подтверждать его никто не
/// просил.
///
/// **Состав ключей — РОВНО `musicians`, ни больше ни меньше.** Не «хотя бы
/// те»: лишний ключ — это ответ за того, кого в составе нет, а недостающий —
/// участник без ответа, то есть дырка, которую следующий читатель заполнит
/// догадкой.
///
/// Повторы в списке схлопываются сами (ключ карты один), пустые строки
/// отбрасываются: пустой uid не человек, и ключ из него сделал бы запись,
/// которую никому не сопоставить.
/// **ШАГ 4 ИЗМЕНИЛ ЭТУ ФУНКЦИЮ, и это единственная её редакция, у которой есть
/// прошлое.** Раньше она ставила `going` всем; теперь — сохраняет уже данные
/// ответы и ставит **`waiting` только НОВЫМ**.
///
/// Почему нельзя было раньше: до шага 4 добавление и означало согласие,
/// другого способа попасть в состав не было. Написать «ждём» тогда значило бы
/// объявить неподтверждённым того, кого никто и не спрашивал.
///
/// Почему нельзя иначе теперь: поставить `waiting` **всем** — стереть ответы
/// тех, кто уже ответил, при первой же правке состава. Человек сказал «не
/// могу», владелец поменял место — и человек снова «ждём».
///
/// **[ownerUid] — ВЛАДЕЛЕЦ СОГЛАСИЯ НЕ ДАЁТ, ОН ВЕЧЕР СОЗДАЛ** (решение
/// владельца 11.08, находка **N112**). У договоров владелец лежит в составе:
/// `onChatUpdated` кладёт обе стороны. Без этого различения правка состава
/// объявляла бы его ждущим ответа на собственном вечере — приложение
/// спрашивало бы человека, идёт ли он туда, куда сам всех позвал. Затронуто
/// **18 документов из 75** (16 договоров = 27 − 11 и 2 мероприятия = 48 − 46,
/// перепись прода 10.08).
///
/// **Умолчание владельца — `going`, но НЕ безусловная запись `going`.**
/// Прежний знакомый ответ владельца переносится наравне со всеми: когда у
/// него появится своя дверь выхода (N108), безусловное `going` затирало бы
/// его собственный ответ при каждой правке места — ровно тот дефект, от
/// которого перенос и заводился.
///
/// Пустой [ownerUid] не совпадёт ни с одним uid состава (пустые отброшены
/// строкой выше), поэтому «владельца не назвали» само собой значит «владельца
/// в этой записи нет» — отдельной ветки не требует.
/// **[previousParticipants] — ПОЧИНКА N114, и без неё перенос отменяет выход.**
///
/// Ключ ушедшего остаётся в карте: `leavesEvent()` разрешает трогать только
/// `musicians`, `lastActionBy` и `lastActionType`, и вычистить свой ответ
/// участник не может ничем. Пока он вне состава, ключ безвреден — `answerOf`
/// спрашивает сначала состав. **Но стоит владельцу пригласить его снова, и
/// прежний `going` переносится поверх выхода: человек возвращается уже
/// согласившимся, ничего не нажимая.**
///
/// Выход из чужого мероприятия — **самое сильное «нет», какое участник сегодня
/// может сказать**: другой двери у него нет вовсе (N106). Перенос отменяет это
/// решение **молча** и занимает его календарь без согласия — ровно то, ради
/// чего затевался шаг 4.
///
/// Поэтому условие переноса не «есть знакомый прежний ответ», а «есть знакомый
/// прежний ответ **И человек был в прежнем составе**». Вернувшийся получает
/// `waiting`, то есть его спрашивают заново; тот, кто из состава не уходил,
/// свой ответ сохраняет.
///
/// **`null` ОЗНАЧАЕТ «СВЕДЕНИЙ НЕТ», ПУСТОЙ СПИСОК — «СОСТАВ БЫЛ ПУСТ», И
/// ЛЕЧЕНИЯ У НИХ ПРОТИВОПОЛОЖНЫЕ** (N173, починено 28.08).
///
/// **Здесь стоял `List<String> previousParticipants = const []`, и это была
/// красная находка.** Пустой список читался как «не знаем» и переносил
/// прежние ответы; но пустым он бывает и по другой причине — **когда из
/// состава вышел последний участник**. Тогда `isEmpty` истинно, «остался»
/// становится истинным для всех подряд, и старое `going` переносится как
/// знакомое: Теймур зовёт Рафаэля заново, а у того вечер открывается **с уже
/// готовым согласием**, которого он второй раз не давал.
///
/// Доказательство было документом прода, а не рассуждением:
/// `pcop3dUyviw2v28AZKmb` — `musicians` пусто, `answers: Rafael = going`.
/// Согласие лежало у человека, которого в составе нет.
///
/// **Это I47 дословно:** два разных незнания сведены к одному ответу, и
/// сведение здесь не теряет сведения, а **выдумывает поступок**. Поэтому тип
/// стал `List<String>?`, и оба случая отвечают порознь:
///
///   • `null` — прежнего состава мы не знаем (старый документ, чужой
///     писатель): переносим по карте, как раньше;
///   • `[]` — состав был пуст, все ушли: **каждый отвечает заново**.
///
/// **ПАРАМЕТР ОБЯЗАТЕЛЬНЫЙ, А НЕ СО ЗНАЧЕНИЕМ ПО УМОЛЧАНИЮ, и это главная
/// часть починки.** Умолчание и было дырой: вызывающий, не подумавший о
/// прежнем составе, молча получал перенос — то есть самый опасный из двух
/// ответов. Теперь не подумать нельзя: компилятор не соберёт вызов без него.
Map<String, String> answersForParticipants(
  List<String> participantUids, {
  Map<String, dynamic>? previous,
  String ownerUid = '',
  required List<String>? previousParticipants,
}) {
  final out = <String, String>{};
  final wasInEvent = previousParticipants?.toSet();
  for (final uid in participantUids) {
    if (uid.isEmpty) continue;
    final was = previous?[uid];
    // Прежний ответ переносится, только если он ЗНАКОМЫЙ. Чужая строка —
    // мусор, а не ответ (I49: поле пишут трое, тип и значение гарантирует
    // не поле, а писатель), и наследовать её значило бы разносить порчу.
    //
    // **`kAnswerNotAsked` В НАБОР НЕ ВХОДИТ, И ДОБАВЛЯТЬ ЕГО СЮДА «ДЛЯ
    // ПОЛНОТЫ» НЕЛЬЗЯ.** Оговорка стоит здесь, а не только при самой
    // константе, потому что соблазн возникает именно в этой строке: рядом
    // перечислены четыре ответа, пятый напрашивается пятым.
    //
    // Он не ответ, а ВЫВОД: `notAsked` и есть отсутствие ключа, его никто
    // никогда не пишет, и `answerOf` выводит его из того, что ключа нет, а
    // отметка `answersWrittenByOwner` стоит. Внеси его в набор — и перенос
    // начнёт записывать в карту то, что означает «в карте этого нет»,
    // то есть утверждать отсутствие наличием.
    //
    // **Запрет держится не только этим текстом:** правило в `firestore.rules`
    // не принимает `notAsked` (список значений — `['going', 'waiting',
    // 'cant', 'left']`), и это проверено `assertFails` —
    // `functions/test/answers-rules.test.ts:224`, «НЕЛЬЗЯ записать notAsked —
    // оно И ЕСТЬ отсутствие ключа». Добавленный сюда, он дал бы отказ сервера
    // на первой же правке состава.
    final known = was is String && kEventAnswers.contains(was);
    // …и только если человек был в ПРЕЖНЕМ составе (N114). Ушедший и
    // приглашённый заново отвечает заново.
    //
    // **`wasInEvent == null`, А НЕ `wasInEvent.isEmpty`** — в этой замене вся
    // починка N173. `isEmpty` отвечал «да, остался» и тому, чьего состава мы
    // не знаем, и тому, чей состав опустел; второму он тем самым возвращал
    // согласие, которого человек не давал.
    final stayed = wasInEvent == null || wasInEvent.contains(uid);
    out[uid] = (known && stayed)
        ? was
        : (uid == ownerUid ? kAnswerGoing : kAnswerWaiting);
  }
  return out;
}

/// РАСХОЖДЕНИЕ ЗАПИСИ С СОСТАВОМ — шаг 2 (`docs/plan.md`).
///
/// **Это НЕ для экрана.** Экран спрашивает `answerOf` и получает ответ на
/// каждого человека; здесь считается другое — **сходится ли запись с
/// составом вообще**, и нужно это переписи, а не показу. Разделение
/// намеренное: там решают, что показать человеку, здесь — норма это или
/// поломка (I47).
///
/// **ОТСУТСТВИЕ ПОЛЯ РАСХОЖДЕНИЕМ НЕ СЧИТАЕТСЯ, а пустая карта считается.**
/// Это и есть решение 10.08, ради которого функция и заведена:
///
///   • `answers == null` — «сведений нет». Так писали до шага 1, так пишет
///     mugam-v2, так пишут старые сборки. Норма;
///   • `answers == {}` при непустом составе — **утверждение «в составе
///     никого» рядом с непустым составом**, то есть противоречие. Ни один
///     наш писатель такого не делает: и клиент, и сервер пишут карту
///     целиком по составу.
///
/// Свести их к одному ответу значило бы потерять возможность отличить
/// поломку от нормы — N13 в новом месте.
class AnswersMismatch {
  /// В составе есть, в карте нет. **Ожидаемо** от старых сборок и от
  /// mugam-v2 — они правят состав, не зная про поле (см. шаг 3 плана).
  final List<String> missing;

  /// Ключ есть, в составе нет. **Ожидаемо** от выхода из состава: правило
  /// `leavesEvent()` разрешает трогать только `musicians`, и ключ ушедшего
  /// остаётся.
  final List<String> extra;

  /// Карта записана пустой, а состав непуст. **Не ожидаемо ни от одного
  /// известного писателя** — единственный по-настоящему тревожный из трёх.
  final bool emptyWithPeople;

  const AnswersMismatch({
    required this.missing,
    required this.extra,
    required this.emptyWithPeople,
  });

  bool get isClean => missing.isEmpty && extra.isEmpty && !emptyWithPeople;
}

/// Считает расхождение. `null` в `answers` — не расхождение, а отсутствие
/// сведений (см. выше).
AnswersMismatch answersMismatch({
  required List<String> participantUids,
  Map<String, dynamic>? answers,
}) {
  if (answers == null) {
    return const AnswersMismatch(
      missing: [],
      extra: [],
      emptyWithPeople: false,
    );
  }
  final people = participantUids.where((u) => u.isNotEmpty).toSet();
  final keys = answers.keys.toSet();
  return AnswersMismatch(
    missing: people.difference(keys).toList()..sort(),
    extra: keys.difference(people).toList()..sort(),
    emptyWithPeople: answers.isEmpty && people.isNotEmpty,
  );
}

/// Ответ одного человека — с запасным путём на время, пока поля нет.
///
/// **Запасной путь обязателен и переживёт шаг 1:** у 75 записей прода поля
/// `answers` нет вовсе, и появится оно только у тех, что создадут или правят
/// после выкладки. Читать их иначе, чем новые, нельзя — на экране это был бы
/// один и тот же вечер с двумя разными ответами.
///
/// **КЛЮЧИ ВНЕ СОСТАВА НЕ СЧИТАЮТСЯ** (решение 10.08, `docs/plan.md`,
/// шаг 3). Вышедший из состава свой ключ в карте ОСТАВЛЯЕТ: правило
/// `leavesEvent()` разрешает трогать только `musicians`, `lastActionBy` и
/// `lastActionType`, и `answers` в этот набор не входит. Значит лишний ключ —
/// мусор, а не ответ, и спрашивать надо сначала состав.
///
/// **ИМЯ ПАРАМЕТРА — `participantUids`, как в модели, а не `musicians`, как в
/// базе.** Слово `musicians` в этом проекте означает пять разных вещей
/// (состав вечера, провайдер всех пользователей, пустая коллекция в правилах,
/// параметр карточки ленты, роль пользователя — N69), и самое частое из них
/// не роль, а состав. Имя берётся из модели: там поле давно зовётся
/// `participantUids`, и тест сторожит, чтобы в базу оно писалось под своим
/// именем `musicians`. **Соответствие: состав вечера = `musicians` в базе =
/// `participantUids` в модели.**
/// **ПЕРЕКЛЮЧАТЕЛЬ ШАГА 4 — НАЛИЧИЕ САМОЙ КАРТЫ. Здесь та самая строка, с
/// которой назад дороги нет** (`docs/plan.md`, шаг 4):
///
/// | Что в документе | Понимается как |
/// |---|---|
/// | карты НЕТ вовсе | по-старому: «в составе» значит «идёт» → `going` |
/// | карта есть, ключа нет | **`notAsked`** — его не спрашивали |
/// | ключ есть | его значение |
///
/// **Почему переключателем служит именно карта.** Она пишется ЦЕЛИКОМ по
/// составу и только новой сборкой, значит её наличие само и есть отметка, что
/// документ живёт по новым правилам. Дату использовать нельзя: у приглашённого
/// нет отметки времени вообще (N107 — снят живой документ, 19 ключей, ни
/// одного про участников во времени). Новое поле-версия не нужно: карта уже
/// эту службу несёт.
///
/// **Старые 75 документов не пострадали** — у них карты нет, работает первая
/// строка, все «идут». Задним числом никого в ждущие не переводим.
/// КАК ОТВЕТ НАЗЫВАЕТСЯ НА ЭКРАНЕ — шаг 4, пункт 2 (`docs/plan.md`).
///
/// **Почему это нужно ровно сейчас, а не раньше.** Пока ответ у всех один
/// (шаги 1–3), различать было нечего, и ярлык, одинаковый у каждого, был бы
/// вторым **N109** — строкой, которая занимает место и ничего не сообщает. С
/// шага 4 обратное: **не различать значит показать неответившего
/// согласившимся**, то есть соврать в ту самую сторону, ради которой работа и
/// затеяна.
///
/// **Четыре ответа, а не три.** `notAsked` держится отдельно от `waiting`
/// именно здесь, на экране, потому что у них разный адресат следующего хода:
/// «его не спрашивали» — дело владельца, «ждём» — дело приглашённого (I47).
/// Слить их значило бы сказать владельцу, что он свою часть уже сделал.
///
/// **Цвета здесь нет намеренно.** Различие несёт слово. Красный на этих
/// экранах уже означает три разные вещи (**N110**), а палитра ломает
/// собственное правило (**N111**); обе находки уехали в работу о форме
/// статуса, и красить «не может» красным сейчас значило бы завести своими
/// руками то, что мы там же и осудим (I51).
///
/// Пустая строка на всё незнакомое — включая `null`. Он означает «человека
/// нет в составе», и ярлыка у него быть не должно: тот, кого не поймало
/// условие, получает НИЧЕГО, а не чужой ярлык (I34).
/// **СЛОВА ВЗЯТЫ ИЗ МАКЕТА, а не придуманы здесь** (`assets/yenilenecekler/
/// mugam-6-kart.html` и `mugam-8-teqvim.html`, 10.08). Первая редакция была
/// написана своими словами — `Gəlir` / `Gözlənilir` / `Gələ bilmir` — и
/// разошлась с макетом в трёх из трёх: у него **строчные** буквы, «ждём» — это
/// `cavab gözlənilir` (сказано, чего именно ждут), а «не может» — `bacarmır`,
/// короче и без вспомогательного глагола.
///
/// **`notAsked` в макете отсутствует, и это не упущение макета.** Он нарисован
/// 10.08, а четвёртое состояние заведено 11.08, когда выяснилось, что «не
/// спрашивали» и «ждём» — разные вещи (I47). Слово подобрано в один ряд с
/// остальными: строчное, о состоянии человека, а не о действии владельца.
String participantAnswerLabel(String? answer) => switch (answer) {
      kAnswerGoing => 'gəlir',
      kAnswerWaiting => 'cavab gözlənilir',
      kAnswerCant => 'bacarmır',
      kAnswerLeft => 'İşdən çıxdı',
      kAnswerNotAsked => 'soruşulmayıb',
      _ => '',
    };

/// **ПЕРЕКЛЮЧАТЕЛЬ ИСПРАВЛЕН 11.08 ПОСЛЕ N115 — переключает не наличие карты, а
/// [answersWrittenByOwner].**
///
/// Прежняя редакция читала так: карта есть → отсутствующий ключ значит
/// `notAsked`. Довод был «карта пишется ЦЕЛИКОМ по составу, значит её наличие
/// и есть отметка нового мира». **Довод верен ровно для тех, кто пишет карту
/// целиком, и неверен для того, кто пишет ОДИН КЛЮЧ** — а такой писатель
/// появился в тот же день, когда участник получил право отвечать за себя.
/// Первый же его ответ в старом вечере создавал карту из одного ключа и
/// стирал согласие всех остальных (N115, воспроизведено дважды из двух).
///
/// Отсюда три случая вместо двух:
///
/// | Что в документе | Как читается |
/// |---|---|
/// | ключ человека есть | его значение |
/// | ключа нет, отметки нет | **`going`** — старый мир; карту начал участник |
/// | ключа нет, отметка стоит | **`notAsked`** — состав правил владелец и не спросил |
///
/// **Средняя строка — самая дорогая.** Сломай её, и все **73 документа без
/// карты** (замер 11.08, только чтение) задним числом переведутся из
/// согласившихся в ждущие.
String? answerOf({
  required String uid,
  required List<String> participantUids,
  Map<String, dynamic>? answers,
  bool answersWrittenByOwner = false,
}) {
  if (!participantUids.contains(uid)) return null;
  // Карты нет вовсе — документа не касалась новая сборка. Никого никогда не
  // спрашивали, и «в составе» означало «идёт».
  if (answers == null) return kAnswerGoing;
  final raw = answers[uid];
  if (raw is String && kEventAnswers.contains(raw)) return raw;
  // Ключа нет либо в нём мусор. ЧТО ЭТО ЗНАЧИТ — решает то, КТО заполнял
  // карту, а не то, что она существует:
  //
  //   • карту заполнял владелец (или сервер) — она полна по составу, значит
  //     человека в неё не включили намеренно: его НЕ СПРАШИВАЛИ;
  //   • отметки нет — карту начал участник своим ответом, и про остальных
  //     она не утверждает ничего. Для них верен старый смысл: «в составе»
  //     значит «идёт».
  return answersWrittenByOwner ? kAnswerNotAsked : kAnswerGoing;
}
