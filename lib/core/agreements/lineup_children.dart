/// КОМУ ПРИГЛАШЕНИЕ ПОД ЭТИМ ВЕЧЕРОМ УЖЕ СОЗДАНО.
///
/// **Сторож против двойного нажатия, и он не про удобство.** Приглашение —
/// документ, а не флаг: нажми человек кнопку дважды, и у каждого позванного
/// окажется по два одинаковых вечера, которые придётся разбирать руками. Это
/// ровно тот необратимый ход в данных, который назван отдельно в
/// `docs/plan.md`, — и проходит он обычным нажатием.
///
/// **Спрашивать не у шаблона, а у документов.** Шаблон (`lineup` на родителе)
/// говорит, кого ЗВАЛИ; здесь нужен ответ, кому приглашение СОЗДАНО, а это
/// разные вопросы: запись `lineup` могла не состояться после уже созданных
/// детей (сеть оборвалась между двумя операциями), и тогда шаблон утверждал бы
/// отсутствие того, что есть. Документ врать не может — он либо есть, либо
/// нет.
///
/// [events] — свои вечера зовущего (`personalEventsProvider`). Дети приходят
/// именно этим потоком: `ownerUid` у них — зовущий, иначе их нельзя было бы
/// создать (`allow create`).
///
/// **Отменённые дети СЧИТАЮТСЯ ПОЗВАННЫМИ, и это решение, а не недосмотр.**
/// Отменённое приглашение — не «человека не звали», а «звали и отменили»;
/// создать поверх него второе значило бы позвать человека, у которого отмена
/// этого же вечера уже лежит в календаре. Позвать заново — отдельный ход, и
/// он должен называться своим именем, а не получаться молча из повторного
/// нажатия.
Set<String> invitedUidsUnder(List<PersonalEvent> events, String parentEventId) {
  final out = <String>{};
  for (final e in events) {
    if (e.parentEventId != parentEventId) continue;
    out.addAll(e.participantUids.where((uid) => uid.isNotEmpty));
  }
  return out;
}
