/// КАКИЕ СУТКИ ЧЕЛОВЕКА ЗАНЯТЫ — один ответ на все сетки выбора дня.
///
/// Заведено 25.08 работой «занятость в листах предложения». До неё занятость
/// в приложении **была и работала** — её показывала красная плашка «Bu gün
/// artıq tədbirin var» в карточке вечера, — но ни одна сетка, где человек
/// ОТМЕЧАЕТ дни, её не получала: `busyDays` стоял на умолчании `const {}` и у
/// листа ответа, и у листа набора дней. Цена измерена 22.08 на трубке:
/// музыкант отметил 25 августа, не видя, что на этот день у него уже стоит
/// «Toy · 15:00», и узнал об этом из плашки ПОСЛЕ приёма, когда отказаться
/// уже нельзя.
///
/// --- ЧТО ЗДЕСЬ СВОЕГО, А ЧТО ВЗЯТО ГОТОВЫМ ---
///
/// Своего — только сборка. Все три решения приняты не здесь:
///
///   • **какие вечера вообще считаются** — `liveEvents` (`day_buckets.dart`):
///     дедуп по `id` (свой вечер приходит ОБОИМИ потоками), без отменённых,
///     без нечитаемых дат;
///   • **занимает ли вечер день ЭТОГО человека** — `dayRoleOf`
///     (`day_role.dart`): приглашение не занимает, отказ не занимает, владелец
///     занят всегда;
///   • **в какие сутки вечер попадает** — `eventDay`
///     (`core/time/event_local_time.dart`).
///
/// Повторить хоть одно значило бы завести второе место, где решается одно, —
/// и дать им разойтись молча (N49, N74).
///
/// --- ПОЧЕМУ `eventDay`, А НЕ `DateTime.parse` ---
///
/// `eventDay` приводит строку с `Z` к местному времени, голый `DateTime.parse`
/// — нет. В Баку это −4 часа, то есть на записях легаси-формата **другие
/// сутки**. Перепись 07.08 по 72 мероприятиям (шапка `event_local_time.dart`):
/// 56 плавающих, **13 с `Z`**, 3 с микросекундами.
///
/// **Расхождение с `conflictEventsOnDay` записано находкой, а не сглажено
/// здесь** (N161): та берёт `DateTime.parse` и сравнивает поля
/// (`sameCalendarDay`), то есть на тех же 13 записях отвечает про сутки UTC.
/// Взять неверный разбор ради согласия двух мест — значит закрепить дефект в
/// новом месте; чинится он там, где живёт, отдельной правкой с одной
/// переменной (I48).
///
/// --- ГРАНИЦЫ, ЧЕГО ЭТО ПРАВИЛО НЕ ДЕЛАЕТ ---
///
/// **Оно не знает, ЗНАЕМ ЛИ МЫ ответ.** Пустой набор значит «занятых суток
/// нет» и ничего больше; отличить это от «данные ещё не пришли» здесь нечем —
/// на входе уже готовые списки. Вопрос решается там, где видно состояние
/// потоков: `features/job_offer/busy_days.dart`, и решается один раз на оба
/// листа.
///
/// **Оно не проверяет [uid] на пустоту.** Пустой uid `dayRoleOf` считает
/// занятым ВСЁ (`day_role.dart:181`) — намеренно, это ложная тревога, видная в
/// тот же миг. Ловится это до вызова, там же, где решается «знаем ли»: до сюда
/// пустой uid не доходит.
library;

import '../../firebase/models.dart';
import '../time/event_local_time.dart';
import 'day_buckets.dart';
import 'day_role.dart';

/// Сутки, занятые у [uid], из двух его потоков — своих вечеров и тех, где он
/// в составе. Чем именно занят каждый день — [occupiedEventsByDayOf], оно же
/// и считает; здесь только ключи.
///
/// **Отдаёт СУТКИ, а не вечера, и это решение.** Сетке нужен ответ «этот день
/// покрасить или нет»; отдай она вечера, каждый вызывающий раскладывал бы их
/// по дням сам — тем же `eventDay` или своим способом, и второй разошёлся бы с
/// первым. Два вечера в один день дают одни сутки.
///
/// **Оба потока обязательны и оба именованы.** Свои вечера и чужие, где
/// человек в составе, приходят РАЗНЫМИ запросами (`ownerUid ==` и `musicians
/// arrayContains`), и половина занятости выглядит как вся: пропущенный поток
/// не краснеет, а тихо освобождает календарь.
Set<DateTime> occupiedDaysOf({
  required List<PersonalEvent> own,
  required List<PersonalEvent> asParticipant,
  required String uid,
}) => occupiedEventsByDayOf(
  own: own,
  asParticipant: asParticipant,
  uid: uid,
).keys.toSet();

/// ЧЕМ ИМЕННО заняты эти сутки — те же вечера, разложенные по дням.
///
/// **Источник один, форм две, и вторая ВЫВЕДЕНА из первой** (`occupiedDaysOf`
/// — это её ключи). Завести два прохода значило бы дать им разойтись: набор
/// дней сказал бы «занято», а список вечеров оказался бы пуст, и оба ответа
/// выглядели бы правильными порознь (N49, N74).
///
/// **Зачем понадобились вечера, а не только даты (владелец, 25.08).** Сетка
/// красит день предупредительно, и человек, нажав на него, вправе спросить
/// «чем занят?». Ответить на это набором дат нельзя — нужен сам вечер: его
/// тип, время и `id`, по которому открывается карточка.
///
/// **ВЕЧЕРА ОТДАЮТСЯ ВСЕ, а не первый.** Два вечера в один день — обычная
/// жизнь; отдай мы один, второй пропал бы молча, и это ровно N51/I11:
/// сигнатура, возвращающая одно там, где их может быть несколько, прячет тот
/// же дефект, что и `.first`. Порядок — по времени, тот же, которым живут
/// список дня и пометка месяца, чтобы человек видел их в одном порядке везде.
Map<DateTime, List<PersonalEvent>> occupiedEventsByDayOf({
  required List<PersonalEvent> own,
  required List<PersonalEvent> asParticipant,
  required String uid,
}) {
  final out = <DateTime, List<PersonalEvent>>{};
  for (final e in liveEvents(own: own, asParticipant: asParticipant)) {
    if (dayRoleOf(e, uid) != DayRole.occupied) continue;
    final day = eventDay(e.date);
    // `liveEvents` уже выбросил записи без разбираемой даты — проверка здесь
    // только ради типа, а не ради правила.
    if (day == null) continue;
    (out[day] ??= <PersonalEvent>[]).add(e);
  }
  for (final list in out.values) {
    list.sort(
      (a, b) => eventLocalDateTime(a.date)!.compareTo(eventLocalDateTime(b.date)!),
    );
  }
  return out;
}
