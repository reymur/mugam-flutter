/// Запись правки — ровно [kEventEditWrites] и ничего сверх.
///
/// Возвращается карта, а не пишется в Firestore: правило должно быть
/// проверяемо тестом, а вызов базы в тесте проверять нечем.
Map<String, dynamic> eventEditUpdate({
  required String date,
  required String type,
  required String location,
  required String notes,
  required List<String> musicians,
  required String actorUid,
  /// Прежние ответы состава — чтобы правка их НЕ СТЁРЛА (шаг 4).
  ///
  /// Без этого первая же правка места или времени объявляла бы всех
  /// ответивших заново ждущими: человек сказал «не могу», владелец поправил
  /// адрес — и ответ пропал. Ответ принадлежит человеку, а не документу, и
  /// правка чужого поля его отнимать не вправе.
  Map<String, dynamic>? previousAnswers,

  /// Владелец ПРАВИМОГО мероприятия — не тот же, кто правит.
  ///
  /// Правит [actorUid], а владельцем может быть другой человек: у договора
  /// правку делает любая из сторон. Смешать их значило бы записать правящему
  /// согласие, которого он не давал, а владельцу — ожидание ответа на его же
  /// вечере (N112). Два разных вопроса — два разных параметра.
  String ownerUid = '',
}) {
  return <String, dynamic>{
    'date': date,
    'type': type,
    'location': location,
    'notes': notes,
    // Копия, а не сама ссылка: список приходит из состояния формы, и
    // отдать наружу его же значило бы позволить правке измениться после
    // того, как она собрана.
    'musicians': List<String>.from(musicians),
    // Ответы состава — из ТОГО ЖЕ списка, что и `musicians`, одной
    // функцией. Не из прежнего значения документа: правка на то и правка,
    // что состав в ней уже другой, и ответы обязаны поехать вместе с ним, а
    // не остаться от прошлого состава (шаг 1, `docs/plan.md`).
    'answers': answersForParticipants(musicians,
        previous: previousAnswers, ownerUid: ownerUid),
    // Признак автора. Правила требуют, чтобы он был самим просящим
    // (`stampsSelf`), а сервер берёт из него имя для текста уведомления —
    // без него «{Ad} tarixi dəyişdi» назвало бы владельца вместо
    // правившего.
    'lastActionBy': actorUid,
    'lastActionType': kEventEdited,
  };
}

