/// Что человеку вообще можно ответить на «время занято».
enum ConflictAnswer {
  /// Посмотреть занятое мероприятие.
  view,

  /// Переписать СВОЁ существующее мероприятие тем, что сейчас в форме.
  /// Пишет в ЧУЖОЙ документ — не в тот, который человек собирался создать.
  editExisting,

  /// Убрать ЧУЖОЕ мероприятие из своего календаря (выход из участников).
  /// Тоже пишет в чужой документ, и тоже по прямой просьбе человека.
  leaveForeign,

  /// «Это отдельное мероприятие, сохрани как есть». При совпадении минута
  /// в минуту вызывающий превращает этот ответ в запрет до сдвига времени
  /// — решение владельца 03.08: занятый ДЕНЬ обычная жизнь, занятая
  /// МИНУТА означала бы двух мест разом.
  saveAnyway,

  /// Сохранить молча, ничего не спрашивая.
  saveSilently,

  /// Нельзя: время занято минута в минуту. Сдвиньте.
  blockUntilMoved,
}

/// Ответы, которые пишут в ДРУГОЙ документ — не в тот, который человек
/// сейчас создаёт или правит.
///
/// Набор существует ради одной проверки, и она же есть N39 одной строкой:
/// при ПРАВКЕ ни один допустимый ответ сюда попадать не должен.
const Set<ConflictAnswer> kAnswersTouchingOtherDoc = {
  ConflictAnswer.editExisting,
  ConflictAnswer.leaveForeign,
};

/// Единственное место, где решается, что предложить человеку.
///
/// ---------------------------------------------------------------------
/// ПОЧЕМУ ПРИ ПРАВКЕ ВОПРОСА НЕТ ВОВСЕ (N39)
/// ---------------------------------------------------------------------
/// Окно конфликта написано для СОЗДАНИЯ и отвечает на вопрос «у меня на
/// это время занято, что делать». При правке существующего этого вопроса
/// не существует, и четыре довода тому:
///
/// 1. Правимое мероприятие из конфликтов исключено (`excludeEventId`),
///    значит окно поднимают ПОСТОРОННИЕ мероприятия того дня — к правке
///    отношения не имеющие.
/// 2. Заменять нечем: человек ничего не создаёт, создаваемой записи, которой
///    можно было бы что-то заместить, не существует.
/// 3. «Yeni tədbir» лгала буквально — нового мероприятия не появлялось, а
///    именно она сохраняла правку. Кнопки «сохранить» в окне не было вовсе.
/// 4. Конфликт ДНЯ при правке ничему не мешает: решение владельца 03.08 —
///    дневное мероприятие и вечерний той в одну дату это обычная жизнь. В
///    форме об этом уже говорит живая плашка.
///
/// Остаётся одно настоящее затруднение — совпадение минута в минуту, — и
/// верный ответ на него не «заменить», а «так нельзя, сдвиньте время».
/// Поэтому при правке разрушительного ответа не прячут за подтверждением:
/// его нет как случая.
///
/// [isEditing] — правится существующее мероприятие (иначе создаётся новое);
/// [exactTime] — совпадение с точностью до минуты (иначе занят лишь день);
/// [targetIsMine] — выбранное переключателем мероприятие принадлежит
/// смотрящему. При создании от этого зависит, какой из двух ходов по
/// чужому документу вообще возможен: переписать можно только СВОЁ
/// (`firestore.rules` даёт `update` лишь владельцу), из чужого можно
/// только выйти.
Set<ConflictAnswer> conflictAnswers({
  required bool isEditing,
  required bool exactTime,
  required bool targetIsMine,
}) {
  if (isEditing) {
    return exactTime
        ? const {ConflictAnswer.blockUntilMoved}
        : const {ConflictAnswer.saveSilently};
  }
  // Создание. Набор от `exactTime` НЕ зависит — точная минута меняет не
  // список ответов, а то, во что превращается `saveAnyway` у вызывающего.
  return targetIsMine
      ? const {
          ConflictAnswer.view,
          ConflictAnswer.editExisting,
          ConflictAnswer.saveAnyway,
        }
      : const {
          ConflictAnswer.view,
          ConflictAnswer.leaveForeign,
          ConflictAnswer.saveAnyway,
        };
}

/// Спрашивать ли человека вообще. Один допустимый ответ — спрашивать не о
/// чем: вопрос с единственным ответом это не вопрос, а задержка.
bool conflictAsksHuman(Set<ConflictAnswer> answers) => answers.length > 1;

/// Имя поступка на кнопке.
///
/// Мапка живёт здесь, а не в виджете, ровно потому, что вся эта пара
/// находок — про разошедшиеся имя и поступок. Одно место, и оно
/// проверяемо.
///
/// «Əvəz et» не осталось ни на одной кнопке, где замена возможна: слово
/// называло три разных действия сразу — правку своего, выход из чужого и
/// снос постороннего.
String conflictAnswerLabel(ConflictAnswer answer) {
  switch (answer) {
    case ConflictAnswer.view:
      return 'Bax';
    // «Изменить существующее мероприятие» — оно и меняется, тем же
    // документом и тем же id. Ни удаления, ни второй записи рядом.
    case ConflictAnswer.editExisting:
      return 'Mövcud tədbiri dəyiş';
    // «Убрать из моего календаря» — ровно то, что говорит красная строка
    // предупреждения над кнопками: «yalnız sizin təqvimdən silinəcək». У
    // остальных участников мероприятие остаётся.
    case ConflictAnswer.leaveForeign:
      return 'Təqvimimdən sil';
    case ConflictAnswer.saveAnyway:
      return 'Yeni tədbir';
    // Двух ответов ниже человек не видит: при правке окна нет, и оба
    // случая разрешаются самой формой — молчаливым сохранением либо живой
    // плашкой «время занято». Имена заведены, чтобы значение случая не
    // приходилось выводить из его отсутствия.
    case ConflictAnswer.saveSilently:
      return 'Saxla';
    case ConflictAnswer.blockUntilMoved:
      return 'Başqa vaxt seçin';
  }
