import 'lineup.dart';

// ---------------------------------------------------------------------------
// СПИСОК ЛЮДЕЙ НА ВЕЧЕРЕ — ОДИН (решение владельца 17.09, вариант Б)
// ---------------------------------------------------------------------------
// ЗДЕСЬ БЫЛО ДВА СПИСКА, И ОНИ СНЯТЫ ВМЕСТЕ С ПРИЧИНОЙ, ПО КОТОРОЙ РАЗОШЛИСЬ.
// Карточка показывала «TOY HEYƏTİ» (состав, `musicians`) и «ÇAĞIRILANLAR»
// (позванные, шаблон плюс отдельные документы-приглашения). Разделять их было
// осмысленно ровно до тех пор, пока позванный жил в СВОЁМ документе и в состав
// родителя не попадал: множества не пересекались ПО УСТРОЙСТВУ ДАННЫХ, а не по
// какому-либо правилу.
//
// СНЯВ ОТДЕЛЬНЫЕ ДОКУМЕНТЫ, МЫ СНЯЛИ И ЭТО СВОЙСТВО — и оба раздела стали
// двумя видами на одно и то же. Цена замерена глазами 17.09: вечер
// `qrqTFjiZ8sP5F09eoXAU`, Теймур показан дважды, оба раза «gəlir».
//
// ДОВОД ВЛАДЕЛЬЦА, ДОСЛОВНО: состав вечера один, человек в нём либо есть, либо
// нет. Два списка были нужны только из-за старого устройства, а его мы сняли.
//
// ДВА ВИДА СТРОКИ, А НЕ ПЯТЬ, и третьего («снят») нет намеренно. Снять
// человека значит убрать его из состава; убранного в вечере НЕТ, и строки у
// него нет тоже. Прежде «снят» существовал потому, что отсутствие
// документа-ребёнка было двусмысленным — «сняли» и «ждём» выглядели одинаково.
// Теперь они различаются прямо: есть в составе или нет.

/// Кто эта строка.
enum PartyRowKind {
  /// Человек В СОСТАВЕ. Ответ — в [PartyRow.answer], и он есть всегда:
  /// `answerFor` не возвращает `null` для того, кто в `musicians`.
  member,

  /// Человека в составе НЕТ, и не по недосмотру: его хотели позвать и не
  /// смогли. Причина — в [PartyRow.reason].
  ///
  /// **ЕГО НЕЛЬЗЯ ДЕРЖАТЬ В СОСТАВЕ, и довод не про опрятность.** Попади он в
  /// `musicians` — `isParty()` пустит его ЧИТАТЬ вечер, на который не звали, а
  /// `diff.added` на сервере пошлёт ему «вас добавили». Ответа ему записать
  /// тоже нечем: правила принимают ровно `going|waiting|cant|left`, а
  /// `notAsked` запрещён нарочно — он и есть отсутствие ключа.
  notInvited,
}

/// Одна строка списка людей на вечере.
class PartyRow {
  const PartyRow({
    required this.uid,
    required this.kind,
    this.answer,
    this.reason,
    this.snapshotName = '',
  });

  final String uid;
  final PartyRowKind kind;

  /// Что ответил человек. Только у [PartyRowKind.member]; у непозванного
  /// `null`, потому что вопроса ему не задавали.
  final String? answer;

  /// Отчего не позвали. Только у [PartyRowKind.notInvited].
  final String? reason;

  /// Имя НА МИГ СБОРА — запасное, и только для непозванного.
  ///
  /// У человека в составе запасного имени нет и не нужно: он участник, его
  /// берут из живого списка. У непозванного живой записи может не быть вовсе —
  /// ради этого случая снимок и хранится (шаблон переживает людей).
  final String snapshotName;
}

/// СОБРАТЬ ОДИН СПИСОК.
///
/// [event] — сам вечер: состав и ответы. [notInvited] — записи о тех, кого не
/// позвали; сюда идёт `event.lineup`, а отбор делается здесь, чтобы правило
/// было одно.
///
/// **ПОРЯДОК: сперва состав в своём порядке, непозванные — В КОНЕЦ.** Первые
/// идут на вечер, вторые нет, и мешать их значило бы заставлять читателя
/// разбирать каждую строку.
///
/// **ОДИН UID — ОДНА СТРОКА, И ЭТО ГЛАВНОЕ УТВЕРЖДЕНИЕ ПРАВИЛА.** Оно здесь не
/// ради аккуратности: ровно его нарушение и было дефектом 17.09. Слот,
/// чей человек уже в составе, пропускается молча — он не «ещё одна строка», он
/// та же самая.
///
/// **СЛОТЫ `invited: true` В СПИСОК НЕ ИДУТ ВОВСЕ.** Такой слот означает
/// «звали, и ушло»; если человек при этом в составе — он уже показан строкой
/// состава, а если его там нет, то его из вечера убрали, и показывать нечего
/// (решение владельца 17.09: пятого вида строки не заводим).
///
/// **НЕПОЗВАННЫЕ — ТОЛЬКО ВЛАДЕЛЬЦУ**, и условие стоит ЗДЕСЬ, а не в разметке.
/// «Кому не ушло» — сведения хозяина вечера о его собственной отправке;
/// участнику они ничего не говорят, а человека, которого не звали, называют
/// перед посторонними. Правило проверяемо тестом, разметка — нет (I32).
List<PartyRow> partyRows({
  required PersonalEvent event,
  required List<LineupSlot> notInvited,
  required String viewerUid,
}) {
  final rows = <PartyRow>[];
  final seen = <String>{};

  for (final uid in event.participantUids) {
    if (uid.isEmpty) continue;
    if (!seen.add(uid)) continue;
    rows.add(PartyRow(
      uid: uid,
      kind: PartyRowKind.member,
      // Ответ берётся ПРАВИЛОМ, а не из карты: `answerFor` знает про запасной
      // путь у документов без карты и про то, что отсутствие ключа — «не
      // спрашивали», а не «ждём».
      answer: event.answerFor(uid),
    ));
  }

  // ПУСТОЙ [viewerUid] НЕ ПОКАЗЫВАЕТ НИЧЕГО ЛИШНЕГО. Пустой uid означает не
  // «владелец», а «неизвестно, кто смотрит», то есть поломку вызывающего;
  // сторона выбрана так, чтобы промах не раскрывал чужие сведения.
  if (viewerUid.isEmpty || viewerUid != event.ownerUid) return rows;

  for (final slot in notInvited) {
    if (slot.uid.isEmpty) continue;
    if (slot.invited) continue;
    if (!seen.add(slot.uid)) continue;
    rows.add(PartyRow(
      uid: slot.uid,
      kind: PartyRowKind.notInvited,
      reason: slot.reason,
      snapshotName: slot.name,
    ));
  }

  return rows;
}
