/// СОСТОЯНИЕ ВЕЧЕРА НА КАРТОЧКЕ — шаг 6 (`docs/plan.md`), починка **N116**.
///
/// **Найдено сборкой макета с экраном 12.08:** в `mugam-6-kart` статус стоит
/// первым блоком отдельной плашкой («Dəqiq», зелёная обводка), а на карточке
/// вечера его не было **ни в каком виде** — ноль упоминаний `event.status`
/// против одиннадцати в карточке договора. То есть вечер «под вопросом» и
/// вечер отменённый выглядели как обычные.
///
/// Правило вынесено сюда, а не написано в экране, потому что читателей у него
/// двое: сама плашка и решение, какие кнопки показывать — выход наверх
/// (`showsRestore` ниже) существует ровно для одного состояния и двух
/// поводов из него.
///
/// **ЗДЕСЬ СТОЯЛО «кнопка „Onsuz davam edirəm“ существует ровно для одного
/// состояния и одного повода» — верно до 08.09.** Поводов стало два (работа
/// 7, шаг 1), и надпись у них РАЗНАЯ: у второго «без него» бессмысленно.
library;

/// Что показать про состояние вечера.
class EventStatusView {
  const EventStatusView({required this.label, required this.tone, this.reason});

  /// Слово на плашке.
  final String label;

  final EventStatusTone tone;

  /// **ПОВОД — отдельной строкой под плашкой, и он обязателен для «под
  /// вопросом».** Выход наверх без строки про повод — это действие без
  /// причины на экране: человек видит предложение вернуть вечер в силу, не
  /// зная, отчего вечер под вопросом (решение владельца 12.08).
  ///
  /// **С двумя поводами (08.09) требование только окрепло:** «Onsuz davam
  /// edirəm» и слово второго повода отличаются друг от друга ровно тем, что
  /// сказано в этой строке. Пропадёт строка — две разные кнопки станут
  /// неотличимы по смыслу.
  final String? reason;
}

enum EventStatusTone {
  /// В силе: зелёная обводка, как в макете.
  firm,

  /// Под вопросом: приглушённая обводка. **Не красная** — красный отдан
  /// отмене целиком (N110), и красить им «под вопросом» значило бы дать
  /// одному цвету два состояния.
  doubt,

  /// Отменён: красная обводка.
  cancelled,
}

/// Слова состояний. Литералами здесь, рядом с правилом, — как у ответов
/// состава: их читает проход по исходникам, и вынос значения за константу
/// сделал бы его невидимым там, где он сторожит.
const String kStatusAgreed = 'agreed';
const String kStatusUnsettled = 'unsettled';
const String kStatusCancelled = 'cancelled';

/// Поводы «под вопроса» — их два, третий (`ownerDoubt`) не написан вовсе:
/// поставить `unsettled` клиент не может, это делает только сервер
/// (`markEventUnsettled`). Разбор — шаг 6 в `docs/plan.md`.
///
/// **С 08.09 это значения ОТДЕЛЬНОГО ПОЛЯ `unsettledReason`, а не
/// `lastActionType`** (работа 7, шаг 1). Совпадение написания с двумя
/// именами поступков историческое: до 08.09 повод жил в поле поступка,
/// и переименовывать значения значило бы менять данные прода ради красоты.
/// **Клиент это поле не пишет и писать не может** — запрещено правилом
/// `serverOwnsUnsettledReason()`.
const String kReasonMemberLeft = 'memberLeft';
const String kReasonWorkCancelled = 'workCancelled';

/// Как показать состояние — правило БЕЗ ЭКРАНА с 13.08, и это сказано первым
/// (N179).
///
/// **Здесь стояло «Плашка стоит всегда, и это решение».** Верно это было
/// сутки: 12.08 (`7c100a0`) плашку подключили к карточке вечера, 13.08
/// (`32bd8e4`) сняли — решением автора, довод записан на месте снятия,
/// `agreements_screen.dart`: «под вопросом» музыканту не нужно, вечер либо
/// есть, либо отменён. Запись пережила то, что описывала, и пятнадцать суток
/// утверждала про экран, которого нет, — тот же класс, что N165 и N166.
///
/// **Вызывающих у этой функции сегодня ноль**, и это след решения, а не
/// пропуск: чинить его возвратом плашки нельзя, не отменив довод 13.08.
/// Судьба функции не решена — либо дождётся своего экрана, либо будет снята
/// вместе с тестами, и это решение владельца (N179).
///
/// **Чем она НЕ является: она не отвечает на «что случилось».** Её `label` —
/// это СОСТОЯНИЕ («Dəqiq» / «Şübhə altında» / «Ləğv edilib»), а повод она
/// называет только у `unsettled` и только двумя значениями. Вопрос «кто и что
/// сделал последним» решает `eventDeedLine` (`event_deed_line.dart`),
/// заведённый 28.08 отдельно и намеренно: два разных вопроса — два правила
/// (I47), и сводить их значило бы вернуть снятое боком.
///
/// Ниже — прежний довод, верный для того дня, когда плашка на экране была:
/// отсутствие плашки читается как «состояние неизвестно», а не как «всё в
/// порядке»; пустое место не отличает целый вечер от экрана, который про
/// состояние не знает — ровно тем и был дефект N116.
EventStatusView eventStatusView({
  required String status,
  String? unsettledReason,
  String? leftMemberName,
}) {
  switch (status) {
    case kStatusCancelled:
      return const EventStatusView(
        label: 'Ləğv edilib',
        tone: EventStatusTone.cancelled,
      );
    case kStatusUnsettled:
      return EventStatusView(
        label: 'Şübhə altında',
        tone: EventStatusTone.doubt,
        reason: switch (unsettledReason) {
          kReasonMemberLeft =>
            leftMemberName == null
                ? 'İştirakçı ayrıldı'
                : '$leftMemberName ayrıldı',
          kReasonWorkCancelled => 'İş ləğv olundu',
          // Повод неизвестен — молчим о нём, но само состояние показываем.
          // Придумать причину значило бы сказать человеку неправду о том,
          // почему его вечер под вопросом.
          _ => null,
        },
      );
    default:
      return const EventStatusView(label: 'Dəqiq', tone: EventStatusTone.firm);
  }
}

/// Показывать ли ВЫХОД НАВЕРХ — ход «вернуть вечер в силу».
///
/// **Имя сменилось 08.09 вместе со смыслом, и это не косметика (I45).**
/// Функция звалась `showsContinueWithout` — по надписи «Onsuz davam edirəm»,
/// «продолжаю без НЕГО». С расширением на второй повод имя стало враньём:
/// при `workCancelled` участники все на месте, и «без него» не значит
/// ничего. Имя берётся от того, как вещь зовётся в модели — а в модели это
/// **возврат в силу**, тем же словом, что и правило `restoresEvent()`.
///
/// **Только владельцу, только из `unsettled`, и только по поводу из
/// перечисленных** — те же три условия, что стоят в правиле
/// `restoresEvent()` (`firestore.rules`). Написаны здесь заново намеренно:
/// правило решает, что СЕРВЕР примет, а это — что человеку ПОКАЗАТЬ.
/// Разойдись они, человек увидел бы кнопку, которая молча получает отказ.
///
/// **ЗДЕСЬ СТОЯЛО «Из `workCancelled` возврата нет: работа отменена по
/// согласию обеих сторон, и „продолжаю без него“ обещало бы вечер, которого
/// не существует».** Снято решением владельца 08.09, и записано снятием, а
/// не стёрто. Довод был неверен: **вечер — это день и состав, а не тот
/// договор, под который звали.** Зовущий, нашедший на тот же день другую
/// работу, продолжает с тем же составом; отняв у него ход, мы заставляем
/// распустить согласившихся и собрать заново. Шире, словами владельца:
/// **состояние без выхода — это скрытая отмена.**
///
/// **ПЕРЕЧИСЛЕНИЕ, А НЕ «ЛЮБОЙ ПОВОД», и по той же причине, что в правиле:**
/// новый повод, который мы однажды заведём, поехал бы в «можно вернуть»
/// молча.
///
/// **НАДПИСЬ У ДВУХ ПОВОДОВ РАЗНАЯ, И ЭТО ЧАСТЬ ЭТОГО ЖЕ РЕШЕНИЯ** —
/// надписи ниже, [restoreLabel]. Здесь только «показывать ли», там «что
/// написать»: два вопроса — два правила (I47).
bool showsRestore({
  required bool isOwner,
  required String status,
  String? unsettledReason,
}) =>
    isOwner &&
    status == kStatusUnsettled &&
    (unsettledReason == kReasonMemberLeft ||
        unsettledReason == kReasonWorkCancelled);

/// «Продолжаю без него» — выход наверх, когда ушёл участник.
///
/// Вечер на месте, не хватает человека, и владелец даёт своё обещание
/// продолжить. Слово первого повода, стоит с 12.08.
const String kRestoreLabelMemberLeft = 'Onsuz davam edirəm';

/// «Всё равно продолжаем» — выход наверх, когда исчезла работа.
///
/// **Выбрано владельцем 08.09** из трёх предложенных. Доводы, по которым
/// выбрано именно это:
///   • это ДЕЙСТВИЕ, как соседние кнопки («Şübhə altına al»), а не
///     назывное, как плашки («Dəqiq», «İş ləğv olundu»). Назывное слово
///     размыло бы границу между кнопкой и плашкой;
///   • **множественное число** — обращено к составу, которому и уйдёт
///     уведомление о возврате в силу;
///   • ничего не выдумывает про причину. Отвергнутое «Başqa iş tapdım»
///     («нашёл другую работу») утверждало бы то, чего приложение проверить
///     не может, — тот же класс, что снятый `partnerName`: рассказ,
///     которому верят.
///
/// **ЛОВУШКА, ИЗ-ЗА КОТОРОЙ ЗДЕСЬ НЕТ СЛОВА `Onsuz` (N205).** По-азербайджански
/// «всё равно» — `onsuz da`, «без него» — `onsuz`. Значит **«Onsuz da davam
/// edirik»** значило бы ровно нужное и отличалось бы от
/// [kRestoreLabelMemberLeft] **одним пробелом**. Брать такое нельзя: две
/// кнопки разного смысла, различимые пробелом, — правило и его нарушение на
/// самом опасном расстоянии (I42). Сторож на это стоит в
/// `test/event_status_view_test.dart`.
const String kRestoreLabelWorkCancelled = 'Yenə də davam edirik';

/// Что написать на выходе наверх. `null` — выхода нет, кнопки нет.
///
/// **Отдельно от [showsRestore], и это не дробление ради дробления.** Тот
/// решает, ПОКАЗЫВАТЬ ли (и повторяет три условия правила `restoresEvent`),
/// этот — ЧТО НАПИСАТЬ. Слей их, и функция станет отвечать на два вопроса
/// сразу, а вызывающему придётся разбирать, что означает пустая строка:
/// «не показывать» или «слов нет».
///
/// **Согласие с [showsRestore] держится не памятью, а вердиктом:** у
/// каждого повода, на котором тот говорит «да», здесь обязана быть надпись,
/// и наоборот. Иначе правило разрешит, а кнопка не найдёт слов — или
/// найдёт слова там, где сервер откажет.
String? restoreLabel(String? unsettledReason) => switch (unsettledReason) {
      kReasonMemberLeft => kRestoreLabelMemberLeft,
      kReasonWorkCancelled => kRestoreLabelWorkCancelled,
      _ => null,
    };


/// СТРОКИ ОКОШКА ВЫБОРА СОСТОЯНИЯ — шаг «состояния пересмотрены» (12.08).
///
/// Плашка на карточке стала кнопкой; нажатие открывает три строки. **У вечера
/// с договорённостью и без неё окошко РАЗНОЕ, и разница сказана словами ДО
/// нажатия** (требование автора 12.08): у договорённости отмена не отменяет, а
/// запускает согласие второй стороны.
///
/// Подпись стоит ПОД строкой, а не всплывает после выбора: всплывшее
/// объяснение приходит, когда решение уже принято, — а здесь оно и есть
/// решение. Человек выбирает не «отменить», а «отменить самому» либо
/// «попросить согласия».
class StatusChoice {
  const StatusChoice({
    required this.status,
    required this.deed,
    required this.label,
    this.note,
    this.asksOtherSide = false,
  });

  final String status;
  final String deed;
  final String label;

  /// Подпись под строкой. `null` — сказать нечего.
  final String? note;

  /// Ход не отменяет сам, а просит вторую сторону. Экран по нему решает,
  /// какой метод звать: прямую запись или предложение отмены.
  final bool asksOtherSide;
}

/// Три строки окошка. [partnerName] нужен только вечеру с договорённостью —
/// в подписи называется тот, кто должен подтвердить.
List<StatusChoice> statusChoices({
  required bool isAgreement,
  String? otherSideName,
}) => [
      const StatusChoice(
        status: kStatusAgreed,
        deed: 'ownerFirm',
        label: 'Dəqiq',
      ),
      const StatusChoice(
        status: kStatusUnsettled,
        deed: 'ownerDoubt',
        label: 'İş dəqiq deyil',
        note: 'iştirakçılar xəbər tutacaq',
      ),
      StatusChoice(
        status: kStatusCancelled,
        deed: isAgreement ? 'cancelRequested' : 'ownerCancelled',
        label: 'İş ləğv olundu',
        // ВОТ ТА САМАЯ РАЗНИЦА, СКАЗАННАЯ СЛОВАМИ.
        note: isAgreement
            ? '${otherSideName ?? 'qarşı tərəf'} təsdiqləməlidir'
            : 'tədbir təqvimdə qalacaq',
        asksOtherSide: isAgreement,
      ),
    ];
