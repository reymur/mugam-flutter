/// ЧТО ВЛАДЕЛЕЦ МОЖЕТ СДЕЛАТЬ С ВЫШЕДШИМ УЧАСТНИКОМ — правило отдельно от
/// экрана.
///
/// **Вынесено сюда, потому что это ровно тот случай, на который заведено I32:**
/// «состояние × роль → какие действия предложены». Сторожа на порядок ветвей в
/// разметке нет и быть не может, а вот таблица «кому и когда показана кнопка»
/// проверяется тестом. Оставь это условие в `build`, и единственной защитой
/// была бы внимательность читающего пятитысячную строку экрана.
///
/// Утверждение здесь — **о НАЛИЧИИ** («у вышедшего владельцу предложено ровно
/// два действия»), поэтому оно само себе канарейка (I31): ослепни разбор — и
/// список станет пустым, а пустой список не равен ожидаемым двум.
library;

import 'event_answers.dart';

/// Одно действие окошка: имя поступка, надпись и то, что произойдёт.
///
/// Форма повторяет [StatusChoice] из `event_status_view.dart` НЕ из подражания:
/// оба окошка объясняют последствие ДО нажатия, потому что оба необратимы для
/// того, кого касаются. Разделить их всё же пришлось — у состояния есть
/// `status`, которого у этих двух нет вовсе.
class LeftMemberAction {
  const LeftMemberAction({
    required this.deed,
    required this.label,
    required this.note,
  });

  /// Имя поступка — литералом рядом с именем, как у ответов участника: проход
  /// по исходникам читает литералы, и вынос значения за константу сделал бы
  /// его невидимым ровно там, где он сторожит.
  final String deed;

  /// Надпись на языке экрана (азербайджанский).
  final String label;

  /// Что произойдёт — словами, до нажатия.
  final String note;
}

const String kLeftActionClarify = 'clarify';
const String kLeftActionRemove = 'remove';

/// ПОКАЗЫВАТЬ ЛИ КНОПКУ «?» У ЭТОГО УЧАСТНИКА.
///
/// **Берёт три uid, а не готовые `isOwner`/`isSelf`, и это не многословность.**
/// Готовые признаки вычисляет вызывающий, а вычислить их можно НЕСОГЛАСОВАННО
/// — передать `isOwner: true` вместе с чужим `memberUid` ничто не помешает, и
/// правило подтвердит то, чего нет. Из трёх uid оба признака выводятся здесь,
/// и рассогласовать их нечем.
///
/// Три условия, и все обязательны:
///
///   • **только владельцу** — состав правит он, и спрашивать «почему ушёл»
///     от чужого имени некому;
///   • **только у вышедшего** (`answer == kAnswerLeft`) — у остальных
///     четырёх ответов спрашивать нечего: `going` и `cant` уже ответы,
///     `waiting` ждёт самого человека, `notAsked` ждёт владельца, и ему там
///     нужна не эта кнопка, а приглашение;
///   • **НЕ НА САМОМ СЕБЕ.** Заведено 12.08 обходом «где можно ткнуть в себя
///     и получить действие, рассчитанное на другого» — единственная дырка из
///     десяти проверенных мест, и она была здесь.
///
/// **Почему на себя вообще можно было попасть.** Владелец лежит в составе
/// собственного вечера — у договоров `onChatUpdated` кладёт туда обе стороны
/// (**18 документов из 75**: 16 договоров = 27 − 11 и 2 мероприятия = 48 − 46,
/// перепись прода 10.08, N112). Значит строка с его именем в составе есть, и
/// стоит его собственному ответу стать `left`, как оба хода наводятся на него
/// самого: «Dəqiqləşdir» открыл бы **чат с самим собой**, а «Siyahıdan sil»
/// вычеркнул бы владельца из его же вечера.
///
/// **Пустой uid — это не человек, и совпадение двух пустых не означает «это
/// я».** Без этой проверки незалогиненный смотрящий (`currentUid == ''`) при
/// пустом `ownerUid` прошёл бы первое условие.
///
/// **Прошедший вечер здесь НЕ отсечён, и это оставлено намеренно, а не
/// забыто.** У плашки состояния такое отсечение есть («спорить о том,
/// состоялся ли вчерашний вечер, приложению нечем»), и по тому же доводу его
/// хочется поставить и сюда. Но довод не совпадает: плашка МЕНЯЕТ судьбу
/// прошедшего вечера, а «Dəqiqləşdir» всего лишь открывает переписку, и
/// спросить вчерашнего отказника «что случилось» — законный ход. Про
/// «Siyahıdan sil» на прошедшем вечере решения владельца проекта нет; когда
/// оно появится, менять надо здесь, и тест назовёт, что сломалось.
bool offersLeftMemberMenu({
  required String viewerUid,
  required String memberUid,
  required String ownerUid,
  required String? answer,
}) =>
    viewerUid.isNotEmpty &&
    memberUid.isNotEmpty &&
    viewerUid == ownerUid &&
    viewerUid != memberUid &&
    answer == kAnswerLeft;

/// Два действия окошка, в порядке макета: сперва разговор, потом удаление.
///
/// **Порядок не косметика.** Удаление из состава отнимает у человека доступ к
/// мероприятию (в базе состав и право видеть — одно поле `musicians`), то есть
/// после него спросить уже не выйдет: собеседник перестанет видеть предмет
/// разговора. Разговор поэтому стоит первым — он обратим, а удаление нет
/// (I48: у необратимого шага должна быть одна переменная, и здесь она одна —
/// человек уходит из состава).
///
/// [name] — имя вышедшего; пустое даёт безличную запись, а не «null ушёл».
List<LeftMemberAction> leftMemberActions({String? name}) {
  final who = (name == null || name.isEmpty) ? 'İştirakçı' : name;
  return [
    const LeftMemberAction(
      deed: kLeftActionClarify,
      label: 'Dəqiqləşdir',
      note: 'şəxsi çatda soruşacaqsınız',
    ),
    LeftMemberAction(
      deed: kLeftActionRemove,
      label: 'Siyahıdan sil',
      // ЧЕСТНОЕ ПОСЛЕДСТВИЕ, А НЕ ПЕРЕСКАЗ НАДПИСИ. «Уберётся из списка» —
      // это то же самое, что написано на кнопке, то есть N109 в миниатюре:
      // строка, занимающая место и не сообщающая ничего. Настоящее
      // последствие другое и неочевидное: состав в базе — то же поле, на
      // котором стоит право видеть, и удалённый теряет мероприятие из виду.
      note: '$who tədbiri artıq görməyəcək',
    ),
  ];
}
