/// ОТВЕТ УЧАСТНИКА КАК ПОСТУПОК — шаг 4, пункт 3 (`docs/plan.md`).
///
/// До этого файла ответ существовал только как ЗНАЧЕНИЕ: его писал владелец,
/// правя состав, и читал экран. Поступка «участник ответил» не было вовсе —
/// ни кнопки, ни записи, ни вопроса. Здесь заводится его правило; окно и
/// запись стоят отдельно и зовут отсюда.
///
/// **ЧЕЛОВЕК МОЖЕТ СОГЛАСИТЬСЯ НА ДВА ВЕЧЕРА В ОДНО ВРЕМЯ, и сказать ему об
/// этом надо В МОМЕНТ СОГЛАСИЯ** (решение владельца 11.08). Это прямое
/// следствие того, что «ждём» перестал занимать календарь: сняв занятость с
/// приглашения, мы сняли и единственную преграду от двух вечеров разом. Не
/// спросив при согласии, мы получим человека в двух местах, и выяснится это в
/// день события — ровно то, ради чего проверка конфликта заводилась.
library;

import '../../firebase/models.dart';
import '../../shared/widgets/event_conflict_banner.dart';
import 'event_answers.dart';

/// Что человеку можно ответить на «в это время у тебя уже есть вечер».
///
/// **НАБОР НЕ СОВПАДАЕТ с ответами при создании — и это не оттенок, а
/// граница возможного.** Там «Təqvimimdən sil» / «Əvəz et» правят ЧУЖОЙ
/// документ: удаляют мешающее мероприятие или переписывают его. Здесь такого
/// ответа быть не может **по правилам** (шаг 4, пункт 1): участнику
/// разрешено тронуть ровно свой ключ в `answers`
/// (`diff().affectedKeys().hasOnly([request.auth.uid])`), и кнопка, трогающая
/// мешающий вечер, получила бы отказ сервера.
///
/// **Это урок N39, а не осторожность.** Там главная, золотая кнопка окна
/// удаляла постороннее мероприятие у человека, пришедшего снять участника.
/// Здесь тот же соблазн опаснее вдвое: поступок совершает не владелец вечера,
/// а приглашённый, которому чужой документ не принадлежит ни в каком смысле.
enum AnswerConflictChoice {
  /// Посмотреть тот вечер. Ничего не пишет.
  view,

  /// «Всё равно иду» — пишет `going`. Человек в двух местах, и это его
  /// решение, ровно как «Yeni tədbir» при создании (правило владельца 03.08:
  /// два мероприятия в один день — обычная жизнь, решает человек).
  goAnyway,

  /// «Не могу» — пишет `cant`.
  cannotGo,
}

/// Ответы окна — ВСЕГДА одни и те же, независимо от того, чей мешающий вечер.
///
/// **Ветки по владению здесь нет, и это проверяется тестом.** В N39 вопрос
/// подменялся владением там, где ответ от него не зависел; здесь ни один из
/// трёх ответов мешающего документа не касается вовсе, значит и различать
/// нечего. Функция заведена именно ради того, чтобы это утверждение было
/// записано **исполняемо**, а не комментарием.
Set<AnswerConflictChoice> answerConflictChoices() => const {
      AnswerConflictChoice.view,
      AnswerConflictChoice.goAnyway,
      AnswerConflictChoice.cannotGo,
    };

/// ЧТО ЗАПИСАТЬ ПОСЛЕ ОКНА — или `null`, если писать не надо вовсе.
///
/// **ЗАКРЫТИЕ ОКНА — ОТДЕЛЬНЫЙ ИСХОД, а не «не могу».** Человек мог выйти
/// подумать, и записать за него отказ значило бы ответить вместо него. `null`
/// приходит и от системного закрытия, и от кнопки «назад» — оба означают одно:
/// **поступка не было**, прежний ответ остаётся прежним.
///
/// **«Посмотреть» тоже ничего не пишет** — по той же причине: это не ответ, а
/// отсрочка ответа.
///
/// Вынесено чистой функцией намеренно (I17): внутри виджета это решение
/// непроверяемо, а слить «закрыл окно» с «не могу» — ровно тот вид ошибки,
/// который первый же рефакторинг сделает молча (I47). Здесь оно падает.
String? answerAfterConflict(AnswerConflictChoice? choice) => switch (choice) {
      null => null,
      AnswerConflictChoice.view => null,
      AnswerConflictChoice.goAnyway => kAnswerGoing,
      AnswerConflictChoice.cannotGo => kAnswerCant,
    };

/// ЗАНЯТЫЙ ДЕНЬ — ПЛАШКОЙ ДО НАЖАТИЯ, а не вопросом после (макет
/// `mugam-6-kart.html`: «Bu gün artıq tədbirin var · 19:00 · Toy»).
///
/// **Два случая расходятся не по строгости, а по тому, что человек должен
/// сделать:**
///
/// - **занят ДЕНЬ** — мешать нечему, два мероприятия в один день это обычная
///   жизнь (решение владельца 03.08). Здесь нужно **сказать, а не спросить**:
///   плашка стоит рядом с кнопками и видна ДО нажатия — правило владельца
///   03.08 «предупреждать до нажатия, а не после»;
/// - **занята МИНУТА** — человек оказался бы в двух местах разом, и это
///   вопрос с ответами ([answerConflicts] ниже).
///
/// Возвращает мероприятия того же дня БЕЗ занявших ту же минуту: иначе один
/// вечер сказал бы о себе дважды — и плашкой, и окном.
List<PersonalEvent> answerDayNotice({
  required PersonalEvent target,
  required List<PersonalEvent> myEvents,
  required String currentUid,
}) {
  final DateTime when;
  try {
    when = DateTime.parse(target.date);
  } catch (_) {
    return const [];
  }
  final exact = exactConflictsAt(when, myEvents,
          currentUid: currentUid, excludeEventId: target.id)
      .map((e) => e.id)
      .toSet();
  return conflictEventsOnDay(when, myEvents,
          currentUid: currentUid, excludeEventId: target.id)
      .where((e) => !exact.contains(e.id))
      .toList();
}

/// СПРАШИВАТЬ ЛИ ВООБЩЕ — и когда молчать.
///
/// Спрашиваем **только при согласии** и **только на точном совпадении
/// минуты**:
///
/// - **не согласие** (`cant`) — человек как раз освобождает время, мешать
///   ему нечем;
/// - **занят лишь ДЕНЬ** — обычная жизнь (решение владельца 03.08). Иначе
///   человек с дневным делом получал бы вопрос на каждый вечер, а вопрос,
///   который задают всегда, перестают читать.
///
/// [eventId] исключается из проверки **всегда**: это тот самый вечер, на
/// который отвечают. Без исключения документ конфликтует сам с собой — у
/// владельца он занят по `ownerUid`, а при смене ответа с `going` на `going`
/// занят и у участника.
///
/// [when] — время вечера, на который отвечают. Разбирается здесь, а не у
/// вызывающего: дата в документе лежит строкой, и место разбора должно быть
/// одно.
List<PersonalEvent> answerConflicts({
  required PersonalEvent target,
  required List<PersonalEvent> myEvents,
  required String currentUid,
  required String answer,
}) {
  if (answer != kAnswerGoing) return const [];
  final DateTime when;
  try {
    when = DateTime.parse(target.date);
  } catch (_) {
    // Битая дата — сравнивать не с чем. Молчим, а не выдумываем занятость:
    // ложная тревога здесь стоила бы отказа от вечера, на который человек
    // собирался.
    return const [];
  }
  return exactConflictsAt(
    when,
    myEvents,
    currentUid: currentUid,
    excludeEventId: target.id,
  );
}
