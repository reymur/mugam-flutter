/// СПРЯТАННЫЕ СТРОКИ «ЧТО СЛУЧИЛОСЬ» — то, что человек убрал крестиком.
///
/// Требование владельца 28.08: «справа иконка удаления, если пользователя
/// раздражает — он это убирает».
///
/// --- НА ТЕЛЕФОНЕ, А НЕ В БАЗЕ, И ЭТО РЕШЕНИЕ ---
///
/// Дороги было две, и вторая дороже втрое:
///
///   • **в документе вечера** (поле вроде `deedDismissedBy`) — потребовало бы
///     правки `firestore.rules` и **отдельной выкладки правил**, то есть
///     необратимого шага ради того, чтобы человеку не мозолила глаза строка;
///   • **на телефоне** (`SharedPreferences`) — ноль правил, ноль выкладок,
///     и семантика вернее: раздражает КОНКРЕТНОГО смотрящего, а не вечер.
///
/// **Цена решения названа прямо: скрытие живёт на одной трубке.** Убрал у
/// себя — у второй стороны строка остаётся, и это правильно; но и у себя же,
/// переставив приложение или сменив телефон, человек увидит её снова. Для
/// «убери с глаз» этого хватает; для чего-то важнее — не хватило бы, и тогда
/// пришлось бы в базу.
///
/// --- ПОЧЕМУ ХРАНИТСЯ СПИСОК КЛЮЧЕЙ, А НЕ ФЛАЖОК НА ВЕЧЕР ---
///
/// Ключ строит `deedDismissKey` и включает в него сам поступок, а не только
/// вечер: спрятанной становится КОНКРЕТНАЯ новость. Убравший «Rafael ayrıldı»
/// обязан увидеть следующее сообщение об этом же вечере — например, что вечер
/// отменили. Флажок на вечер закрыл бы ему рот навсегда.
///
/// **Список не чистится, и это осознанно.** Каждый ключ — десятки байт,
/// вечеров у человека сотни, роста здесь нет. Чистка потребовала бы знать,
/// какие вечера ещё существуют, то есть читать базу ради уборки настроек.
library;

import 'package:flutter_riverpod/flutter_riverpod.dart';

import '../settings/image_quality_settings.dart' show sharedPreferencesProvider;

/// Ключ в настройках телефона. Имя с приставкой проекта — рядом лежат чужие.
const String kDismissedDeedsKey = 'dismissed_event_deeds';

/// Какие строки человек убрал с глаз.
///
/// Наружу отдаётся **множество**, а не список: вопрос к нему всегда один —
/// «эта спрятана?», — и порядок в нём не значит ничего.
class DismissedDeeds extends Notifier<Set<String>> {
  @override
  Set<String> build() => ref
      .watch(sharedPreferencesProvider)
      .getStringList(kDismissedDeedsKey)
      ?.toSet() ??
      <String>{};

  /// Спрятать строку. Повтор безвреден — множество, а не список.
  Future<void> dismiss(String key) async {
    if (key.isEmpty || state.contains(key)) return;
    final next = {...state, key};
    // СНАЧАЛА ЭКРАН, ПОТОМ ДИСК — намеренно. Запись на диск асинхронна, и
    // ждать её значило бы задержать исчезновение строки под пальцем. Не
    // допишись она (диск полон, приложение убито в ту же миллисекунду) —
    // строка вернётся на следующем запуске. Это худший исход, и он не
    // страшен: человек нажмёт крестик ещё раз.
    state = next;
    await ref
        .read(sharedPreferencesProvider)
        .setStringList(kDismissedDeedsKey, next.toList());
  }
}

final dismissedDeedsProvider =
    NotifierProvider<DismissedDeeds, Set<String>>(DismissedDeeds.new);
