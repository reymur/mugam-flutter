// ПОЧЕМУ ОТКАЗАНО — правило, разбирающее `permission-denied` (N45)
// ---------------------------------------------------------------------------
// Найдено 06.08 сверкой боевых правил с кодом. `_cancelStep` ловил
// `permission-denied` отдельной веткой и объяснял его ГОНКОЙ СТОРОН: «вас
// опередили». Пока правила отмены не были выложены, та же ветка ловила
// совсем другое — отсутствие правила, — и рассказывала про него неправду,
// молча: в Crashlytics этот случай не уходит по замыслу, потому что гонка
// не поломка.
//
// САМА ОШИБКА НЕРАЗЛИЧИМА, и это не наша недоработка: Firestore на отказ
// правил отдаёт `permission-denied` с общим текстом и не называет ни
// правила, ни условия — иначе он выдавал бы наружу их устройство.
// Ветвиться в `catch` не на чем и не будет.
//
// РАЗЛИЧИМО СОСТОЯНИЕ. Каждое сообщение про гонку утверждает конкретное
// состояние второй стороны, а состояние можно прочитать. Отсюда правило
// ниже: один вопрос — **объясняет ли прочитанное состояние этот отказ**.
//
// ЧИТАТЬ ОБЯЗАТЕЛЬНО С СЕРВЕРА, не из кэша. Кэш вернёт ровно ту картину,
// из которой мы и решили, что ход законен, — то есть подтвердит нашу же
// ошибку и объявит гонкой любой отказ.

/// Что случилось на самом деле, когда правила отказали.
enum CancelDenial {
  /// Состояние объясняет отказ: вторая сторона успела раньше. Сообщение
  /// про гонку верно, в Crashlytics не сообщаем — это законный исход.
  race,

  /// Состояние отказ НЕ объясняет: причина в чём-то другом — не выложены
  /// правила, разошлись имена поступков, испорчены данные. Человеку —
  /// осторожные слова, в Crashlytics — обязательно.
  unknown,
}

/// Объясняет ли прочитанное с сервера состояние отказ по правам.
///
/// [deed] — ход, который отклонили; [status] и [cancelRequestedBy] —
/// прочитанные С СЕРВЕРА поля, [currentUid] — кто ходил.
///
/// ГРАНИЦА НАЗВАНА ВСЛУХ, И ЕЁ НЕ НАДО «УЛУЧШАТЬ»: гонка, успевшая
/// разрешиться (вторая сторона отозвала своё, пока мы получали отказ),
/// даст состояние, которое отказ уже не объясняет, и попадёт в
/// [CancelDenial.unknown]. Это ошибка в БЕЗОПАСНУЮ сторону: осторожные
/// слова и запись в Crashlytics вместо уверенной неправды. Обратный
/// размен — считать необъяснённое гонкой — возвращает ровно тот дефект,
/// ради которого правило заведено.
CancelDenial explainCancelDenial({
  required String deed,
  required String status,
  required String? cancelRequestedBy,
  required String currentUid,
}) {
  // Отменённый договор объясняет отказ любому ходу: правила запрещают всё
  // при `status == 'cancelled'`, и это самая частая гонка — вторая
  // сторона подтвердила, пока человек читал экран.
  if (status == 'cancelled') return CancelDenial.race;

  switch (deed) {
    // Просил отмену, а отказали — значит запрос уже стоит. Чей угодно:
    // свой (нажал дважды) или чужой (опередили).
    case kCancelRequested:
      return cancelRequestedBy != null
          ? CancelDenial.race
          : CancelDenial.unknown;

    // Подтверждал или отклонял ЧУЖОЙ запрос — отказ объясняется тем, что
    // чужого запроса больше нет: отозван или его не было вовсе.
    case kCancelConfirmed:
    case kCancelDeclined:
      return (cancelRequestedBy == null || cancelRequestedBy == currentUid)
          ? CancelDenial.race
          : CancelDenial.unknown;

    // Отзывал СВОЙ — объясняется тем, что запрос больше не мой.
    case kCancelWithdrawn:
      return cancelRequestedBy != currentUid
          ? CancelDenial.race
          : CancelDenial.unknown;
  }
  return CancelDenial.unknown;
}
