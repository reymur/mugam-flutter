// КОГО ЗОВЁТ «ÖZ ADAMLARIMI ÇAĞIR» — правило, а не разметка (17.09)
// ---------------------------------------------------------------------------
// ПОВОД. Решение «звать или пропустить» жило прямо в `_callMyPeople` одной
// строкой — `if (!already.contains(uid))`, где `already` это `musicians`. Оно
// не проверялось ничем: условие в разметке прогнать нечем (I32), и потому
// дожило до трубки. Владелец, не убирая вышедшего, нажал «позвать» дважды —
// приложение показало «приглашение отправлено», а Теймуру не пришло ничего.
//
// ПОЧЕМУ ОДНА СТРОКА ОКАЗАЛАСЬ НЕВЕРНОЙ. `musicians` после выхода значит
// «имеет право видеть вечер», а не «участвует»: вышедший остаётся в списке с
// пометкой «İşdən çıxdı» (решение 29.08, N121 шаг 2). Зов читал это поле как
// «уже позван» — и молча пропускал того, кого зовут.
//
// ЧТО ЗДЕСЬ РЕШАЕТСЯ И ЧТО НЕТ. Здесь — ТОЛЬКО «что сделать с этим человеком»
// по данным вечера. Открытый раунд предложения работы сюда не входит: он
// живёт на документе чата, у каждой пары свой, и спрашивать его надо у базы.
// Правило чистое и прогоняется без Firestore (I55: портить настоящий путь, а
// не ближайшую удобную точку).
//
// ПЕРВЫЙ ЗАХОД ПОВЕДЕНИЯ НЕ МЕНЯЛ — он разносил только МЕСТО решения. Второй
// (17.09) починил само решение: вышедший больше не считается спрошенным.
// Разнесено это по двум шагам нарочно, чтобы на живую пробу не поехали две
// переменные разом.

/// Что делать с отмеченным человеком.
enum CallOutcome {
  /// Его в составе нет — добавить и спросить.
  addToParty,

  /// Он в составе, но ВЫШЕЛ либо его не спрашивали — поставить `waiting`,
  /// унести причину выхода вместе с голосом и известить.
  ///
  /// **ДВА СЛУЧАЯ ПОД ОДНИМ ИСХОДОМ, И ЭТО НЕ СЛИЯНИЕ ДВУХ НЕЗНАНИЙ (I47).**
  /// `left` — «я ушёл», `notAsked` — «меня не спрашивали»; в данных они
  /// различны, и различие сохраняется. Одинаково у них ДЕЙСТВИЕ: человек в
  /// составе есть, вопроса перед ним нет, и зов обязан вопрос поставить.
  /// Решается здесь «что сделать», а не «что случилось».
  askAgain,

  /// Он в составе, и вопрос перед ним СТОИТ либо он на него ответил. Трогать
  /// нечего: повторный зов не задаёт вопроса заново, он его повторяет.
  alreadyAsked,
}

/// Один отмеченный человек и что с ним делать.
class CallTarget {
  const CallTarget({required this.uid, required this.outcome});

  final String uid;
  final CallOutcome outcome;
}

/// РАЗОБРАТЬ ОТМЕЧЕННЫХ.
///
/// [picked] — кого владелец отметил в окне выбора, в порядке отметки.
/// [event] — вечер: состав и ответы.
///
/// **ПОРЯДОК ОТМЕТКИ СОХРАНЯЕТСЯ.** Он же порядок, в каком человек собирал
/// состав, и пересказывать его своими словами правило не вправе.
///
/// **ОДИН UID — ОДИН РАЗБОР.** Дважды отмеченный человек даёт одну запись:
/// иначе он ушёл бы в состав дважды, а это уже оплачено двойной строкой на
/// экране 17.09.
///
/// **ПУСТОЙ uid ВЫБРАСЫВАЕТСЯ.** Он не человек, и завести на него ключ в
/// карте ответов значило бы сделать запись, которую некому сопоставить.
List<CallTarget> callTargets({
  required PersonalEvent event,
  required List<String> picked,
}) {
  final out = <CallTarget>[];
  final seen = <String>{};
  for (final uid in picked) {
    if (uid.isEmpty) continue;
    if (!seen.add(uid)) continue;
    // ПРИЗНАК — ОТВЕТ, А НЕ СОСТАВ, и вот где различие становится видно.
    // `musicians` после выхода значит «видит вечер», а не «участвует»:
    // вышедший остаётся в списке с пометкой «İşdən çıxdı». Прежнее условие
    // читало это как «уже позван» и молча глотало зов.
    final answer = event.answerFor(uid);
    out.add(CallTarget(
      uid: uid,
      outcome: switch (answer) {
        // Его в составе нет вовсе.
        null => CallOutcome.addToParty,
        // Вышел сам — зов возвращает его в ожидание (решение владельца
        // 17.09). Довод владельца дословно: Рафаэль видит вышедшего и жмёт
        // «позвать» — это естественное действие, и приложение обязано его
        // выполнить, а не промолчать.
        kAnswerLeft => CallOutcome.askAgain,
        // В составе, а ключа нет: вопроса ему не задавали (N115). Зов задаёт.
        kAnswerNotAsked => CallOutcome.askAgain,
        // `going` и `waiting` — вопрос уже стоит либо отвечен.
        _ => CallOutcome.alreadyAsked,
      },
    ));
  }
  return out;
}

/// ЕСТЬ ЛИ ВООБЩЕ ЧТО ОТПРАВЛЯТЬ.
///
/// **Заведено ради плашки, и это не удобство, а починка.** Плашка «Çağırış
/// göndərildi» показывалась по числу ОТМЕЧЕННЫХ, а не отправленных: человек,
/// уже бывший в составе, молча попадал в счёт. Владелец дважды нажал
/// «позвать» на вышедшем, увидел «отправлено» и был уверен, что позвал.
///
/// **Утверждение о НАЛИЧИИ, а не об отсутствии** (I31): «есть кому уйти»
/// ломается с криком, «никому не ушло» ломалось бы молча.
bool anythingToSend(List<CallTarget> targets) =>
    targets.any((t) => t.outcome != CallOutcome.alreadyAsked);
