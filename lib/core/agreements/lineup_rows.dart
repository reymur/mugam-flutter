// Заведён ПРОБОЙ, а не разбором (N210): шаг 5 прошёл все четыре пробы и оставил
// зовущего без ответа на вопрос «кого я позвал». Граница была названа заранее,
// в трёх местах, и всё равно прочиталась как недоделка — у объявленной пропажи
// нет отличительного признака, на экране она выглядит ровно как забытая.
//
// ДВА ИСТОЧНИКА, И ЭТО НЕ ПЕРЕСТРАХОВКА, А ЕДИНСТВЕННОЕ ВЕРНОЕ ЧТЕНИЕ.
// Строка обязана сказать четыре вещи; ни один источник не знает всех четырёх:
//
//   `lineup` родителя — имя, позван ли, ПОЧЕМУ не позван. Ответа не знает
//                       вовсе: ответ пишет приглашённый в СВОЙ документ;
//   дети по `parentEventId` — имя, позван ли, ОТВЕТ. Про непозванного не знает
//                       ничего: документа у него нет по определению.
//
// Лишних чтений ни одного: экран смотрит `personalEventsProvider(currentUid)`
// (`where('ownerUid', isEqualTo: uid)`), а у детей владелец — зовущий, и
// родитель приходит тем же потоком.
//
// ДОВОД СИЛЬНЕЕ ПОЛНОТЫ: КАЖДЫЙ ИСТОЧНИК МОЖЕТ ПРОПАСТЬ ОТДЕЛЬНО.
//   • запись `lineup` может не состояться ПОСЛЕ созданных детей — порядок
//     такой нарочно, дети сами себе свидетели. Возьми только шаблон — и
//     карточка скажет «никого не звали» при двух позванных;
//   • ребёнка зовущий может снять: `allow delete` по `ownerUid`
//     (`firestore.rules`) и `ownerCancelsOwnEvent` — у ребёнка
//     `isAgree == false`, значит ход ему доступен. Возьми только детей — и
//     непозванный исчезнет; возьми только шаблон — и снятое приглашение
//     покажется ожиданием ответа.

/// ЧТО СТАЛО С ПРИГЛАШЕНИЕМ ЭТОГО ЧЕЛОВЕКА.
///
/// **Три вида, а не два, и третий — тот, о котором не думают.** Он же
/// единственный, ради которого этот перечень вообще существует: без него
/// «приглашение сняли» слилось бы с «ждём ответа», а это два разных незнания
/// с разным адресатом следующего хода (I47, цена уже заплачена в N13).
enum LineupRowKind {
  /// Приглашение существует. Ответ — в [LineupRow.answer].
  invited,

  /// Приглашения нет и не было: отправка не состоялась. Причина — в
  /// [LineupRow.reason].
  notInvited,

  /// Приглашение БЫЛО и его больше нет — снято или отменено зовущим.
  ///
  /// **Отличать обязательно.** В шаблоне такой человек записан позванным, а
  /// ответа у него нет, и без этого вида строка сказала бы «cavab gözlənilir»
  /// о вопросе, который сняли, — то есть пообещала бы ответ, которого никто
  /// не ждёт.
  withdrawn,
}

/// Одна строка списка «кого я позвал».
class LineupRow {
  const LineupRow({
    required this.uid,
    required this.name,
    required this.kind,
    this.answer,
    this.reason,
    this.eventId,
    this.status,
    this.unsettledReason,
  });

  final String uid;

  /// Имя, УЖЕ разрешённое: живое, запасное из шаблона либо пустое.
  ///
  /// Пустое значит «сведений нет» и на экране становится «Naməlum». Врать
  /// вместо пустоты чужим именем нельзя — этим уже оплачен `partnerName`.
  final String name;

  final LineupRowKind kind;

  /// Что ответил приглашённый — значение из словаря `event_answers.dart`.
  ///
  /// Только у [LineupRowKind.invited]. У остальных `null`: там вопроса нет
  /// вовсе, и `notAsked` сюда писать нельзя — он означает отсутствие ключа в
  /// карте, а не отсутствие приглашения.
  final String? answer;

  /// Отчего приглашение не ушло. Только у [LineupRowKind.notInvited].
  final String? reason;

  /// ТРИ ПОЛЯ НИЖЕ — ДОБАВЛЕНИЕ, А НЕ ВТОРАЯ ДОРОГА К ПРИГЛАШЕНИЮ (N220).
  ///
  /// **Проверяется тремя вопросами, а не заверением:**
  ///
  /// 1. **лишних чтений ноль.** Документ ребёнка эта функция уже держит в
  ///    руках — `childOf[uid]`, — и уже читает у него `status` (строкой
  ///    `final live = child.status != kStatusCancelled`) и `answerFor`.
  ///    Новое здесь только то, что прочитанное отдаётся наружу;
  /// 2. **новых решений ноль.** «Предлагать ли возврат» решает
  ///    [offersLineupRestore] ниже, а он зовёт **тот же `showsRestore`**, что
  ///    и карточка. Второго правила про один вопрос не заводится (N49);
  /// 3. **новых маршрутов ноль.** Возврат — это существующий ход `restored`
  ///    на документе ребёнка. Экрана ребёнка не появляется, `eventDetailRoute`
  ///    не трогается, третьего пути к тому же документу нет (N90, N117 —
  ///    дважды оплачено).
  ///
  /// Признак I58 в обратную сторону сошёлся: вызывающему **не понадобился
  /// переключатель**, строка получает данные, а решает правило.
  ///
  /// `null` у всех, кроме [LineupRowKind.invited]: у снятого и непозванного
  /// документа нет вовсе.
  final String? eventId;

  /// Состояние документа приглашения.
  final String? status;

  /// Повод состояния. Пишет только сервер, клиенту запрещено правилами.
  final String? unsettledReason;
}

/// ПРЕДЛАГАТЬ ЛИ НА ЭТОЙ СТРОКЕ ВОЗВРАТ РЕБЁНКА В СИЛУ (N220, 11.09).
///
/// **ТОЛЬКО У СОГЛАСИВШИХСЯ, и это решение владельца 11.09 с доводом.** У
/// ответившего «Bacarmıram» вечер вернулся бы **без состава**: зовущий получил
/// бы пустой вечер и не понял почему, а человеку навязали бы работу, от
/// которой он отказался. У молчавшего — хуже: **отказа не было, и вернуть его
/// значит вернуть ВОПРОС**, то есть спросить заново от чужого имени. Тех и
/// других зовут заново, обычным приглашением.
///
/// **`isOwner: true` НЕ ДОПУЩЕНИЕ, А СВОЙСТВО ИСТОЧНИКА.** Строки собираются
/// из `personalEventsProvider(currentUid)` — запроса
/// `where('ownerUid', isEqualTo: uid)`, — значит владелец каждого ребёнка в
/// списке и есть смотрящий. Передаётся явно, а не прячется: соври источник —
/// и правило соврёт молча.
///
/// **ЗДЕСЬ ТРЕТИЙ ВЫЗЫВАЮЩИЙ `showsRestore`, И ОН ЖЕ ПЕРВЫЙ ЖИВОЙ ДЛЯ ТОГО,
/// КОМУ КНОПКА НУЖНА** (N223). Прежний вызывающий стоит на карточке вечера, где
/// `isOwner` у приглашённого ложно всегда, — то есть предикат существовал при
/// дороге, по которой не мог пройти тот, ради кого написан.
/// **ПОВОД СУЖЕН ДО `workCancelled`, И ЭТО НЕ ДУБЛИРОВАНИЕ `showsRestore`.**
/// Тот отвечает «какие поводы ВООБЩЕ допускают возврат» и принимает два;
/// здесь спрашивается «какие допускают возврат ОТСЮДА», и ответ у́же.
///
/// **Поймано вердиктом 11.09, а не разбором.** Без сужения «Qaytar» вылезал бы
/// и у ребёнка под вопросом из-за УХОДА участника — случая, по которому
/// решения владельца нет вовсе. А у приглашения состав из одного человека:
/// вернув его в силу после ухода этого самого человека, зовущий получил бы
/// пустой вечер — ровно то, ради чего отказавшимся возврат и не предлагают.
///
/// Довод тот же, что записан у самого `showsRestore`: **перечисление, а не
/// «любой повод»** — иначе новый повод молча поедет в «можно вернуть».
bool offersLineupRestore(LineupRow r) =>
    r.kind == LineupRowKind.invited &&
    r.answer == kAnswerGoing &&
    r.unsettledReason == kReasonWorkCancelled &&
    showsRestore(
      isOwner: true,
      status: r.status ?? '',
      unsettledReason: r.unsettledReason,
    );

/// СОБРАТЬ СТРОКИ ИЗ ДВУХ ИСТОЧНИКОВ.
///
/// [lineup] — шаблон с родителя, в порядке отметки. [children] — свои вечера
/// зовущего целиком; отбор по `parentEventId` делается здесь, а не у
/// вызывающего, чтобы правило было одно.
///
/// [nameOf] — живое имя по uid, `null` если человека в списке нет. Передаётся
/// функцией, а не списком людей: правило не должно знать про `User`, иначе его
/// нечем прогнать без модели экрана.
///
/// **ПОРЯДОК — ШАБЛОНА, И ЭТО ПОРЯДОК ОТМЕТКИ.** Он же порядок приглашений:
/// человек собирал состав в каком-то порядке, и показать его иначе значит
/// пересказать чужое решение своими словами. Дети, которых в шаблоне нет,
/// дописываются в конец — их порядок неизвестен, и выдумывать его нечем.
///
/// **РЕБЁНОК СТАРШЕ ШАБЛОНА ВЕЗДЕ, ГДЕ ОНИ СПОРЯТ.** Документ — то, что
/// произошло; шаблон — то, что записали о произошедшем. Шаблон мог не
/// дописаться, документ существует либо нет.
List<LineupRow> lineupRows({
  required List<LineupSlot> lineup,
  required List<PersonalEvent> children,
  required String parentEventId,
  required String? Function(String uid) nameOf,
}) {
  // Ребёнок на человека. Их может оказаться несколько только при поломке —
  // сторож двойного нажатия этого не допускает, — и тогда берётся первый:
  // выбирать между двумя одинаковыми нечем, а падать на показе нельзя.
  final childOf = <String, PersonalEvent>{};
  for (final e in children) {
    if (e.parentEventId != parentEventId) continue;
    for (final uid in e.participantUids) {
      if (uid.isEmpty) continue;
      childOf.putIfAbsent(uid, () => e);
    }
  }

  final rows = <LineupRow>[];
  final seen = <String>{};

  for (final slot in lineup) {
    if (!seen.add(slot.uid)) continue;
    final child = childOf[slot.uid];
    rows.add(_rowFor(
      uid: slot.uid,
      // ЖИВОЕ ИМЯ ПЕРВЫМ, ЗАПАСНОЕ ВТОРЫМ, и это весь смысл пары «uid плюс
      // снимок»: шаблон переживает людей, и запасное имя нужно ровно тогда,
      // когда uid больше не находится.
      name: nameOf(slot.uid) ?? slot.name,
      child: child,
      slot: slot,
    ));
  }

  // ДЕТИ, КОТОРЫХ НЕТ В ШАБЛОНЕ. Так выглядит незаписавшийся шаблон: дети
  // созданы, `lineup` не дописан. Показать их обязаны — приглашение у людей
  // на руках, и промолчать о нём значило бы соврать сильнее, чем показать без
  // порядка.
  for (final entry in childOf.entries) {
    if (!seen.add(entry.key)) continue;
    rows.add(_rowFor(
      uid: entry.key,
      name: nameOf(entry.key) ?? '',
      child: entry.value,
      slot: null,
    ));
  }

  return rows;
}

LineupRow _rowFor({
  required String uid,
  required String name,
  required PersonalEvent? child,
  required LineupSlot? slot,
}) {
  // ОТМЕНЁННЫЙ РЕБЁНОК — ЭТО СНЯТОЕ ПРИГЛАШЕНИЕ, А НЕ ЖИВОЕ. Он остаётся в
  // потоке (`liveEvents` выбрасывает его только из показа календаря), и
  // прочитать его ответ значило бы отчитаться о вопросе, который сняли.
  final live = child != null && child.status != kStatusCancelled;
  if (live) {
    return LineupRow(
      uid: uid,
      name: name,
      kind: LineupRowKind.invited,
      answer: child.answerFor(uid),
      // Состояние отдаётся наружу с 11.09 (N220): по нему строка решает,
      // предлагать ли возврат. Читается тот же документ, что и строкой выше.
      eventId: child.id,
      status: child.status,
      unsettledReason: child.unsettledReason,
    );
  }
  // Ребёнка нет. Два случая, и они РАЗНЫЕ (I47):
  //   шаблон говорит «не позван» — вопроса не задавали;
  //   шаблон говорит «позван»    — задавали и сняли.
  // Шаблона нет вовсе, а ребёнок был и отменён — тоже снятие: документ
  // старше шаблона.
  if (slot != null && !slot.invited) {
    return LineupRow(
      uid: uid,
      name: name,
      kind: LineupRowKind.notInvited,
      reason: slot.reason,
    );
  }
  return LineupRow(uid: uid, name: name, kind: LineupRowKind.withdrawn);
}
