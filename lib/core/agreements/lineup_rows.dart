// Заведён ПРОБОЙ, а не разбором (N210): шаг 5 прошёл все четыре пробы и оставил
// зовущего без ответа на вопрос «кого я позвал». Граница была названа заранее,
// в трёх местах, и всё равно прочиталась как недоделка — у объявленной пропажи
// нет отличительного признака, на экране она выглядит ровно как забытая.
//
// ЗДЕСЬ СТОЯЛО «ДВА ИСТОЧНИКА» — ШАБЛОН И ДЕТИ-ПРИГЛАШЕНИЯ. Снято 17.09
// вместе с самими детьми: приглашённый — участник ТОГО ЖЕ вечера (закон о
// договоре, `CLAUDE.md`). Прежний довод записан снятием, а не стёрт, потому
// что он был верен и держался на устройстве, которого больше нет:
//
//   `lineup` вечера    — имя, позван ли, ПОЧЕМУ не позван. Ответа не знал
//                        вовсе: ответ писал приглашённый в СВОЙ документ;
//   дети по `parentEventId` — имя, позван ли, ОТВЕТ. Про непозванного не знали
//                        ничего: документа у него нет по определению.
//
// ЧТО ИЗ ЭТОГО ОСТАЛОСЬ ПРАВДОЙ: шаблон по-прежнему единственный, кто знает
// про НЕПОЗВАННОГО, — у того ни строки в составе, ни ответа, и назвать его
// больше нечем.
//
// ЧТО ОТПАЛО: «каждый источник может пропасть отдельно». Состав и шаблон
// уходят ОДНОЙ записью (`FirestoreService.callPeopleToEvent`), значит случая
// «дети созданы, шаблон не дописан» не существует, а снятие приглашения
// выражается прямо — человека нет в составе.
//
// Лишних чтений ни одного и теперь их меньше: правило смотрит на сам вечер,
// который экран уже держит, и чужих документов не спрашивает вовсе.

/// ЧТО СТАЛО С ПРИГЛАШЕНИЕМ ЭТОГО ЧЕЛОВЕКА.
///
/// **Три вида, а не два, и третий — тот, о котором не думают.** Он же
/// единственный, ради которого этот перечень вообще существует: без него
/// «приглашение сняли» слилось бы с «ждём ответа», а это два разных незнания
/// с разным адресатом следующего хода (I47, цена уже заплачена в N13).
enum LineupRowKind {
  /// Приглашение существует. Ответ — в [LineupRow.answer].
  invited,

  /// Приглашения нет и не было: отправка не состоялась. Причина — в
  /// [LineupRow.reason].
  notInvited,

  /// Приглашение БЫЛО и его больше нет — снято или отменено зовущим.
  ///
  /// **Отличать обязательно.** В шаблоне такой человек записан позванным, а
  /// ответа у него нет, и без этого вида строка сказала бы «cavab gözlənilir»
  /// о вопросе, который сняли, — то есть пообещала бы ответ, которого никто
  /// не ждёт.
  withdrawn,
}

/// Одна строка списка «кого я позвал».
class LineupRow {
  const LineupRow({
    required this.uid,
    required this.name,
    required this.kind,
    this.answer,
    this.reason,
  });

  final String uid;

  /// Имя, УЖЕ разрешённое: живое, запасное из шаблона либо пустое.
  ///
  /// Пустое значит «сведений нет» и на экране становится «Naməlum». Врать
  /// вместо пустоты чужим именем нельзя — этим уже оплачен `partnerName`.
  final String name;

  final LineupRowKind kind;

  /// Что ответил приглашённый — значение из словаря `event_answers.dart`.
  ///
  /// Только у [LineupRowKind.invited]. У остальных `null`: там вопроса нет
  /// вовсе, и `notAsked` сюда писать нельзя — он означает отсутствие ключа в
  /// карте, а не отсутствие приглашения.
  final String? answer;

  /// Отчего приглашение не ушло. Только у [LineupRowKind.notInvited].
  final String? reason;

  // ЗДЕСЬ СТОЯЛИ ТРИ ПОЛЯ — `eventId`, `status`, `unsettledReason`, —
  // заведённые 11.09 ради плитки «Qaytar» на строке позванного (N220).
  // СНЯТЫ 12.09 вместе с ней: возврат по одному человеку отменён решением
  // владельца, дети идут за родителем одной записью. Ни один другой
  // читатель этих полей не спрашивал — проверено обходом перед снятием.
}

// ЗДЕСЬ БЫЛО ПРАВИЛО ПЛИТКИ «Qaytar» — `offersLineupRestore` (N220, 11.09):
// предлагать ли возврат ЭТОГО позванного, по одному человеку, только
// согласившимся и только по поводу `workCancelled`.
//
// СНЯТО 12.09 решением владельца: «никаких плиток возврата по одному
// человеку». Под вопрос ставит хозяин вечера и снимает вопрос он же — сразу
// со всего вечера, родителя и приглашений одной записью
// (`invitationsFollowing` ниже). Возврата «этому, но не тому» больше нет, а
// значит нет и правила, которое его решало.
//
// Записано снятием, а не стёрто: у правила были довод и вердикты, и без этой
// строки следующий заведёт его заново, увидев строку без кнопки.

/// КОМУ ПЕРЕДАЁТСЯ ВЫБРАННОЕ ВЛАДЕЛЬЦЕМ СОСТОЯНИЕ — 12.09.
///
/// Приглашения этого вечера, кроме отменённых. Владелец у них тот же человек,
/// значит его выбор — «под вопросом» или «отменить» — получают все разом,
/// одной записью, и каждый документ шлёт своё письмо сам.
///
/// **ОТМЕНЁННЫЕ НЕ ТРОГАЕМ**, и это не осторожность, а смысл: снятое
/// приглашение возвращать в силу нечем и незачем — вопрос человеку сняли.
///
/// **Правило здесь, а не в разметке**, потому что его можно прогнать тестом, а
/// разметку нельзя (I32). И оно одно на все три хода: отмену, вопрос и
/// возврат — иначе первый же из них разойдётся с остальными (N49).
List<String> invitationsFollowing(String parentEventId, List<PersonalEvent> events) =>
    events
        .where((e) =>
            e.parentEventId == parentEventId && e.status != kStatusCancelled)
        .map((e) => e.id)
        .toList();

/// СОБРАТЬ СТРОКИ ИЗ ОДНОГО ИСТОЧНИКА И ШАБЛОНА.
///
/// **ЗДЕСЬ БЫЛО «ИЗ ДВУХ ИСТОЧНИКОВ», И ВТОРЫМ БЫЛИ ДЕТИ-ПРИГЛАШЕНИЯ.** Их
/// больше нет: приглашённый — участник ТОГО ЖЕ вечера (закон о договоре,
/// `CLAUDE.md`, 17.09). Ответ позванного лежит там же, где ответ любого
/// другого участника, — в `answers` этого документа, и читается тем же
/// правилом `answerFor`.
///
/// **ЧТО ЭТИМ ПОТЕРЯНО — НИЧЕГО, И ЭТО ПРОВЕРЯЕМО ПО ПРЕЖНЕМУ ДОВОДУ.** Два
/// источника держались на том, что «каждый может пропасть отдельно»: шаблон
/// мог не дописаться ПОСЛЕ созданных детей, а ребёнка зовущий мог снять.
/// Первого больше не бывает — состав и шаблон уходят **одной записью**
/// (`callPeopleToEvent`), и оборваться между ними нечему. Второе никуда не
/// делось и отвечает теперь честнее: снять человека — значит убрать его из
/// состава, и строка это видит прямо, а не по отсутствию документа.
///
/// [lineup] — шаблон с вечера, в порядке отметки. [event] — сам вечер: из него
/// берётся состав и ответы.
///
/// [nameOf] — живое имя по uid, `null` если человека в списке нет. Передаётся
/// функцией, а не списком людей: правило не должно знать про `User`, иначе его
/// нечем прогнать без модели экрана.
///
/// **ПОРЯДОК — ШАБЛОНА, И ЭТО ПОРЯДОК ОТМЕТКИ.** Человек собирал состав в
/// каком-то порядке, и показать его иначе значит пересказать чужое решение
/// своими словами.
///
/// **ХОДИМ ПО ШАБЛОНУ, А НЕ ПО СОСТАВУ, И ЭТО НЕСУЩЕЕ.** Раздел отвечает на
/// вопрос «кого я ПОЗВАЛ», а состав вечера показан выше своим списком.
/// Пройди мы по составу — в раздел попали бы все, кого владелец вписал руками
/// через «+ Əlavə et», и один и тот же человек стоял бы на экране дважды. То
/// же самое было и прежде: у вписанного руками ребёнка не было, и в этот
/// список он не попадал.
///
/// **ПРЕЖНИЙ ДОПИСОК «ДЕТИ, КОТОРЫХ НЕТ В ШАБЛОНЕ» СНЯТ ВМЕСТЕ С ПРИЧИНОЙ.**
/// Он существовал ровно для случая «дети созданы, шаблон не дописался» —
/// того самого, который одна запись сделала невозможным.
List<LineupRow> lineupRows({
  required List<LineupSlot> lineup,
  required PersonalEvent event,
  required String? Function(String uid) nameOf,
}) {
  final inEvent = event.participantUids.toSet();
  final rows = <LineupRow>[];
  final seen = <String>{};

  for (final slot in lineup) {
    if (!seen.add(slot.uid)) continue;
    rows.add(_rowFor(
      uid: slot.uid,
      // ЖИВОЕ ИМЯ ПЕРВЫМ, ЗАПАСНОЕ ВТОРЫМ, и это весь смысл пары «uid плюс
      // снимок»: шаблон переживает людей, и запасное имя нужно ровно тогда,
      // когда uid больше не находится.
      name: nameOf(slot.uid) ?? slot.name,
      inEvent: inEvent.contains(slot.uid),
      // Ответ берётся ПРАВИЛОМ, а не из карты: `answerFor` знает про запасной
      // путь у документов без карты и про то, что отсутствие ключа — «не
      // спрашивали», а не «ждём». У того, кого в составе нет, он даёт `null`,
      // и строка о нём говорит не ответом, а видом.
      answer: event.answerFor(slot.uid),
      slot: slot,
    ));
  }

  return rows;
}

LineupRow _rowFor({
  required String uid,
  required String name,
  required bool inEvent,
  required String? answer,
  required LineupSlot slot,
}) {
  // ЧЕЛОВЕК В СОСТАВЕ — ЗНАЧИТ ПОЗВАН. Прежде тем же ответом был живой
  // документ-приглашение; теперь это одно и то же утверждение, сказанное
  // прямо.
  //
  // ПРОВЕРКИ НА ОТМЕНУ ЗДЕСЬ БОЛЬШЕ НЕТ, И ЭТО НЕ ПРОПУСК. Она снимала
  // отменённого РЕБЁНКА — «приглашение сняли». Отменить вечер по одному
  // человеку нельзя (решение владельца 12.09), а отменённый вечер отменён
  // целиком, и состояние его сказано строкой выше. Снятие приглашения теперь
  // выражается единственным способом: человека убрали из состава.
  if (inEvent) {
    return LineupRow(
      uid: uid,
      name: name,
      kind: LineupRowKind.invited,
      answer: answer,
    );
  }
  // Человека в составе нет. Два случая, и они РАЗНЫЕ (I47):
  //   шаблон говорит «не позван» — вопроса не задавали;
  //   шаблон говорит «позван»    — задавали и сняли.
  if (!slot.invited) {
    return LineupRow(
      uid: uid,
      name: name,
      kind: LineupRowKind.notInvited,
      reason: slot.reason,
    );
  }
  return LineupRow(uid: uid, name: name, kind: LineupRowKind.withdrawn);
}
