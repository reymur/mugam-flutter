// ШАБЛОН СОСТАВА — «кого звали на этот вечер»
// ---------------------------------------------------------------------------
// Работа 7, шаг 5 (`docs/plan.md`), 09.09.
//
// ЧТО ЭТО ЗА ВЕЩЬ. Зовущий отмечает несколько человек, и на КАЖДОГО заводится
// отдельное приглашение — свой документ `personalEvents` с `parentEventId`.
// Список отмеченных при этом никуда не девается: он живёт полем `lineup` на
// РОДИТЕЛЕ и отвечает на два вопроса сразу — «кого звали» (шаблон, чтобы через
// месяц позвать той же командой) и «кому не ушло» (отметка непозванного).
//
// ПОЧЕМУ UID ПЛЮС ЗАПАСНОЕ ИМЯ, А НЕ ОДНО ИЗ ДВУХ — решение владельца 08.09,
// довод его же: **шаблон переживает людей.** Состав собирают, чтобы позвать
// той же командой через месяц, а за месяц учётка исчезает — перемер 07.09
// 22:45 UTC: в Auth 16, профилей 12, без профиля 4. Живая ссылка на
// исчезнувшего даёт пустоту, голый снимок — имя, которого больше нет; пара
// «uid + запасное имя» даёт «Naməlum», то есть правду.
//
// ТРЕБОВАНИЕ ПРИЁМКИ, А НЕ ПОЖЕЛАНИЕ: **шаблон пишется в момент сбора и не
// пересобирается при чтении.** Иначе запасное имя свежее ровно тогда, когда
// бесполезно: оно нужно в тот миг, когда uid уже не находится, а пересборка
// при чтении берёт имя из того самого списка, где человека больше нет —
// механизм работал бы всегда, кроме единственного случая, ради которого
// заведён (I9). Признак соблюдения: `name` пишется тем же ходом, что и `uid`,
// и ни один читатель его не трогает.

/// ЧЕГО ЖДАЛИ ОТ ЗАПИСИ И ЧТО С НЕЙ СТАЛО.
///
/// **[invited] — СОСТОЯНИЕ В ДАННЫХ, А НЕ ВЫВОД ИЗ «ОТВЕТА НЕТ»** (требование
/// владельца 08.09). Вывести «его не позвали» из отсутствия ответа нельзя по
/// устройству: «ответа нет» одинаково истинно и когда спросили и молчат, и
/// когда не спрашивали (I47, цена уже заплачена в N13). Через месяц эти два
/// состояния свели бы в одно — на экране они похожи, — и приложение сказало бы
/// «ждём ответа» о человеке, которому вопроса не задавали.
///
/// **Три состояния, а не два, и различимы они все:**
///
///   записи нет вовсе          — в состав не звали;
///   `invited == true`         — позван, приглашение создано;
///   `invited == false`        — хотели позвать, не ушло, и [reason] говорит
///                               почему.
///
/// **Почему явный признак, а не «есть причина — значит не позван».** Признак
/// и причина отвечают на разные вопросы, и `null` в причине у нового повода
/// (которого мы ещё не завели) прочитался бы как «позван» — то есть молчание,
/// выданное за успех (I14).
class LineupSlot {
  const LineupSlot({
    required this.uid,
    required this.name,
    required this.invited,
    this.reason,
  });

  /// Основной путь: по нему человек читается из живого списка людей.
  final String uid;

  /// ЗАПАСНОЕ ИМЯ — снимок на миг сбора, и только для случая «uid не
  /// находится». Читателю его брать, лишь когда живого имени нет; пустое
  /// значит «сведений нет», и врать вместо него чужим именем нельзя.
  final String name;

  final bool invited;

  /// Отчего не ушло. `null` у позванного.
  ///
  /// Значение — из перечня ниже, а не свободная строка: причина едет в показ,
  /// и незнакомое значение обязано быть заметно, а не превращаться в пустоту.
  final String? reason;

  Map<String, dynamic> toMap() => {
        'uid': uid,
        'name': name,
        'invited': invited,
        'reason': reason,
      };
}

/// С этим человеком уже идёт другой разговор про работу — раунд предложения на
/// документе чата открыт.
///
/// Решение владельца 08.09 по третьему вопросу работы: **не блокировать всю
/// отправку из-за одного** — иначе один чужой разговор про работу через месяц
/// запирает весь состав на пятницу. Отказ приходит на КОНКРЕТНОГО человека,
/// потому что раунд живёт на документе чата и у каждой пары он свой.
const String kNotInvitedOpenRound = 'openRound';

/// Запись не состоялась — сеть, права, отказ базы.
///
/// **Отдельно от [kNotInvitedOpenRound], а не свалено в одну «не ушло».** Это
/// два разных незнания: первое — законный отказ, о котором человеку есть что
/// сделать («открой чат, закрой раунд»); второе — поломка, и делать с ней
/// человеку нечего, кроме как нажать ещё раз. Свести их значило бы потерять
/// возможность отличить норму от поломки (I47).
const String kNotInvitedFailed = 'failed';

/// ЧТЕНИЕ ЗАЩИТНОЕ, И ЭТО НЕ ПЕРЕСТРАХОВКА (I49).
///
/// Документ вечера пишет не только наш клиент: наш сервер ходит мимо правил
/// Admin SDK, плюс правка руками в консоли. Жёсткое приведение здесь роняло бы
/// не поле, а весь календарь — `PersonalEvent.fromFirestore` зовётся на каждый
/// документ каждого потока.
///
/// **Запись с пустым `uid` выбрасывается целиком.** Слот без человека — не
/// «человек без имени», а мусор: по нему нечего читать и некому звонить, а в
/// показе он стал бы пустой строкой, которую примут за потерянного участника.
List<LineupSlot> lineupFromFirestore(dynamic raw) {
  if (raw is! List) return const [];
  final out = <LineupSlot>[];
  for (final item in raw) {
    if (item is! Map) continue;
    final uid = item['uid'];
    if (uid is! String || uid.isEmpty) continue;
    out.add(
      LineupSlot(
        uid: uid,
        name: item['name'] is String ? item['name'] as String : '',
        // Всё, что не `true`, читается как «не позван» — включая отсутствие
        // ключа и чужой тип. Сторона выбрана нарочно: ошибись умолчание в
        // другую сторону, и непозванный молча стал бы позванным, то есть
        // человек ждал бы ответа, которого никто не обещал.
        invited: item['invited'] == true,
        reason: item['reason'] is String ? item['reason'] as String : null,
      ),
    );
  }
  return out;
}

List<Map<String, dynamic>> lineupToFirestore(List<LineupSlot> slots) =>
    [for (final s in slots) s.toMap()];
