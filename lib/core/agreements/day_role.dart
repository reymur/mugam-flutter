/// ЧЕМ ЭТОТ ВЕЧЕР ЯВЛЯЕТСЯ ДЛЯ ЭТОГО ЧЕЛОВЕКА — одно правило на весь проект.
///
/// Заведено 12.08 работой «показ приглашений в календаре» (`docs/plan.md`)
/// после **N126**: сетка месяца помечала день занятым и на приглашении, и на
/// отказе, потому что не смотрела на ответ вовсе.
///
/// --- ПОЧЕМУ ТРИ ЗНАЧЕНИЯ, А НЕ ДВА ---
///
/// Прежнее правило `occupiesCalendarOf` отвечало **да/нет**, и этого хватало
/// ровно одному вызывающему — разбору конфликтов, где вопрос и правда
/// двоичный: мешает или не мешает. **Показу этого мало.** У показа три
/// разных случая, и сведение их к двум и есть N126:
///
///   занят      — я иду (или это мой вечер): день мой, он занят;
///   приглашён  — меня спрашивают: день НЕ занят, но и не пуст;
///   свободен   — я отказался, вышел, или меня ещё не позвали.
///
/// **Свести «приглашён» с «занят» значит соврать про чужое решение** (день
/// заблокирован без согласия человека). **Свести «приглашён» со «свободен»
/// значит потерять вопрос**, на который человек не ответил. Это I47: два
/// разных состояния, сведённые к одному ответу, лишают возможности отличить
/// одно от другого — и здесь разница видна на экране, а не только в разборе.
///
/// --- ГРАНИЦА: ЭТО ПРАВИЛО НЕ ЗНАЕТ ПРО ЦВЕТ ---
///
/// Оно отвечает, ЧЕМ вечер является человеку, и молчит о том, как это
/// нарисовать. Золотая точка, заливка, рамка — решение показа
/// (`month_marks.dart` и `_buildDayCell`), и держать его здесь значило бы
/// завести второе место, где решается вид.
library;

import '../../firebase/models.dart';
import 'event_answers.dart';

/// Чем вечер является человеку.
enum DayRole {
  /// День занят: я иду, либо это мой вечер.
  occupied,

  /// Меня спрашивают, я не ответил. **День при этом НЕ занят.**
  invited,

  /// Я ответил «Bacarmıram». **День свободен, но след остаётся** — решение
  /// автора 12.08, по виду на трубке.
  ///
  /// **Зачем отдельно от [free], если день в обоих случаях свободен.**
  /// Свободен — это про занятость, а тут вопрос второй: **был ли здесь
  /// вопрос ко мне.** У отказа был, и человек его разобрал; у пустого дня
  /// не было вовсе. Слить их значит стереть разницу между «я это видел и
  /// отказался» и «здесь никогда ничего не было» — а она человеку нужна: по
  /// ней он вспоминает, что уже отвечал, и не ищет пропавшее приглашение.
  declined,

  /// Ни то ни другое: вышел из состава, не позвали, либо не в составе.
  ///
  /// **`left` лежит здесь, а не в [declined], и это решение.** Вышедший не
  /// «отказался от приглашения» — он ушёл из дела, где уже был; следа
  /// приглашения у него не остаётся, потому что приглашение он когда-то
  /// принял. Сегодня недостижимо (писать `left` некому, N121), но правило
  /// пишется сейчас, и умолчание читалось бы как решение.
  free,
}

/// Правило. **Порядок ветвей здесь содержателен**, и менять его нельзя не
/// подумав — каждая следующая читается только после того, как предыдущая не
/// сработала.
///
/// **1. Пустой [uid] — «занят», и менять это на «свободен» нельзя.** Пустой
/// uid означает не «свободен», а «неизвестно, кто спрашивает», то есть
/// поломку вызывающего. «Свободен» тихо очистил бы список и выключил ВСЕ
/// предупреждения о конфликтах — пустой вывод, прочитанный как хорошая
/// новость (I14). «Занято» на каждом вечере — ложная тревога, и её видно в
/// тот же миг. Перенесено из `occupiesCalendarOf` вместе с доводом.
///
/// **2. Владелец занят ВСЕГДА, до чтения ответа, и это не перестраховка.**
/// `answersForParticipants` ставит `waiting` всем новым в составе, а у
/// договоров владелец в составе есть (`onChatUpdated` кладёт обе стороны) —
/// значит без этой ветви правка состава молча освобождала бы календарь
/// владельца на его же вечере. Разбор и числа — **N112**.
///
/// **3. `notAsked` — СВОБОДЕН, а не «приглашён», и это не мелочь.**
/// «Вопрос не задан» и «задан, ответа нет» — разные вещи с разным адресатом
/// следующего хода: при `notAsked` действовать должен ВЛАДЕЛЕЦ (позвать
/// по-настоящему), при `waiting` — приглашённый (ответить). Показать
/// приглашение тому, кого не звали, значит позвать его от чужого имени.
/// Разбор — `event_answers.dart`, `kAnswerNotAsked`.
///
/// **4. `null` (человека нет в составе) — свободен.** До этой ветви дойти
/// не должно: человеку приходят только те вечера, где он есть в `musicians`.
/// Ответ дан явно, потому что «не должно» — не то же самое, что «не может»,
/// а умолчание здесь читалось бы как решение.
///
/// **5. Старые документы без карты ответов дают `going` и потому «занят» —
/// это ВЕРНО, а не дырка.** До разделения смыслов «есть в `musicians`» и
/// означало «идёт», поэтому запасной путь `answerOf` — честный перевод
/// старого смысла. Перепись 12.08: **72 человека в 38 документах из 78**
/// читаются так, из них будущих документов **3**. Множество замкнуто и
/// расти не будет: mugam-v2 мёртв, других писателей мимо нас нет.
/// СКОЛЬКО НА ЭТОТ ДЕНЬ ПРИГЛАШЕНИЙ, КОТОРЫХ ЧЕЛОВЕК ЕЩЁ НЕ СМОТРЕЛ.
///
/// Заведено 12.08 решением автора: точку на клетке заменяет число. Три
/// приглашения — золотая «3»; открыл одно — «2»; открыл все — числа нет.
///
/// **`seenEventIds` — то, чего нельзя вывести из документа.** Ответ лежит в
/// самом мероприятии, а «я это видел» не лежит нигде: этот факт про ЧЕЛОВЕКА,
/// и приходит он снаружи — из `users/{uid}/seenInvitations`. Поэтому правило
/// принимает его параметром, а не читает само: чистая функция не должна
/// ходить в базу, иначе её нечем проверить.
///
/// **СЧИТАЮТСЯ ТОЛЬКО НЕОТВЕЧЕННЫЕ (`invited`).** Отвеченное приглашение из
/// счёта выбывает независимо от того, смотрел ли человек его формально:
/// ответить, не увидев, нельзя.
int unseenInvitationsOn(
  List<PersonalEvent> dayEvents,
  String uid,
  Set<String> seenEventIds,
) {
  var n = 0;
  for (final e in dayEvents) {
    if (dayRoleOf(e, uid) != DayRole.invited) continue;
    if (seenEventIds.contains(e.id)) continue;
    n++;
  }
  return n;
}

/// ОСТАЛСЯ ЛИ НА ДНЕ СЛЕД РАЗОБРАННОГО ВОПРОСА — серая точка.
///
/// Отдельной функцией от [unseenInvitationsOn], а не полем в общем ответе:
/// это **другой вопрос**. Первая отвечает «сколько ждёт меня», вторая —
/// «было ли здесь вообще что-то ко мне». Слить их в одну структуру значило бы
/// заставить читателя разбирать, какая половина ему нужна.
///
/// След оставляют два случая, и оба означают «я это разобрал»:
/// приглашение **просмотренное**, но пока без ответа, и приглашение
/// **отклонённое**.
bool hasHandledInvitationOn(
  List<PersonalEvent> dayEvents,
  String uid,
  Set<String> seenEventIds,
) {
  for (final e in dayEvents) {
    switch (dayRoleOf(e, uid)) {
      case DayRole.declined:
        return true;
      case DayRole.invited:
        if (seenEventIds.contains(e.id)) return true;
      case DayRole.occupied:
      case DayRole.free:
        break;
    }
  }
  return false;
}

/// ПОКАЗЫВАТЬ ЛИ ЭТОТ ВЕЧЕР СТРОКОЙ ПРИГЛАШЕНИЯ, а не карточкой вечера.
///
/// Заведено 12.08 после прогона на трубке: строка «Rafael səni çağırır»
/// пропадала сразу после ответа «Bacarmıram», и день показывался обычной
/// карточкой. **Это не поломка от `declined`, это было неверно с самого
/// начала:** условие спрашивало ровно `invited`, а любой ответ выводит вечер
/// из этого состояния — сперва в `free`, теперь в `declined`.
///
/// **ПРАВИЛО: приглашение остаётся приглашением и ПОСЛЕ ответа «нет».**
/// Отказ не превращает чужой зов в моё дело — он на него отвечает. Карточка
/// вечера говорит «вот что у меня в этот день», а у отказавшегося в этот день
/// НИЧЕГО нет: показать карточку значит записать ему чужую работу.
///
/// **Согласие — превращает.** Сказав «Gəlirəm», человек делает вечер своим,
/// и с этой минуты ему нужна карточка, а не строка: он туда идёт.
///
/// **Зачем отдельной функцией, а не условием внутри экрана.** Решение «что
/// показать» жило в виджете и потому не проверялось ничем — тот самый класс,
/// что I32 и N125. Здесь оно проверяемо, и на него есть тест.
bool showsAsInvitation(PersonalEvent e, String uid) {
  final role = dayRoleOf(e, uid);
  return role == DayRole.invited || role == DayRole.declined;
}

DayRole dayRoleOf(PersonalEvent e, String uid) {
  if (uid.isEmpty) return DayRole.occupied;
  if (e.ownerUid == uid) return DayRole.occupied;
  final answer = e.answerFor(uid);
  if (answer == kAnswerGoing) return DayRole.occupied;
  if (answer == kAnswerWaiting) return DayRole.invited;
  if (answer == kAnswerCant) return DayRole.declined;
  return DayRole.free;
}
