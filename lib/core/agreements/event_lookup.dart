/// Найти мероприятие по id среди своих и тех, где я участник.
///
/// **Почему два списка, а не один.** У договора две стороны, и документ у
/// них один: у владельца он приходит потоком «мои», у второй стороны —
/// потоком «где я участник». Искать в одном значило бы не находить свой же
/// договор у половины людей. Тот же союз с дедупом по id собирает список
/// договоров на экране (`agreementEventsById`).
///
/// Порядок важен и назван: сперва свои. Один и тот же документ в обоих
/// списках оказаться не может, но если окажется — своя запись главнее,
/// потому что по ней считаются права на правку.
PersonalEvent? findEventById(
  String id,
  List<PersonalEvent> own,
  List<PersonalEvent> asParticipant,
) {
  for (final e in own) {
    if (e.id == id) return e;
  }
  for (final e in asParticipant) {
    if (e.id == id) return e;
  }
  return null;
}

/// Какую карточку показывать для этого документа.
enum EventCardKind { agreement, personalEvent }

/// Договор это или личное мероприятие.
///
/// **Признак — `isAgree`, и он не выбран заново, а взят оттуда, где уже
/// работает:** ровно им отбирается список договоров
/// (`agreements_screen.dart`, `_agreeEvents`). Вкладка «Tədbirlər» этого
/// поля не смотрит вовсе, поэтому один документ законно виден в обоих
/// списках — и вопрос «какую карточку открыть» решается не тем, откуда
/// пришли, а тем, чем документ является.
///
/// **Вынесено в отдельную функцию ДО появления третьего читателя** (I23):
/// сегодня по этому полю судят два списка, а с публичным входом по id
/// будет судить и он. Три места, решающих одно по-своему, расходятся
/// молча — это N74 и N76 дословно.
EventCardKind eventCardKindOf(PersonalEvent event) =>
    event.isAgree ? EventCardKind.agreement : EventCardKind.personalEvent;
