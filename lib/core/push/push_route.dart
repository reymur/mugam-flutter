// --- ГРАНИЦЫ (I50) ---
//
//   • `incoming_call` сюда не попадает и не должен: его разбирает отдельный
//     фоновый обработчик (`main.dart`, `_firebaseMessagingBackgroundHandler`)
//     и отдаёт CallKit ещё до того, как человек чего-либо коснётся;
//   • правило не проверяет, ЖИВ ли документ, в который ведёт. Удалённый
//     вечер — забота двери `eventDetailRoute`, у неё для этого три состояния;
//   • правило не решает, ПОКАЗЫВАТЬ ли уведомление. Это сервер.

/// Куда вести по нажатию. `null` — вести некуда.
///
/// **`null` И «В ОБЩИЙ СПИСОК» — РАЗНОЕ (I47), и сводить их нельзя.** Первое
/// значит «типа не знаем либо в данных нет нужного ключа» — то есть молчание
/// от незнания. Второе — сказанный ответ: у двух типов карточку по правилам
/// уже не прочитать, и список это верное место, а не запасное.
///
/// Свести их к «/agreements по умолчанию» — ровно тот дефект, что чинится
/// этим файлом: незнакомый тип уводил бы человека на экран, к его
/// уведомлению отношения не имеющий, и выглядело бы это как «приложение
/// открылось не туда», а не как «мы такого не умеем».
String? pushRouteFor(Map<String, dynamic> data) {
  final type = data['type'];
  if (type is! String || type.isEmpty) return null;

  if (_chatBound.contains(type)) {
    final chatId = data['chatId'];
    return chatId is String && chatId.isNotEmpty ? '/chat/$chatId' : null;
  }

  if (_eventBound.contains(type)) {
    final eventId = data['eventId'];
    return eventId is String && eventId.isNotEmpty ? '/event/$eventId' : null;
  }

  if (_eventListBound.contains(type)) return '/agreements';

  return null;
}

