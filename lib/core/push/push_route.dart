//      клиент ждал `job_offer_waiting_date`, БЕЗ `for`. Опечатка в имени, и
//      уведомление «ждёт от вас даты» не открывало чат ни разу;
//   2. **девять событийных типов вели в общий список** вместо самого вечера:
//      `eventId` сервер клал (`openEvent`), клиент его не читал вовсе
