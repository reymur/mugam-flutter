/// **«Не может» НЕ КРАСНОЕ, а приглушённо-кирпичное (`#8A4A3A`/`#B08070`).**
/// Красный на этих экранах означает ОТМЕНУ (N110), и покрась им отказ
/// участника — человек прочтёт «вечер отменён» вместо «один не придёт».
/// Разница в цвете здесь несёт весь смысл, и потому взята из макета, а не
/// подобрана.
/// **«ЖДЁМ ОТВЕТА» СТАЛО ЯНТАРНЫМ — решение владельца 28.08, макет проиграл
/// трубке во второй раз.**
///
/// Здесь стояло `#BFB093` — тот же цвет, что у обычного второстепенного
/// текста, и на устройстве строка «cavab gözlənilir» ничем не отличалась от
/// подписи. У двух соседних состояний цвет говорит сам: «идёт» зелёное,
/// «не может» кирпичное. У третьего цвета не было вовсе, и ожидание —
/// единственное из трёх, где **ход за человеком**, — читалось тише всех.
///
/// **Янтарный, а не `kGold`:** золото в этом приложении означает «нажми меня»
/// (кнопки, имена, ободок выбранного). Слово под именем не нажимается, и
/// покрась его золотом — оно обещало бы действие, которого нет (N174: у
/// нажимаемого две половины, адресат и вид, — и обратная сторона того же
/// правила: ненажимаемое не должно выглядеть кнопкой).
///
/// Пара «обводка темнее, слово светлее» взята у двух соседей, а не изобретена.
const Color kAnswerWaitBorder = Color(0xFF8A6A2A);
