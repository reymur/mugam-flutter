import 'dart:async';

/// Один источник — много подписчиков, с повтором последнего значения.
///
/// Появился ради B17: на `chats/{chatId}` висело три отдельных
/// `.snapshots()` (мета, печатает, отсечка очистки), а Firestore
/// тарифицирует чтение документа на каждого слушателя — то есть каждая
/// запись в самый горячий документ приложения оплачивалась трижды.
/// Проекции при этом обязаны остаться раздельными потоками (складывать
/// их в один было замерено как вредное: запись «печатает» раз в ~3 с
/// перестраивала весь экран чата), но раздельных потоков никогда не
/// требовало раздельных СЛУШАТЕЛЕЙ.
///
/// Три свойства, ради которых это отдельный класс, а не пара строк с
/// `asBroadcastStream()`:
///
/// 1. **Повтор последнего значения.** Подписчики приходят в разные
///    моменты (мета — при построении экрана, отсечка — при старте
///    контроллера сообщений), и опоздавший без повтора ждал бы
///    следующей записи, то есть, возможно, минуты. `asBroadcastStream()`
///    так не умеет.
/// 2. **Отсутствие щели.** Повтор идёт синхронно и в том же обороте
///    цикла событий, что и подключение к живому потоку, поэтому между
///    ними не может проскочить значение.
/// 3. **Ничего не остаётся после последнего подписчика.** Источник
///    отключается, запомненное значение стирается. Иначе следующий
///    подписчик получил бы его как актуальное — в том числе после
///    смены аккаунта на устройстве.
class SharedStream<T> {
  SharedStream(this._source, {this.onIdle});

  /// Фабрика, а не готовый поток: после ухода последнего подписчика
  /// подписка закрывается, и следующему нужен новый живой поток.
  final Stream<T> Function() _source;

  /// Зовётся, когда ушёл последний подписчик или источник завершился —
  /// владелец обычно убирает этот объект из своего кэша.
  final void Function()? onIdle;

  final List<MultiStreamController<T>> _subscribers = [];
  StreamSubscription<T>? _sub;
  T? _last;
  bool _hasLast = false;

  /// Сколько сейчас подписчиков. Только для тестов и диагностики.
  int get subscriberCount => _subscribers.length;

  /// Активна ли подписка на источник. Только для тестов и диагностики.
  bool get isConnected => _sub != null;

  late final Stream<T> stream = Stream.multi((controller) {
    _subscribers.add(controller);

    if (_hasLast) controller.addSync(_last as T);

    _sub ??= _source().listen(
      (value) {
        _last = value;
        _hasLast = true;
        for (final subscriber in List.of(_subscribers)) {
          subscriber.addSync(value);
        }
      },
      onError: (Object e, StackTrace st) {
        for (final subscriber in List.of(_subscribers)) {
          subscriber.addErrorSync(e, st);
        }
      },
      onDone: () {
        // Источник закончился — закрываем всех и забываем состояние.
        // Список копируется, потому что close() приводит к onCancel,
        // который правит тот же список.
        for (final subscriber in List.of(_subscribers)) {
          subscriber.close();
        }
        _reset();
      },
    );

    controller.onCancel = () {
      _subscribers.remove(controller);
      if (_subscribers.isEmpty) _reset();
    };
  });

  void _reset() {
    // Сюда приходят двумя путями, и они пересекаются: завершение
    // источника закрывает подписчиков, а закрытие последнего подписчика
    // само по себе означает сброс. Без этой проверки onIdle звался бы
    // дважды за одно завершение — владелец, который на нём что-то
    // считает или чистит, получил бы лишний вызов.
    if (_sub == null && _subscribers.isEmpty && !_hasLast) return;
    _sub?.cancel();
    _sub = null;
    _last = null;
    _hasLast = false;
    onIdle?.call();
  }
}
