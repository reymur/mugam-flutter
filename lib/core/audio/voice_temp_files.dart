import 'dart:io';

// ВРЕМЕННЫЕ ФАЙЛЫ ЗАПИСЕЙ — И ИХ УБОРКА.
//
// Голосовое в листе предложения пишется во временный файл и грузится только
// при «Göndər». Закрыл лист не отправив — файл обязан пропасть.
//
// **ПОЧЕМУ ЭТО ВЫНЕСЕНО В ОТДЕЛЬНУЮ ФУНКЦИЮ, А НЕ ОСТАЛОСЬ ЦИКЛОМ ВНУТРИ
// ЛИСТА.** Пока уборка стояла строчками в обработчике, проверить её было
// нечем: она не возвращала ничего, и «файл удалён» отличалось от «файла и
// не было» ровно ничем. Мусор, который никто не подберёт, копится молча —
// и замечают его не по ошибке, а по кончившемуся месту на телефоне.
//
// Функция возвращает ЧИСЛО удалённого. Это и делает уборку проверяемой:
// у неё есть ответ, который можно сличить с ожидаемым (I13 — сторож,
// который считает, обязан показать своё число).

/// Удаляет временные записи. Возвращает, сколько файлов НА САМОМ ДЕЛЕ
/// удалено.
///
/// Отсутствие файла не считается сбоем: система могла убрать его сама, а
/// один и тот же файл после копирования деталей принадлежит нескольким
/// дням — второй заход по нему законно не найдёт ничего.
int deleteVoiceTempFiles(Iterable<String> paths) {
  var removed = 0;
  for (final p in paths) {
    try {
      final f = File(p);
      if (f.existsSync()) {
        f.deleteSync();
        removed += 1;
      }
    } catch (_) {
      // Занятый файл или отказ в доступе — уборка не обязана падать: она
      // сопровождает закрытие экрана, и человек не должен видеть ошибку
      // из-за не удалённого временного файла.
    }
  }
  return removed;
}
