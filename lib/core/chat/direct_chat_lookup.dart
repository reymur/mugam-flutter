/// Личный чат с этим человеком в УЖЕ ЗАГРУЖЕННОМ списке чатов.
///
/// Правило существовало в одном месте — кнопка «Mesaj» в карточке
/// человека — и было записано там прямо в теле обработчика. С пунктом 6
/// его читателей становится двое: та же кнопка и общая точка вызова
/// предложения работы, которой чат нужен, чтобы вообще было куда писать.
///
/// **Зачем вообще смотреть в загруженный список, а не звать
/// `getOrCreateDirectChat` сразу.** Тот делает несколько
/// последовательных обращений к Firestore и на паре со старыми чатами
/// заметно думает — это измерено и записано в его собственном
/// комментарии. Список же вкладки «Mesaj» держится тёплым и применяет тот
/// же отбор «самый свежий на собеседника», что и сам экран списка.
/// Значит попадание в кэш обязано давать РОВНО ТУ ЖЕ ветку, которую
/// показал бы список, — иначе предложение уедет в один чат, а переписка
/// про него пойдёт в другом.
///
/// Возвращает `null`, когда подходящего чата в списке нет: это НЕ «чата не
/// существует», а «в этом списке его нет». Ответ на вопрос
/// существования знает только `getOrCreateDirectChat`, и путать эти два
/// ответа нельзя — на разнице между «нет в кэше» и «нет вовсе» уже
/// однажды строился ложный вывод (B27).
Chat? directChatIn(List<Chat> chats, String otherUid) {
  for (final c in chats) {
    if (!c.isGroup && c.members.contains(otherUid)) return c;
  }
  return null;
}
