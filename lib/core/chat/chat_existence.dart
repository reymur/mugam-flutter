/// Существует ли документ чата — ТРИ состояния, а не два.
///
/// Заведено по N34: `watchChatMeta` сводил отсутствующий документ к
/// `{}` и отдавал его как обычный чат с пустыми полями. Отличить «чата
/// больше нет» от «чат есть, участников нет» было нечем ни одному
/// потребителю — второе вхождение класса N13, «не знаю», выданное за
/// ответ.
///
/// **Почему именно три, а не `bool`.** Поток поднят с
/// `includeMetadataChanges`, и до ответа сервера снимок штатно приходит
/// пустым: `snap.exists == false` там значит «ещё не знаю», а вовсе не
/// «удалён». `bool` слил бы эти два состояния — и проверка членства,
/// написанная поверх него, вышвыривала бы человека из ЛЮБОГО чата на
/// входе. Ровно этим N33 и была опасна, пока N34 не закрыта.
///
/// **Почему не `bool?`.** Читается как `if (!exists)`, и `null` молча
/// уходит в ветку «нет». Тип обязан заставлять называть случай вслух —
/// иначе он повторит ту самую ошибку, ради которой заведён.
enum ChatExistence {
  /// Сервер подтвердил: документ есть.
  present,

  /// Сервер подтвердил: документа нет. Единственное состояние, на котором
  /// можно говорить человеку «чат удалён» и уводить его с экрана.
  absent,

  /// Ответа сервера ещё не было. НЕ «нет» — на этом состоянии нельзя ни
  /// уводить с экрана, ни решать, что человека исключили.
  unknown,
}

/// Правило целиком, отдельно от Firestore — чтобы проверялось тестом.
///
/// [exists] — `snap.exists`, [isFromCache] — `snap.metadata.isFromCache`.
///
/// Пустой снимок ИЗ КЭША не значит ничего: документ мог быть не загружен.
/// Пустой снимок ОТ СЕРВЕРА — значит документа нет. Существующий документ
/// существует независимо от того, откуда пришёл: кэш не выдумывает
/// записей, которых не было.
ChatExistence chatExistenceOf({
  required bool exists,
  required bool isFromCache,
}) {
  if (exists) return ChatExistence.present;
  return isFromCache ? ChatExistence.unknown : ChatExistence.absent;
}
