import 'chat_existence.dart';

/// Что открытый экран чата должен сделать с тем, кто в него смотрит.
///
/// N33: проверки «я ещё участник» в `chat_screen.dart` не было НИ ОДНОЙ.
/// Список чатов при этом верен всегда — он перестраивается запросом
/// `where('members', arrayContains: uid)`, — а открытый экран живёт тем,
/// что успел загрузить. Собственные действия он переживает нормально:
/// после них человек сам куда-то уходит навигацией. Не замечает он ровно
/// то, что сделал КТО-ТО ДРУГОЙ, — и потому одной трубкой невидим.
enum ChatAccess {
  /// Всё в порядке: чат есть, человек в нём участник.
  ok,

  /// Ничего не решено. Отдельное состояние, а не «всё в порядке»: пока
  /// сервер не ответил, уводить с экрана не на чем.
  unknown,

  /// Чата больше нет — его удалили целиком.
  chatDeleted,

  /// Чат есть, но человека в нём больше нет: его удалили из группы.
  removedFromChat,
}

/// Правило целиком. Отдельно от экрана — потому что проверить его внутри
/// `build()` нечем, а цена ошибки здесь высокая в ОБЕ стороны: не
/// среагируешь — человек сидит в чате, которого лишился; среагируешь
/// слишком рано — вышвырнешь из чата, в котором он состоит.
///
/// [existence] — ответ N34, [fromCache] — пришёл ли снимок из кэша,
/// [members] — участники (`null`, если проекция ещё не пришла).
///
/// **Почему выброс требует ответа СЕРВЕРА, а не просто наличия данных.**
/// Кэш может отдать состав, устаревший на сессию: человека добавили в
/// группу, а в кэше документ с прежним составом. Решение об исключении,
/// принятое по такому снимку, — ложное, и выглядит оно для человека ровно
/// как настоящее. Ждать сервера ничего не стоит: чужое удаление приходит
/// ИМЕННО от сервера, то есть в том единственном случае, ради которого
/// правило и написано, задержки нет вовсе.
ChatAccess resolveChatAccess({
  required ChatExistence existence,
  required bool fromCache,
  required List<String>? members,
  required String currentUid,
}) {
  switch (existence) {
    case ChatExistence.unknown:
      return ChatAccess.unknown;
    case ChatExistence.absent:
      // Единственное состояние, на котором «чат удалён» — правда: сервер
      // сказал это прямо (N34).
      return ChatAccess.chatDeleted;
    case ChatExistence.present:
      break;
  }
  // Проекция ещё не пришла — не знаем состава, не знаем и ответа.
  if (members == null) return ChatAccess.unknown;
  // Данные из кэша: решать по ним об исключении нельзя, см. выше.
  if (fromCache) return ChatAccess.ok;
  return members.contains(currentUid)
      ? ChatAccess.ok
      : ChatAccess.removedFromChat;
}
