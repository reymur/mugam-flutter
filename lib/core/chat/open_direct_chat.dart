// ОБЩИЙ ВХОД «ОТКРЫТЬ ЧАТ С ЧЕЛОВЕКОМ»
// ---------------------------------------------------------------------------
// Дорога в чат состоит из двух разных вопросов, и здесь они РАЗДЕЛЕНЫ на две
// функции, потому что читатели у них разные:
//
//   [resolveDirectChatId] — «какой чат с этим человеком»; нужен и тому, кто
//     чат ОТКРЫВАЕТ, и тому, кому чат нужен как место, куда что-то записать
//     (предложение работы);
//   [openDirectChat]      — «увести человека в этот чат»; нужен только первым.
//
// Слить их в одну значило бы заставить второго читателя тащить за собой показ
// и переход, которых он не делает.
//
// **ЧИСЛО, РАДИ КОТОРОГО ВЫНОС И ЗАТЕВАЛСЯ (замер 12.08, команда ниже).**
// Конспект говорил «дорога написана ДВАЖДЫ»; на деле `getOrCreateDirectChat`
// зовут из **четырёх** мест, плюс пятым файлом лежит общий отбор
// `direct_chat_lookup.dart`, которого в конспекте нет вовсе:
//
//     grep -rn "\.getOrCreateDirectChat(" lib
//
// Пока считали два, копия казалась мелочью — «ну два похожих обработчика».
// При четырёх это уже не копия, а расходящийся обычай: из четырёх мест
// **три** идут «кэш → запасной путь», и **одно из этих трёх** (`chats_screen`)
// держит отбор своим циклом вместо общего `directChatIn`; четвёртое
// (`status_viewer`) кэш не смотрит вовсе.
//
// **СТАРЫЕ ЧЕТЫРЕ МЕСТА СЮДА НЕ ПЕРЕВЕДЕНЫ — это отдельная работа**
// (`docs/plan.md`). Они работают, и перевод рабочего кода в один заход с
// заведением нового входа означал бы шаг с несколькими переменными сразу
// (I48): сломайся что-нибудь — непонятно, сломал это новый вход или перевод.

/// Какой личный чат с этим человеком — сперва в загруженном списке, потом у
/// самого Firestore.
///
/// **Порядок именно такой, и он не про скорость, а про СОГЛАСИЕ С ЭКРАНОМ.**
/// `getOrCreateDirectChat` делает несколько обращений подряд и на паре со
/// старыми чатами заметно думает (замер записан в его собственном
/// комментарии), но главное не это: список вкладки «Çat» применяет отбор
/// «самый свежий на собеседника», и попадание в кэш обязано давать РОВНО ТУ
/// ЖЕ ветку, которую показал бы список. Отбор поэтому берётся у
/// [directChatIn], а не пишется здесь заново (I23).
///
/// **Запасной путь обязателен и не является редкостью:** первое в жизни
/// сообщение этому человеку — это чат, которого в списке нет, потому что его
/// нет вовсе. Пустой ответ кэша означает «в этом списке его нет», а не «его не
/// существует», и путать эти два ответа нельзя (B27).
/// МОЖНО ЛИ ВООБЩЕ ОТКРЫВАТЬ ЭТОТ ЧАТ — правило отдельно от вызова, чтобы его
/// можно было прогнать тестом.
///
/// **Отвечает `false` на чат с самим собой и на пустые uid.** Пустой uid не
/// человек, а `myUid == otherUid` — это N120 в общем месте: действие,
/// рассчитанное на другого, наведённое на себя. `getOrCreateDirectChat` такой
/// запрос не отвергнет — он **создаст документ**, где обе стороны один и тот же
/// человек, и этот чат потом будет жить в списке наравне с настоящими.
///
/// **Утверждение здесь — о наличии** («открывать можно»), поэтому оно само себе
/// канарейка (I31): ослепни правило, и открывать станет нельзя ни с кем, что
/// видно в первую же минуту.
bool canOpenDirectChat({required String myUid, required String otherUid}) =>
    myUid.isNotEmpty && otherUid.isNotEmpty && myUid != otherUid;

Future<String> resolveDirectChatId(
  WidgetRef ref, {
  required String myUid,
  required String otherUid,
}) async {
  // Не мягкий возврат, а падение: сюда приходят с уже принятым решением
  // открыть чат, и «чат с самим собой» означает, что решение приняли неверно
  // ВЫШЕ. Тихо вернуть чужой id значило бы спрятать ошибку вызывающего в
  // данные — ровно то, что делает `getOrCreateDirectChat`, создавая документ.
  if (!canOpenDirectChat(myUid: myUid, otherUid: otherUid)) {
    throw ArgumentError(
      'resolveDirectChatId: чат с самим собой либо пустой uid '
      '(myUid=$myUid, otherUid=$otherUid)',
    );
  }
  final cached = ref.read(chatsProvider(myUid)).asData?.value;
  final match = cached == null ? null : directChatIn(cached, otherUid);
  if (match != null) return match.id;
  return ref
      .read(firestoreServiceProvider)
      .getOrCreateDirectChat(myUid: myUid, otherUid: otherUid);
}

/// Открыть чат с человеком: найти или завести и перейти на экран чата.
///
/// Возвращает `true`, когда переход состоялся.
///
/// **ОТКАЗ ЗДЕСЬ ГОВОРИТСЯ ВСЛУХ, И ЭТО НАМЕРЕННОЕ ОТЛИЧИЕ ОТ ДВУХ СТАРЫХ
/// МЕСТ.** `chats_screen` и `user_profile_screen` оборачивают тот же вызов в
/// `try/finally` **без `catch`**: снимают признак занятости и отпускают
/// исключение дальше. Там это сходит с рук — обе кнопки нажимает человек,
/// который и так смотрит на список чатов, и повторное нажатие ему очевидно.
///
/// Отсюда же вызов приходит из карточки вечера, где чат — не цель, а средство:
/// человек нажал «Dəqiqləşdir», чтобы спросить ушедшего. Молчаливый отказ на
/// таком ходу читается как «ничего не произошло, нажму ещё раз», и человек
/// остаётся в уверенности, что спросил (тот же довод, что у заглушек «скоро»).
///
/// [failureText] — на языке экрана: слова принадлежат месту вызова, а не
/// этому файлу, потому что для «открыть переписку» и для «спросить ушедшего»
/// честная жалоба разная.
Future<bool> openDirectChat(
  BuildContext context,
  WidgetRef ref, {
  required String myUid,
  required String otherUid,
  String failureText = 'Çat açılmadı',
}) async {
  // ЧАТ С САМИМ СОБОЙ — СЕТЬ, А НЕ СООБЩЕНИЕ, и разница намеренная.
  //
  // Жалобы человеку здесь НЕТ, и это не оплошность: сюда можно попасть только
  // ошибкой вызывающего — кнопка, которой не должно было быть. Сказать
  // «не удалось открыть» значило бы соврать про попытку, которой не было, а
  // сказать «нельзя писать себе» — объяснять человеку наш дефект его словами.
  // **Честное место починки — у вызывающего**; здесь стоит сеть, чтобы
  // следующий вызывающий не завёл ту же дырку молча, и она кричит туда, где
  // её прочтут разработчики.
  //
  // Пример такого вызывающего назывался здесь по имени — `offersLeftMemberMenu`,
  // правило кнопки «?» у вышедшего, которое «не даёт кнопку на себе». Кнопки
  // «?» больше нет: 29.08 на её месте встал крестик удаления, и правило
  // переименовано в `offersLeftMemberRemoval` (N179, N121 шаг 2). Условие «не
  // на самом себе» в нём цело — оно и было единственной дыркой из десяти
  // проверенных мест 12.08, — но чат оно больше не открывает, поэтому имя
  // снято отсюда, а не поправлено: пример, который перестал быть примером,
  // хуже отсутствующего.
  if (!canOpenDirectChat(myUid: myUid, otherUid: otherUid)) {
    assert(false, 'openDirectChat: чат с самим собой ($myUid)');
    FirebaseCrashlytics.instance.recordError(
      ArgumentError('openDirectChat: чат с самим собой либо пустой uid'),
      StackTrace.current,
      reason: 'openDirectChat: вызывающий предложил ход, которого быть не должно',
    );
    return false;
  }
  // Захвачено ДО `await`: после него собственный `context` уже небезопасно
  // спрашивать о новых зависимостях — тот же приём, что у отправки ответа на
  // статус.
  final messenger = ScaffoldMessenger.of(context);
  try {
    final chatId = await resolveDirectChatId(
      ref,
      myUid: myUid,
      otherUid: otherUid,
    );
    if (!context.mounted) return false;
    context.push('/chat/$chatId');
    return true;
  } catch (e, st) {
    FirebaseCrashlytics.instance.recordError(
      e,
      st,
      reason: 'openDirectChat: не удалось найти или создать личный чат',
    );
    messenger.showSnackBar(SnackBar(content: Text(failureText)));
    return false;
  }
}
