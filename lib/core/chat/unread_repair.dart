/// ПОЧИНКА ЗАЛИПШЕГО СЧЁТЧИКА НЕПРОЧИТАННЫХ — РЕШЕНИЕ И ЗАСЛОНКА, ОТДЕЛЬНО
/// ОТ ЭКРАНА И ОТ БАЗЫ.
///
/// --- ЧТО ЗАЛИПАЕТ ---
///
/// `chats/{chatId}.unreadCount.{uid}` пишут ДВОЕ, и пишут несовместимо:
/// сервер прибавляет (`functions/src/index.ts`, `onNewMessage` —
/// `FieldValue.increment(1)` каждому, кроме отправителя, **включая того, у
/// кого чат открыт**: это записано там намеренно, `activeUsers` значит
/// «экран открыт», а не «прочитал»), а читатель пишет абсолютный ноль.
/// Прибавка, пришедшая ПОСЛЕ обнуления, побеждает — и на прочитанном чате
/// остаётся число.
///
/// Сама гонка этой починкой НЕ лечится, и это сказано прямо: лечение гонки —
/// один писатель у счётчика, оно трогает правила и сервер и заведено
/// отдельной находкой (N247). Здесь чинится последствие.
///
/// --- ПОЧЕМУ ЭТО НЕ ПОВТОР ПО ЧАСАМ ---
///
/// До 18.09 починка жила внутри `build` экрана чата и держалась на пустой
/// перерисовке раз в двадцать секунд. Часы были нужны не ей, а **отсутствию у
/// записи признака неудачи**: `resetUnreadCount` ловил ошибку и молчал, а
/// заслонка ставилась ДО записи и при отказе не снималась. То есть повторить
/// было нечем, кроме будильника.
///
/// Теперь починку ведёт СНИМОК: прибавка сервера меняет документ, документ
/// выдаёт снимок, снимок и есть повод попробовать. Сходимость: после записи
/// счётчик ноль, условие ложно, повтора нет. **Отказ не оставляет следа** —
/// заслонка снимается в `finally`, и следующий же снимок пробует снова.
///
/// Образец не выдуман: ровно так устроен `_recordDeliveries` в
/// `firestore_service.dart` (пометка `deliveredSeq.{uid}` против
/// `lastMessageSeq`, откат пометки в обработчике ошибки со словами «иначе одна
/// неудачная запись навсегда закрыла бы этот чат от повторной попытки в этой
/// сессии»). Здесь то же правило в более дешёвой форме: заслонка не «докуда
/// записано», а «запись в полёте», и снимать её отдельной рукой не нужно.
///
/// --- ЧЕГО ЗДЕСЬ НЕТ НАРОЧНО ---
///
/// Нет расписания и нет счёта попыток. Если запись отказала, а в чате больше
/// ничего не происходит, число на карточке останется до следующего события в
/// этом чате — и это осознанная цена, а не недосмотр: следующее же сообщение
/// снова прибавит счётчик, снова выдаст снимок и снова позовёт починку.
library;

import 'dart:async';

/// Мой счётчик непрочитанных из снимка документа чата.
///
/// **Только мой.** Поле — карта `{uid: число}` на общий документ; сложи все
/// записи, и получишь чужое непрочитанное вместе со своим.
///
/// Пустота и чужой тип дают ноль, а не отказ, и это осознанно: документ чата
/// пишут трое (наш клиент, наш сервер, правка руками в консоли), поэтому
/// жёсткое приведение здесь падало бы на чужой записи (I49). Умолчание
/// безвредно ровно потому, что ноль означает «чинить нечего» — тихая ошибка
/// в эту сторону не чинит исправное.
int myUnreadCount(Map<String, dynamic>? chatMeta, String uid) {
  if (uid.isEmpty) return 0;
  final raw = chatMeta?['unreadCount'];
  if (raw is! Map) return 0;
  final mine = raw[uid];
  return mine is num ? mine.toInt() : 0;
}

/// Чинить ли счётчик по этому снимку.
///
/// Правило целиком: экран чата открыт (значит человек читает), счётчик больше
/// нуля, и есть кому его обнулять. Больше здесь ничего нет — в частности, нет
/// сверки с идентификатором последнего прочитанного сообщения: у залипшего
/// счётчика он по определению тот же самый, и сверка глушила бы починку
/// (N22, регрессия 02.08).
bool shouldRepairUnread({required int unread, required String uid}) =>
    unread > 0 && uid.isNotEmpty;

/// Заслонка «запись уже в полёте» — одна на чат.
///
/// **Живёт в службе, а не в состоянии экрана, и это принципиально.**
/// `chatMetaProvider` объявлен `autoDispose`: при каждом входе в чат он
/// создаётся заново, и заслонка, живущая на экране, начиналась бы пустой. Тот
/// же довод записан у `_lastReadMsgIdWritten` в `firestore_service.dart`.
class UnreadRepairGate {
  final Set<String> _inFlight = <String>{};

  /// Сколько записей сейчас в полёте. Только для вердиктов.
  int get inFlightCount => _inFlight.length;

  /// Выполнить запись, если такая же не летит прямо сейчас.
  ///
  /// Возвращает `true`, если запись состоялась; `false` — если её не начинали,
  /// потому что предыдущая ещё в полёте. **Отказ самой записи не глотается**:
  /// исключение уходит вызывающему, и это единственный способ, которым он
  /// узнаёт, что чинить придётся снова.
  ///
  /// Заслонка снимается в `finally`, то есть **и после успеха, и после
  /// отказа**. Именно это заменяет откат пометки у `_recordDeliveries`:
  /// неудачная запись не оставляет следа, который закрыл бы чат от повторной
  /// попытки до конца сессии.
  Future<bool> run(String chatId, Future<void> Function() write) async {
    if (!_inFlight.add(chatId)) return false;
    try {
      await write();
      return true;
    } finally {
      _inFlight.remove(chatId);
    }
  }
}
