/// Открыт ли раунд переговоров о работе — ОДНО правило на весь проект.
///
/// Правило жило строкой внутри `build()` экрана чата и было там
/// единственным читателем, поэтому вопроса «а где ещё так же считают» не
/// возникало. С пунктом 6 читателей становится двое: экран чата рисует по
/// нему плашку и прячет пункт меню, а общая точка вызова предложения
/// (`features/job_offer/job_offer_entry.dart`) по нему же отказывает
/// входу сбоку.
///
/// **Два места, считающие одно правило по-своему, расходятся молча** — это
/// ровно N74 (сетка месяца считала свой счёт) и N76 (строка чата решала
/// сама). Оба раза находил человек, смотрящий на экран, а не проверка.
/// Поэтому правило вынесено сюда ДО появления второго читателя, а не
/// после того, как они разойдутся.
///
/// Чистая функция намеренно: её можно проверить возвратом (I17), а внутри
/// `build()` — нельзя.
bool jobOfferRoundOpen({
  required String? jobOfferBy,
  required String? roundStep,
  required bool recipientAgreed,
}) {
  // `jobOfferBy != null` — общее условие обеих веток: у открытого раунда
  // всегда есть инициатор, обе половины пишутся одной операцией.
  if (jobOfferBy == null) return false;
  // ЯВНЫЙ ШАГ, а не вывод из четырёх полей. Откат на прежний вывод
  // оставлен не «на всякий случай», а под конкретный случай: документы
  // чатов, которых не касались с прежней сборки, поля `roundStep` не
  // имеют вовсе, и для них «раунд открыт» по-прежнему означает
  // «предложение есть, согласия нет».
  if (roundStep != null) {
    return roundStep == 'proposed' || roundStep == 'dated';
  }
  return !recipientAgreed;
}

/// Возвращаться ли к выбору человека после того, как лист предложения
/// закрылся.
///
/// **Найдено на устройстве 09.08 (N91): ошибся человеком — вернуться
/// некуда.** Ход «выбери человека → заполни предложение» был собран как
/// два ПОСЛЕДОВАТЕЛЬНЫХ листа: первый закрывался насовсем, и у второго не
/// было «назад». Тап по человеку в списке оказывался необратимым — при
/// том, что обратимости тапа мы в этом же пункте и добивались.
///
/// Правило целиком: возвращаемся, если предложение НЕ отправлено И
/// человека выбирали здесь же. Пришёл со знакомым человеком (из чата, из
/// карточки) — возвращаться не к чему, там списка не было.
///
/// Вынесено отдельно, потому что проверяется возвратом (I17), а внутри
/// цикла с двумя `await` — нет. **Честная граница: проверяется РЕШЕНИЕ, а
/// не проводка.** Что цикл действительно снова покажет список, доказывает
/// только прогон на устройстве.
bool jobOfferReturnsToPicker({
  required bool sent,
  required bool personGivenByEntry,
}) =>
    !sent && !personGivenByEntry;
