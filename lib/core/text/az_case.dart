// ОКОНЧАНИЯ АЗЕРБАЙДЖАНСКИХ СЛОВ — по гармонии гласных.
//
// Заведено 19.08, когда выяснилось, что фраза «ждём ответа от такого-то»
// написана в проекте ДВАЖДЫ и по-разному: `job_offer_card.dart` лепил к
// имени `un`, `job_offer_accept_sheet.dart` — `-in`. Оба варианта неверны
// и оба неподвижны: приклеенное окончание не умеет меняться вслед за
// именем, а в азербайджанском оно обязано.

/// Гласные заднего ряда. После них идёт `-dan`.
const _back = {'a', 'ı', 'o', 'u'};

/// Гласные переднего ряда. После них идёт `-dən`.
const _front = {'e', 'ə', 'i', 'ö', 'ü'};

/// Исходный падеж — «от кого». Решает ПОСЛЕДНЯЯ гласная слова, а не первая
/// и не буква на конце.
///
///   Teymur -> Teymurdan   (последняя гласная `u`, задняя)
///   Rafael -> Rafaeldən   (последняя гласная `e`, передняя)
///
/// **В азербайджанском у этого окончания только два вида**, `-dan` и
/// `-dən`; оглушения до `-tan`, как в турецком, здесь нет — поэтому
/// согласная на конце слова ни на что не влияет и не проверяется.
///
/// Слово без гласных (набор согласных, пустая строка) получает `-dan`:
/// выбирать не из чего, а падать на имени — хуже, чем ошибиться в
/// окончании у строки, которой в жизни не бывает.
String azAblativeSuffix(String word) {
  final lower = word.toLowerCase();
  for (var i = lower.length - 1; i >= 0; i--) {
    final ch = lower[i];
    if (_front.contains(ch)) return 'dən';
    if (_back.contains(ch)) return 'dan';
  }
  return 'dan';
}

/// Имя в исходном падеже: `Teymur` -> `Teymurdan`.
String azFrom(String name) => '$name${azAblativeSuffix(name)}';

/// «Ждём ответа от такого-то».
///
/// **Пустое имя не склеивается в « cavab gözlənilir» с дырой в начале.**
/// Оно означает, что имя не доехало, — и это отдельная поломка, которую
/// эта функция не лечит и лечить не должна; её дело в том, чтобы не
/// показать человеку обрубок. Без имени говорится просто «ждём ответа»:
/// фраза остаётся правдой, просто менее точной.
String azAwaitingAnswerFrom(String name) {
  final trimmed = name.trim();
  if (trimmed.isEmpty) return 'Cavab gözlənilir';
  return '${azFrom(trimmed)} cavab gözlənilir';
}
