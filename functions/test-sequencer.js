const Sequencer = require("@jest/test-sequencer").default;

// ПОРЯДОК НАБОРОВ ПЕРЕМЕШИВАЕТСЯ КАЖДЫЙ ПРОГОН, И ЭТО СТОРОЖ, А НЕ ПРИЧУДА
// (долг N192).
//
// ЧТО СЛУЧИЛОСЬ 01.09. Зелёный прогон держался на удачной очереди: 23 набора
// были зелёными, а 24-й — заведомо безвредный, про VoIP-токены — сделал их
// красными. Падал при этом не случайный вердикт, а проверка ЗАПРЕТА доступа:
// функция разрешила копирование чужого закрытого статуса. Починен был один
// файл (барьер `settle()` после каждой записи), а проверки «прогон не зависит
// от порядка наборов» в проекте не существовало вовсе.
//
// ПОЧЕМУ ЖДАТЬ БЫЛО НЕЛЬЗЯ, И ЭТО НАШЛОСЬ ПОПУТНО 03.09: **jest по умолчанию
// сортирует наборы ПО РАЗМЕРУ ФАЙЛА, крупные первыми.** Значит порядок
// меняется сам от любой правки — дописал десяток строк, и набор переехал.
// Сегодняшняя связка «19-й роняет 10-й» может распасться или возникнуть
// заново МОЛЧА, и зелёный прогон не наследуется завтрашним даже тогда, когда
// в логике не тронуто ничего.
//
// ПОЧЕМУ ПЕРЕМЕШИВАНИЕ ВМЕСТО ВТОРОГО ПРОГОНА (решение владельца 03.09).
// Второй прогон в другом порядке стоит +100 % времени (замер 03.09: `npm test`
// — **284 с** целиком, из них jest 258,2 с, 443 вердикта, 25 наборов) и
// проверяет ОДНУ лишнюю перестановку из 25! возможных, то есть ловит не
// «зависимость от порядка», а зависимость от этих двух порядков.
// Перемешивание стоит **≈0 %** и проверяет НОВУЮ перестановку каждый прогон:
// при 34 коммитах в `functions/src` за 30 дней это три десятка порядков в
// месяц вместо двух. Ловит строго больше, стоит строго меньше.
//
// ЧЕМ ПЛАТИМ И ЧЕМ ЭТО ЛЕЧИТСЯ: воспроизводимостью. Красный прогон надо уметь
// повторить, поэтому **зерно печатается ВСЕГДА**, а не при отказе, и
// повторяется командой:
//
//     JEST_SHUFFLE_SEED=<зерно> npm test
//
// Печать зерна при отказе была бы дырой ровно того же вида, что и всё
// остальное в этом проекте: сообщение об отказе печатает jest, а зерно знает
// только этот файл, и связать их некому.
//
// ЧЕГО ЭТОТ ПОРЯДОК НЕ ЛОВИТ (границы пишутся вместе со сторожем):
//   - он тасует НАБОРЫ, а не вердикты внутри набора. На это у jest есть свой
//     ключ `--randomize`, и он здесь НЕ включён: зависимость вердиктов друг
//     от друга внутри файла — отдельная болезнь и отдельное решение;
//   - зависимость, проявляющаяся только на одной перестановке из 25!, может
//     не выпасть годами. Перемешивание уменьшает срок ожидания, а не
//     доказывает отсутствие;
//   - при `--runInBand` наборы идут по одному. Без него jest разложил бы их
//     по процессам, и порядок перестал бы значить то, что значит здесь.

/// Зерно: из окружения, если задано, иначе новое на каждый прогон.
///
/// `>>> 0` приводит к 32 битам без знака — тому же виду, в каком зерно
/// печатается и в каком его вернут обратно.
const envSeed = process.env.JEST_SHUFFLE_SEED;
const seed =
  envSeed !== undefined && envSeed !== "" && Number.isFinite(Number(envSeed))
    ? Number(envSeed) >>> 0
    : Date.now() >>> 0;

/// Свой генератор, а не `Math.random`, ровно ради одного свойства: по зерну
/// порядок восстанавливается байт в байт. `Math.random` зерна не принимает,
/// и с ним красный прогон повторить было бы нечем.
function mulberry32(a) {
  let t = a >>> 0;
  return function () {
    t = (t + 0x6d2b79f5) >>> 0;
    let r = Math.imul(t ^ (t >>> 15), 1 | t);
    r = (r + Math.imul(r ^ (r >>> 7), 61 | r)) ^ r;
    return ((r ^ (r >>> 14)) >>> 0) / 4294967296;
  };
}

/// Тасование Фишера — Йетса по зерну. Вынесено отдельно и экспортировано
/// НАРОЧНО: сторож `test/shuffle-sequencer.test.ts` проверяет именно эту
/// функцию, а не свою копию приёма — иначе он проверял бы копию инструмента,
/// а не инструмент.
function shuffleWithSeed(items, seedValue) {
  const rand = mulberry32(seedValue);
  const out = items.slice();
  for (let i = out.length - 1; i > 0; i -= 1) {
    const j = Math.floor(rand() * (i + 1));
    const tmp = out[i];
    out[i] = out[j];
    out[j] = tmp;
  }
  return out;
}

// ПЕЧАТЬ ПРИ ЗАГРУЗКЕ, А НЕ ВНУТРИ `sort`: `sort` зовётся один раз, но это
// подробность jest, на которую опираться незачем.
//
// В `stderr`, потому что `stdout` у нас занят отчётом jest, а зерно нужно
// видеть и тогда, когда отчёт увели в файл.
//
// УСЛОВИЕ `typeof jest === "undefined"` — НЕ ПЕРЕСТРАХОВКА, А ПОЧИНКА
// НАБЛЮДЁННОГО. Без него зерно печаталось ДВАЖДЫ и РАЗНОЕ: один раз здесь, в
// хозяйском процессе, второй — когда этот же файл загружает сторож
// `test/shuffle-sequencer.test.ts`, а у тестового окружения свой реестр
// модулей и своё `Date.now()`. Два разных зерна в выводе делают команду
// повтора двусмысленной, то есть отменяют ровно то свойство, ради которого
// зерно и печатается. Глобальное `jest` существует только внутри тестового
// окружения — по нему хозяйский процесс и отличается от тестового.
if (typeof jest === "undefined") {
  process.stderr.write(
    `[jest] порядок наборов перемешан, зерно ${seed}. ` +
      `Повторить тот же порядок: JEST_SHUFFLE_SEED=${seed} npm test\n`
  );
}

class ShuffleSequencer extends Sequencer {
  sort(tests) {
    return shuffleWithSeed(tests, seed);
  }
}

module.exports = ShuffleSequencer;
module.exports.shuffleWithSeed = shuffleWithSeed;
module.exports.seed = seed;
