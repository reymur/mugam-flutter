import { logger } from "firebase-functions";

// ГОЛОС УБРАННОГО ИЗ СОСТАВА — N244, 17.09.
//
// Крестик владельца убирает человека из `musicians` и той же пачкой удаляет
// документ его причины `personalEvents/{id}/leaveNotes/{uid}`. Файл голоса
// `event_leave_notes/{id}/{uid}` клиент не удаляет и удалить не может:
// `storage.rules` пускает запись в эту папку только автору, а крестик нажимает
// владелец. Открывать владельцу запись в чужую папку голоса ради уборки нельзя
// (решение владельца 17.09), поэтому убирает сервер.
//
// Замер 17.09 до починки: после крестика документ причины ушёл, файл остался —
// с живым токеном и без документа, который бы его объяснял.
//
// БАКЕТ ПРИХОДИТ ПАРАМЕТРОМ, А НЕ БЕРЁТСЯ ЗДЕСЬ, по двум причинам:
//   • имя бакета обязано быть явным — `bucket()` без имени в тестовом проекте
//     указывает мимо (случай 16.09 с уборкой вечера), и вызывающий пишет его
//     сам, как соседи;
//   • различение «файла нет» от «удалить не вышло» проверяется без эмулятора,
//     подставной корзиной, отвечающей нужным кодом.

/** То, что нужно от корзины, — и ничего больше. */
export interface VoiceBucket {
  file(path: string): { delete(): Promise<unknown> };
}

/** Путь файла голоса причины. Тот же, что у клиента (`leaveNoteVoicePath`). */
export function leaveNoteVoiceObjectPath(eventId: string, uid: string): string {
  return `event_leave_notes/${eventId}/${uid}`;
}

/**
 * Удаляет файлы голоса причин у тех, кого убрали из состава.
 *
 * **УБРАННЫЙ МОЖЕТ НЕ ИМЕТЬ ПРИЧИНЫ — и это обычный случай, а не сбой.**
 * Тогда файла нет, хранилище отвечает на удаление кодом **404**, и это молча
 * пропускается. Спрашивать «есть ли файл» заранее незачем: это второй запрос
 * и гонка между ним и удалением, а ответ 404 и есть тот же ответ.
 *
 * **ВСЁ, ЧТО НЕ 404, — В ЖУРНАЛ, И ТОЛЬКО В ЖУРНАЛ.** Уборка и извещение —
 * разные дела (I58): сбой уборки не повод не известить состав, поэтому наружу
 * ничего не выбрасывается. Файл, который не удалился, остаётся тем же, чем был
 * до починки, — сиротой, а не молчаливой потерей.
 *
 * Повторная доставка того же события даст 404 на уже удалённом — молча.
 */
export async function removeLeaveNoteVoices(
  bucket: VoiceBucket,
  eventId: string,
  uids: string[],
): Promise<void> {
  await Promise.all(uids.map(async (uid) => {
    const path = leaveNoteVoiceObjectPath(eventId, uid);
    try {
      await bucket.file(path).delete();
    } catch (e) {
      if ((e as { code?: unknown })?.code === 404) return;
      logger.error("[member-removed] голос причины не удалён", {
        eventId,
        uid,
        error: String(e),
      });
    }
  }));
}
