#!/bin/bash
# Установка на телефон не начинается, пока подпись бундла не сошлась с его
# содержимым.
#
# Случай 09.08, из которого сторож вырос. `flutter build ios --release`
# сказал «✓ Built build/ios/iphoneos/Runner.app» и вернул 0, а проверка
# того же бундла дала:
#   codesign --verify --deep --strict → a sealed resource is missing or invalid
# Инкрементальная сборка обновила `App.framework/App` (новый код Dart), а
# печать бундла осталась от позавчерашней сборки. То есть «✓ Built» и код
# возврата 0 НЕ РАЗЛИЧАЮТ годный бундл и разошедшийся с подписью — ровно
# тот же класс, что «строка Flutter run key commands доказывает готовность
# трубки» (конспект, раздел 5б).
#
# Почему сторож, а не строчка в порядке сборки. Порядок читают перед
# первой установкой и не перечитывают перед десятой; проверка, которую
# надо помнить, — это память, а не защита. Момент, когда цена ошибки
# максимальна, ровно один — установка, и сторож стоит именно на нём.
#
# ЧЕГО ЭТОТ СТОРОЖ НЕ ЛОВИТ — здесь, а не выяснится потом:
#   1. установку, сделанную МИМО этого инструмента: из Xcode.app, из
#      другого терминала, с другой машины;
#   2. СТАРЫЙ, но целый бундл. Он проверяет, что печать сошлась с
#      содержимым, и молчит о том, ТА ЛИ ЭТО сборка. «Подпись сошлась» не
#      значит «внутри сегодняшний код»;
#   3. годность профиля и прав (entitlements) — это другая проверка,
#      `codesign --verify` о них не судит;
#   4. команду, из которой путь к `.app` не вычленяется: если разбор ниже
#      пути не нашёл, сторож молчит и пропускает.
# Второй пункт важнее прочих: он и есть та ошибка, ради которой сторож
# написан, только с другого конца — признак, который называют
# доказательством, обязан быть проверен и на то, чего он НЕ различает.

payload=$(cat)
c=$(printf '%s' "$payload" | /usr/bin/python3 -c 'import json,sys; print(json.load(sys.stdin).get("tool_input",{}).get("command",""))' 2>/dev/null)
[ -z "$c" ] && exit 0

# Ловится ВЫЗОВ установки, а не упоминание: этот файл сам про неё пишет, и
# сторож, сравнивающий текст целиком, отказал бы в записи собственного
# объяснения (I12 — уже случалось с запретом на разрушающий git).
installs=0
while IFS= read -r seg; do
  seg="${seg#"${seg%%[![:space:]]*}"}"
  case "$seg" in
    xcrun\ devicectl\ device\ install*|devicectl\ device\ install*) installs=1 ;;
  esac
done <<< "$(printf '%s' "$c" | tr '\n;|&' '\n\n\n\n')"
[ "$installs" -eq 0 ] && exit 0

# Путь к бундлу — первое слово, оканчивающееся на .app
bundle=$(printf '%s' "$c" | tr ' \n' '\n\n' | grep -E '\.app$' | head -1)
[ -z "$bundle" ] && exit 0
[ -d "$bundle" ] || exit 0

out=$(codesign --verify --deep --strict "$bundle" 2>&1)
rc=$?
if [ "$rc" -ne 0 ]; then
  reason="Подпись бундла не сошлась с содержимым: $out

Это значит, что сборка обновила часть бундла (обычно App.framework с кодом Dart), а печать осталась от предыдущей. Установка либо провалится, либо поставит НЕ ТО, и отличить это на телефоне будет нечем: приложение выглядит установленным одинаково.

Лечится пересборкой начисто по выходным каталогам релиза:
  rm -rf build/ios/iphoneos build/ios/Release-iphoneos
  flutter build ios --release
  codesign --verify --deep --strict build/ios/iphoneos/Runner.app

Проверку запускать ОТДЕЛЬНОЙ командой, без трубы: код возврата у конвейера берётся у последней команды, и 09.08 codesign | head показал 0 при отказе."
  /usr/bin/python3 - "$reason" <<'PY'
import json, sys
print(json.dumps({"hookSpecificOutput": {
    "hookEventName": "PreToolUse",
    "permissionDecision": "deny",
    "permissionDecisionReason": sys.argv[1],
}}))
PY
  exit 0
fi

exit 0
