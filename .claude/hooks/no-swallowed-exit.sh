#!/bin/bash
# Проверка, чей результат съеден конвейером, не имеет права решать судьбу
# коммита.
#
# Случай 07.08, из которого сторож вырос: команда была
#   flutter test 2>&1 | tail -2 && git commit … && git push
# Код возврата в конвейере берётся у ПОСЛЕДНЕЙ команды, то есть у `tail`,
# а он успешен всегда. Тест упал, `&&` этого не заметил, коммит с красной
# проверкой ушёл в main.
#
# Ловится узкий и точный случай: в одной команде есть и конвейер с
# проверкой, и `&&` перед git commit/push. Не «подозрительно похоже», а
# ровно та ошибка.
#
# ЧЕГО ЭТОТ СТОРОЖ НЕ ЛОВИТ — сказано здесь, чтобы на него не полагались
# шире, чем он умеет (I9: сторож, который молчит, неотличим от сторожа,
# которому нечего сказать):
#   1. проверку и коммит, разнесённые по ДВУМ вызовам инструмента, — во
#      втором вызове о первом ничего не известно;
#   2. чтение результата глазами: `flutter test | grep -c fail` вернёт 0
#      и при упавшем тесте, и при несобравшемся проекте — тут съеден не
#      код возврата, а смысл;
#   3. любую проверку, имени которой нет в списке ниже.
# Первое лечится только правилом в CLAUDE.md, второе — вопросом «а
# сколько она сейчас нашла?» (I13).

payload=$(cat)
c=$(printf '%s' "$payload" | /usr/bin/python3 -c 'import json,sys; print(json.load(sys.stdin).get("tool_input",{}).get("command",""))' 2>/dev/null)
[ -z "$c" ] && exit 0

# Есть ли в команде git commit или git push как ВЫЗОВ (а не упоминание).
mutates=0
while IFS= read -r seg; do
  seg="${seg#"${seg%%[![:space:]]*}"}"
  case "$seg" in
    git\ commit*|git\ push*) mutates=1 ;;
  esac
done <<< "$(printf '%s' "$c" | tr '\n;|&' '\n\n\n\n')"
[ "$mutates" -eq 0 ] && exit 0

# Есть ли конвейер, начинающийся с проверки: `flutter test | …`.
#
# Перенаправления снимаются ПЕРЕД разбором: первая редакция этого сторожа
# пропустила ровно тот случай, ради которого писалась, — `2>&1` содержит
# `&`, а промежуток до трубы искался как «без & ; |». Сторож, ищущий не
# то, молчит так же, как сторож, которому нечего сказать (I13), и поймать
# это удалось только прогоном по настоящей строке.
clean=$(printf '%s' "$c" | sed -E 's/[0-9]?>&[0-9]//g; s/[0-9]?>[[:space:]]*\/dev\/null//g')
if printf '%s' "$clean" | grep -qE '(flutter[[:space:]]+(test|analyze)|dart[[:space:]]+test|npm[[:space:]]+(run[[:space:]]+)?test|npx[[:space:]]+jest|jest)[^|;&]*\|'; then
  cat <<'EOF'
{"hookSpecificOutput":{"hookEventName":"PreToolUse","permissionDecision":"deny","permissionDecisionReason":"Проверка уходит в конвейер, а следом в той же команде стоит git commit/push. Код возврата конвейера — от последней команды (tail/grep/head), а не от теста: упавшая проверка не остановит коммит. Так 07.08 в main ушёл коммит с красным тестом.\n\nЗапускай проверку ОТДЕЛЬНЫМ вызовом и читай её результат сам, а коммить следующей командой. Если конвейер нужен для чтения вывода — добавь `set -o pipefail` перед ним."}}
EOF
  exit 0
fi

exit 0
